use std::fs;
use std::path::PathBuf;

use gunbc_toolsgen::{build_toolsgen_dag, ToolsgenConfig};
use gunbc_toolsgen::ops::extract_hash;

#[test]
fn generates_cargo_wrapper() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let tools_dir = tmp.path().join("tools");
    fs::create_dir_all(&tools_dir).expect("create tools dir");

    let output_path = PathBuf::from("tools/cargo_wrapper.c");
    let config = ToolsgenConfig {
        workspace_path: tmp.path().to_string_lossy().into_owned(),
        output_path: output_path.to_string_lossy().into_owned(),
        force: true,
    };

    let dag = build_toolsgen_dag(&config, false);
    let log = gunbc_exec::execute(&dag).expect("execute toolsgen");
    assert!(!log.entries.is_empty());

    let file_path = tmp.path().join("tools/cargo_wrapper.c");
    let content = fs::read_to_string(&file_path).expect("read generated file");
    assert!(content.contains("Generated by gunbc-toolsgen"));
    assert!(extract_hash(&content).is_some());
}
