#!/bin/bash
# AT THE REGENERATED (CONVERGED) SEED: the two measurements that decide whether the regenerated
# mirrors can be shipped, plus the fmt question the pre-commit gate will ask.
# The converged mirrors arrive as keep/converged/*.rs, produced by the previous dispatch (round 2
# rc=0, ZERO hard diagnostics) and shipped back as a base64 tar.
#   [A] the cross_coproduct suite: 3 rows must be RED on the shipped seed and my new controls must
#       behave as labelled (fold_replaces_... = the RED-before control; fold_keeps_... = lock).
#   [B] the self-host rebind count: the 0-bound-as evidence the parent asked for. Expect 0 refusals
#       for the pairs my relation admits; the rows owned by X1/X2/the unattributed classes may
#       remain, and are reported by identity, not by count alone.
#   [C] cargo fmt --check on the mirrors: the pre-commit gate runs it, so a failure here would mean
#       the regenerated bytes cannot be committed as-is.
# NO git checkout / git clean. Restores by cp at the end.
set -uo pipefail
export PATH="/opt/cargo/bin:/usr/local/bin:/usr/local/sbin:$PATH"
cd .
SEED=src/v1/stage0/src
MIRRORS="v1_compiler_infer.rs v1_compiler_infer_types.rs v1_compiler_emit_rust.rs v1_tests_claim_generic_identity_census.rs"
for f in $MIRRORS; do cp "keep/converged/$f" "$SEED/$f"; done
echo "installed converged: $(for f in $MIRRORS; do echo -n "$(basename $f)=$(sha256sum $SEED/$f|cut -c1-12) "; done)"
echo "seed carries: relation=$(grep -c generic_types_unify $SEED/v1_compiler_infer.rs) formalGuard=$(grep -c binding_is_unsettled_formal_annotation $SEED/v1_compiler_infer.rs) tvLeaf=$(grep -c binding_has_type_variable_leaf $SEED/v1_compiler_infer.rs) fold=$(grep -o UnifyGenericsAcc $SEED/v1_compiler_infer.rs | wc -l)"
echo "########## [C] fmt on the mirrors (pre-commit gate) ##########"
cargo fmt --all --check 2>&1 | head -12 | cut -c1-160
echo "fmt rc=$? (0 = committable as-is)"
echo "########## [A] SUITE at the converged seed ##########"
cargo build --release -p v1-compiler --bin gunbc 2>&1 | grep -E "^error|error\[|Finished" | tail -2
cargo test -p v1-compiler-tests --lib cross_coproduct_generic_locate 2>&1 | grep -E "^test |test result|^error" | head -36
echo "########## [B] SELF-HOST at the converged seed ##########"
timeout 2400 target/release/gunbc test //gunbc/instruments:self-host > /tmp/sh4.log 2>&1
echo "self-host rc=$?"
echo "rebind refusals=$(grep -ac 'bound as' /tmp/sh4.log)  hard diagnostics=$(grep -acE "^type mismatch|^call shape|arm decides" /tmp/sh4.log)"
echo "--- refusal rows, by identity (first 20):"
grep -a "bound as" /tmp/sh4.log | sed 's/.*bound as//' | sort | uniq -c | sort -rn | head -20 | cut -c1-170
echo "--- compile failures in the emitted closure (the pre-fold lane's signature):"
grep -aE "^error(\[|:)" /tmp/sh4.log | head -6 | cut -c1-190
cp /tmp/sh4.log selfhost_converged.log
echo "=== BEGIN-TAR ==="; ( cd . && tar -c selfhost_converged.log 2>/dev/null | base64 -w0 ); echo; echo "=== END-TAR ==="
for f in $MIRRORS; do cp "keep/main_$f" "$SEED/$f"; done
echo "restored: $(for f in $MIRRORS; do echo -n "$(basename $f)=$(sha256sum $SEED/$f|cut -c1-10) "; done)"
echo CONVERGED_RUN_DONE
