//! Mock specification for the Buck2 tool.
//!
//! This file declares:
//! - What mock values boundary nodes provide
//! - What input constraints upstream must satisfy
//! - Resource simulations for file system operations

use gunbc_ir::Value;
use gunbc_test::{InputConstraint, MockSpec};

/// Mock specification for the buck2 graph.
///
/// # Boundary Mocks
///
/// The `execute_transport` node is the boundary (world write).
/// It outputs:
/// - `response`: Transport response
/// - `written_path`: Path where BUCK file was written
/// - `content`: The generated BUCK file content
///
/// # Input Expectations
///
/// - `cargo_toml_path`: Path to Cargo.toml (defaults to "Cargo.toml")
/// - `output_path`: Path for BUCK file output (defaults to "BUCK")
pub fn buck2_mock_spec() -> MockSpec {
    MockSpec::new("buck2")
        // Boundary: execute_transport outputs
        .boundary(
            "execute_transport",
            "written_path",
            Value::Str("BUCK".into()),
        )
        .boundary(
            "execute_transport",
            "content",
            Value::Str(mock_buck_content()),
        )
        .boundary(
            "execute_transport",
            "response",
            Value::Json(serde_json::json!({
                "status": "ok",
                "bytes_written": 512
            })),
        )
        // Input expectations
        .expects_input("cargo_toml_path", InputConstraint::NonEmpty)
        .expects_input("output_path", InputConstraint::Any)
        // Resource: file locks
        .resource_lock("fs:Cargo.toml")  // Read lock
        .resource_lock("fs:BUCK")        // Write lock
}

/// Mock spec for testing custom output path.
pub fn buck2_mock_spec_custom_output(path: &str) -> MockSpec {
    MockSpec::new("buck2")
        .boundary("execute_transport", "written_path", Value::Str(path.into()))
        .boundary("execute_transport", "content", Value::Str(mock_buck_content()))
        .boundary(
            "execute_transport",
            "response",
            Value::Json(serde_json::json!({ "status": "ok" })),
        )
        .expects_input("cargo_toml_path", InputConstraint::NonEmpty)
        .expects_input("output_path", InputConstraint::Any)
        .resource_lock("fs:Cargo.toml")
        .resource_lock(format!("fs:{}", path))
}

/// Mock spec for testing missing Cargo.toml.
pub fn buck2_mock_spec_cargo_missing() -> MockSpec {
    MockSpec::new("buck2")
        .boundary("execute_transport", "written_path", Value::Str("".into()))
        .boundary("execute_transport", "content", Value::Str("".into()))
        .boundary(
            "execute_transport",
            "response",
            Value::Json(serde_json::json!({
                "status": "error",
                "error": "Cargo.toml not found"
            })),
        )
        .expects_input("cargo_toml_path", InputConstraint::NonEmpty)
        .expects_input("output_path", InputConstraint::Any)
        .resource_lock_fails("fs:Cargo.toml", "File not found: Cargo.toml")
}

/// Mock spec for testing BUCK write failure.
pub fn buck2_mock_spec_write_fails() -> MockSpec {
    MockSpec::new("buck2")
        .boundary("execute_transport", "written_path", Value::Str("".into()))
        .boundary("execute_transport", "content", Value::Str("".into()))
        .boundary(
            "execute_transport",
            "response",
            Value::Json(serde_json::json!({
                "status": "error",
                "error": "Permission denied"
            })),
        )
        .expects_input("cargo_toml_path", InputConstraint::NonEmpty)
        .expects_input("output_path", InputConstraint::Any)
        .resource_lock("fs:Cargo.toml")
        .resource_lock_fails("fs:BUCK", "Permission denied: BUCK is read-only")
}

fn mock_buck_content() -> String {
    r#"# Generated by gunbc-buck2
# DO NOT EDIT

load("@prelude//rust:rust.bzl", "rust_library", "rust_binary")

rust_library(
    name = "gunbc-ir",
    srcs = glob(["core/ir/src/**/*.rs"]),
    deps = [],
)

rust_binary(
    name = "gunbc-gist",
    srcs = glob(["lib/tools/gist/src/**/*.rs"]),
    deps = [":gunbc-ir"],
)
"#
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_mock_spec_has_boundary() {
        let spec = buck2_mock_spec();
        assert!(spec.get_boundary_mock("execute_transport", "written_path").is_some());
        assert!(spec.get_boundary_mock("execute_transport", "content").is_some());
        assert!(spec.get_boundary_mock("execute_transport", "response").is_some());
    }

    #[test]
    fn test_mock_spec_path_default() {
        let spec = buck2_mock_spec();
        let path = spec.get_boundary_mock("execute_transport", "written_path").unwrap();
        assert!(matches!(path, Value::Str(s) if s == "BUCK"));
    }

    #[test]
    fn test_custom_output_spec() {
        let spec = buck2_mock_spec_custom_output("build/BUCK");
        let path = spec.get_boundary_mock("execute_transport", "written_path").unwrap();
        assert!(matches!(path, Value::Str(s) if s == "build/BUCK"));
    }

    #[test]
    fn test_file_locks_present() {
        let spec = buck2_mock_spec();
        assert!(spec.get_resource("fs:Cargo.toml").is_some());
        assert!(spec.get_resource("fs:BUCK").is_some());
    }

    #[test]
    fn test_cargo_missing_spec() {
        let spec = buck2_mock_spec_cargo_missing();
        let cargo = spec.get_resource("fs:Cargo.toml").unwrap();
        let result = cargo.acquire();
        assert!(matches!(result, gunbc_test::ResourceAcquireResult::Failed(_)));
    }

    #[test]
    fn test_write_fails_spec() {
        let spec = buck2_mock_spec_write_fails();
        let cargo = spec.get_resource("fs:Cargo.toml").unwrap();
        let buck = spec.get_resource("fs:BUCK").unwrap();
        
        assert!(matches!(cargo.acquire(), gunbc_test::ResourceAcquireResult::Acquired));
        assert!(matches!(buck.acquire(), gunbc_test::ResourceAcquireResult::Failed(_)));
    }

    #[test]
    fn test_content_has_rust_targets() {
        let spec = buck2_mock_spec();
        let content = spec.get_boundary_mock("execute_transport", "content").unwrap();
        if let Value::Str(s) = content {
            assert!(s.contains("rust_library"));
            assert!(s.contains("rust_binary"));
        } else {
            panic!("Expected string content");
        }
    }
}
