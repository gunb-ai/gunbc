//! Makefile rendering.

use crate::registry::{EntrypointParam, ExtraTarget, ToolInfo, ToolRegistry};

/// Render a complete Makefile from the tool registry.
pub fn render_makefile(registry: &ToolRegistry) -> String {
    let mut output = String::new();

    // Header
    output.push_str("# Generated by gunbc-makegen\n");
    output.push_str("# DO NOT EDIT - regenerate with: make makegen\n\n");

    // Default goal
    output.push_str(".DEFAULT_GOAL := help\n\n");

    // Phony targets
    output.push_str(".PHONY: help");
    for tool in &registry.tools {
        output.push_str(&format!(" {} {}-dry", tool.short_name, tool.short_name));
        for extra in &tool.extra_targets {
            output.push_str(&format!(" {}-{}", tool.short_name, extra.suffix));
        }
    }
    output.push_str("\n\n");

    // Help target
    output.push_str("help:\n");
    output.push_str("\t@echo \"gunbc tools - generated Makefile\"\n");
    output.push_str("\t@echo \"\"\n");
    output.push_str("\t@echo \"Available targets:\"\n");
    for tool in &registry.tools {
        let params = render_help_params(&tool.entrypoints);
        output.push_str(&format!(
            "\t@echo \"  {} {}  - {}\"\n",
            tool.short_name, params, tool.description
        ));
        for extra in &tool.extra_targets {
            output.push_str(&format!(
                "\t@echo \"  {}-{}  - {}\"\n",
                tool.short_name, extra.suffix, extra.description
            ));
        }
    }
    output.push_str("\t@echo \"\"\n");
    output.push_str("\t@echo \"Add -dry suffix for dry-run (e.g., make gist-dry)\"\n\n");

    // Tool targets
    for tool in &registry.tools {
        output.push_str(&render_tool_target(tool));
        output.push_str(&render_dry_run_target(tool));
        for extra in &tool.extra_targets {
            output.push_str(&render_extra_target(tool, extra));
        }
    }

    output
}

/// Render help text for parameters.
fn render_help_params(params: &[EntrypointParam]) -> String {
    params
        .iter()
        .map(|p| {
            if let Some(ref default) = p.default {
                format!("[{}={}]", p.make_var, default)
            } else {
                format!("[{}=...]", p.make_var)
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// Render a tool target.
fn render_tool_target(tool: &ToolInfo) -> String {
    let mut output = String::new();

    // Comment with entrypoint info
    let port_list = tool
        .entrypoints
        .iter()
        .map(|p| format!("{} ({})", p.port_name, p.type_hint))
        .collect::<Vec<_>>()
        .join(", ");
    output.push_str(&format!("# {} entrypoints: {}\n", tool.crate_name, port_list));

    // Target
    output.push_str(&format!("{}:\n", tool.short_name));
    output.push_str(&format!(
        "\t@cargo run -p {} --{}",
        tool.crate_name,
        render_cli_args(&tool.entrypoints)
    ));
    output.push_str("\n\n");

    output
}

/// Render a dry-run target.
fn render_dry_run_target(tool: &ToolInfo) -> String {
    let mut output = String::new();

    output.push_str(&format!("{}-dry:\n", tool.short_name));
    output.push_str(&format!(
        "\t@cargo run -p {} -- --dry-run{}",
        tool.crate_name,
        render_cli_args(&tool.entrypoints)
    ));
    output.push_str("\n\n");

    output
}

/// Render an extra composite target.
fn render_extra_target(tool: &ToolInfo, extra: &ExtraTarget) -> String {
    let mut output = String::new();

    output.push_str(&format!(
        "# {}-{}: {}\n",
        tool.short_name, extra.suffix, extra.description
    ));
    output.push_str(&format!("{}-{}: {}\n", tool.short_name, extra.suffix, tool.short_name));

    // Add post commands
    for cmd in &extra.post_commands {
        output.push_str(&format!("\t{}\n", cmd));
    }
    output.push_str("\n");

    output
}

/// Render CLI arguments from entrypoint parameters.
fn render_cli_args(params: &[EntrypointParam]) -> String {
    if params.is_empty() {
        return String::new();
    }

    let args: Vec<String> = params
        .iter()
        .map(|p| {
            // $(if $(VAR),--flag $(VAR))
            format!(" $(if $({}),{} $({}))", p.make_var, p.cli_flag, p.make_var)
        })
        .collect();

    args.join("")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_render_makefile_has_header() {
        let registry = ToolRegistry::default_registry();
        let makefile = render_makefile(&registry);

        assert!(makefile.contains("Generated by gunbc-makegen"));
        assert!(makefile.contains(".PHONY:"));
        assert!(makefile.contains("help:"));
    }

    #[test]
    fn test_render_makefile_has_targets() {
        let registry = ToolRegistry::default_registry();
        let makefile = render_makefile(&registry);

        assert!(makefile.contains("gist:"));
        assert!(makefile.contains("gist-dry:"));
        assert!(makefile.contains("buck2:"));
        assert!(makefile.contains("buck2-dry:"));
    }

    #[test]
    fn test_render_makefile_has_cli_args() {
        let registry = ToolRegistry::default_registry();
        let makefile = render_makefile(&registry);

        // Should have conditional variable expansion
        assert!(makefile.contains("$(if $(REPO)"));
        assert!(makefile.contains("--repo"));
    }
}
