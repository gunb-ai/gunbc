//! Bootstrap operations.
//!
//! This module contains pure bootstrap-specific operations.
//! File writing is handled via the transport pattern:
//! - `PrepareFileWriteOp` (primitive) creates the TransportRequest
//! - `TransportOps::Execute` (boundary) performs actual I/O
//!
//! All I/O (including workspace scanning) goes through the transport layer.

use gunbc_exec::{ExecError, Executable};
use gunbc_ir::transport::{FileRequest, ShellRequest, TransportRequest, TransportResponse};
use gunbc_ir::Value;
use gunbc_lib_transport::execute_transport;
use std::collections::HashMap;

/// Operations for the bootstrap tool.
///
/// These operations use the transport layer for all I/O.
/// File writing is handled via `PrepareFileWriteOp` + `TransportOps::Execute`.
#[derive(Debug, Clone)]
pub enum BootstrapOp {
    /// Scan workspace for crates (uses transport layer for directory listing)
    ScanWorkspace,
    /// Generate Makefile content (pure - string generation)
    GenerateMakefile,
    /// Generate .gitignore content (pure - string generation)
    GenerateGitignore,
}

impl Executable for BootstrapOp {
    fn execute(&self, inputs: HashMap<String, Value>) -> Result<HashMap<String, Value>, ExecError> {
        match self {
            BootstrapOp::ScanWorkspace => execute_scan_workspace(inputs),
            BootstrapOp::GenerateMakefile => execute_generate_makefile(inputs),
            BootstrapOp::GenerateGitignore => execute_generate_gitignore(inputs),
        }
    }
}

/// Scan workspace for crate information using transport layer.
fn execute_scan_workspace(_inputs: HashMap<String, Value>) -> Result<HashMap<String, Value>, ExecError> {
    // Check if crates directory exists using transport
    let exists_request = TransportRequest::File(FileRequest::exists("crates"));
    let crates_exists = match execute_transport(&exists_request) {
        Ok(TransportResponse::File(resp)) => resp.exists.unwrap_or(false),
        _ => false,
    };

    let mut crate_names = Vec::new();

    if crates_exists {
        // List directories in crates/ using find via transport
        let list_request = TransportRequest::Shell(ShellRequest {
            command: "find".to_string(),
            args: vec![
                "crates".to_string(),
                "-maxdepth".to_string(),
                "1".to_string(),
                "-mindepth".to_string(),
                "1".to_string(),
                "-type".to_string(),
                "d".to_string(),
            ],
            cwd: None,
            env: HashMap::new(),
            stdin: None,
        });

        if let Ok(TransportResponse::Shell(shell)) = execute_transport(&list_request) {
            if shell.success() {
                for line in shell.stdout.lines() {
                    let line = line.trim();
                    if !line.is_empty() {
                        // Extract crate name from path like "crates/foo"
                        if let Some(name) = line.strip_prefix("crates/") {
                            if !name.is_empty() && !name.contains('/') {
                                crate_names.push(name.to_string());
                            }
                        }
                    }
                }
            }
        }
    }

    crate_names.sort();

    let mut out = HashMap::new();
    out.insert("crate_count".to_string(), Value::Int(crate_names.len() as i64));
    out.insert("crate_names".to_string(), Value::StrList(crate_names));
    Ok(out)
}

/// Generate Makefile content.
fn execute_generate_makefile(_inputs: HashMap<String, Value>) -> Result<HashMap<String, Value>, ExecError> {
    let makefile = r#"# Generated by gunbc-bootstrap
# Regenerate with: make bootstrap

.DEFAULT_GOAL := help

.PHONY: help build test lint ci gist buck2 makegen deps bootstrap

help:
	@echo "gunbc - DAG-based code generation framework"
	@echo ""
	@echo "Development:"
	@echo "  build       Build all targets"
	@echo "  test        Run all tests"
	@echo "  lint        Run clippy"
	@echo "  ci          Run full CI pipeline"
	@echo ""
	@echo "Tools:"
	@echo "  gist        Create GitHub gist from code"
	@echo "  buck2       Generate BUCK file"
	@echo "  makegen     Regenerate this Makefile"
	@echo "  deps        Install/check dependencies"
	@echo "  bootstrap   Regenerate all build infrastructure"

build:
	cargo build --all-targets

test:
	cargo test

lint:
	cargo clippy --all-targets -- -D warnings

ci:
	cargo run -p gunbc-ci -- run

gist:
	cargo run -p gunbc-gist -- $(if $(REPO),--repo $(REPO)) $(if $(EXT),-e $(EXT))

gist-dry:
	cargo run -p gunbc-gist -- --dry-run $(if $(REPO),--repo $(REPO))

buck2:
	cargo run -p gunbc-buck2 -- $(if $(INPUT),--input $(INPUT))

buck2-dry:
	cargo run -p gunbc-buck2 -- --dry-run

makegen:
	cargo run -p gunbc-makegen

makegen-dry:
	cargo run -p gunbc-makegen -- --dry-run

deps:
	cargo run -p gunbc-deps -- install

deps-list:
	cargo run -p gunbc-deps -- --list

bootstrap:
	cargo run -p gunbc-bootstrap

bootstrap-dry:
	cargo run -p gunbc-bootstrap -- --dry-run
"#;

    let mut out = HashMap::new();
    out.insert("makefile_content".to_string(), Value::Str(makefile.to_string()));
    Ok(out)
}

/// Generate .gitignore content.
fn execute_generate_gitignore(_inputs: HashMap<String, Value>) -> Result<HashMap<String, Value>, ExecError> {
    let gitignore = r#"# Generated by gunbc-bootstrap

# Rust
/target/
**/*.rs.bk
Cargo.lock

# IDE
.idea/
.vscode/
*.swp
*.swo
*~

# OS
.DS_Store
Thumbs.db

# Build artifacts
*.o
*.a
*.so
*.dylib

# Generated files (keep these tracked)
# Makefile
# .github/workflows/ci.yml
"#;

    let mut out = HashMap::new();
    out.insert("gitignore_content".to_string(), Value::Str(gitignore.to_string()));
    Ok(out)
}

// Mockable implementation for test generation
use gunbc_test::Mockable;

impl Mockable for BootstrapOp {
    fn mock_outputs(&self) -> HashMap<String, Value> {
        match self {
            BootstrapOp::ScanWorkspace => {
                let mut out = HashMap::new();
                out.insert("crate_count".to_string(), Value::Int(5));
                out.insert("crate_names".to_string(), Value::StrList(vec!["lib-a".to_string(), "lib-b".to_string()]));
                out
            }
            BootstrapOp::GenerateMakefile => {
                let mut out = HashMap::new();
                out.insert("makefile_content".to_string(), Value::Str("# Mock Makefile".to_string()));
                out
            }
            BootstrapOp::GenerateGitignore => {
                let mut out = HashMap::new();
                out.insert("gitignore_content".to_string(), Value::Str("# Mock .gitignore\n/target/".to_string()));
                out
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_makefile() {
        let result = execute_generate_makefile(HashMap::new()).unwrap();

        match result.get("makefile_content") {
            Some(Value::Str(content)) => {
                assert!(content.contains("build:"));
                assert!(content.contains("test:"));
                assert!(content.contains("gist:"));
            }
            _ => panic!("expected makefile content"),
        }
    }

    #[test]
    fn test_generate_gitignore() {
        let result = execute_generate_gitignore(HashMap::new()).unwrap();

        match result.get("gitignore_content") {
            Some(Value::Str(content)) => {
                assert!(content.contains("/target/"));
                assert!(content.contains(".DS_Store"));
            }
            _ => panic!("expected gitignore content"),
        }
    }
}
