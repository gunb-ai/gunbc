#!/usr/bin/env bash
# Regenerate stage0 using the v2 compiler (self-compile).
#
# FF-9: The compiler resolves imports transitively from source roots.
# No manual file lists. The compiler follows imports and loads only
# what's needed.
#
# Usage:
#   ./scripts/regenerate-stage0.sh              # regenerate in-place
#   ./scripts/regenerate-stage0.sh --output-dir DIR  # regenerate to DIR (no copy, no verify)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
STAGE0_DIR="$ROOT/src/v2/stage0"

# Parse args
OUTPUT_ONLY=""
if [ "${1:-}" = "--output-dir" ]; then
    OUTPUT_ONLY="${2:?--output-dir requires a path}"
fi

echo "=== Building stage0 (v2-compiler) ==="
cargo build -p v2-compiler --release

STAGE0_CMD="cargo run -p v2-compiler --release --"

OUTPUT_DIR="${OUTPUT_ONLY:-$ROOT/.regen-output}"
rm -rf "$OUTPUT_DIR"

echo "=== Compiling .dag source with v2 compiler (FF-9: import-driven resolution) ==="
$STAGE0_CMD compile \
    --source-root "$ROOT/src/v2" \
    --source-root "$ROOT/dsl" \
    --output-dir "$OUTPUT_DIR"

# Generate lib.rs from emitted modules + hand-maintained extras
{
    echo '// Generated by v2 compiler -- do not edit.'
    echo ''
    echo '#![allow(unused_imports, unused_variables, unused_mut, unused_parens, dead_code, unreachable_patterns, non_shorthand_field_patterns, suspicious_double_ref_op, clippy::all)]'
    echo ''
    for f in "$OUTPUT_DIR"/src/*.rs; do
        mod=$(basename "$f" .rs)
        [ "$mod" = "lib" ] && continue
        [ "$mod" = "main" ] && continue
        [ "$mod" = "v2_rt" ] && continue
        echo "pub mod $mod;"
    done
    echo 'pub mod v2_rt;'
    echo ''
    echo '#[cfg(test)]'
    echo 'mod compiler_tests;'
} > "$OUTPUT_DIR/src/lib.rs"

# Copy hand-maintained files from committed stage0.
# These files have manual additions that the emitter doesn't produce:
#   main.rs: FF-9 import resolution, CLI entrypoint
#   v2_rt.rs: runtime shims (Rc::make_mut, string ops, etc.)
#   compiler_tests.rs: test harness
#   extdeps_languages_dag_syntax.rs: thread_local cache for dag_syntax_spec
#     (called per-token in parser hot loop; without cache each call
#     reconstructs full SyntaxSpec. Remove when emitter supports data-def
#     memoization.)
cp "$STAGE0_DIR/src/v2_rt.rs" "$OUTPUT_DIR/src/v2_rt.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/compiler_tests.rs" "$OUTPUT_DIR/src/compiler_tests.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/main.rs" "$OUTPUT_DIR/src/main.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/extdeps_languages_dag_syntax.rs" "$OUTPUT_DIR/src/extdeps_languages_dag_syntax.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/v2_coercion.rs" "$OUTPUT_DIR/src/v2_coercion.rs" 2>/dev/null || true

# --output-dir mode: leave output in place, caller handles it
if [ -n "$OUTPUT_ONLY" ]; then
    echo "=== Regeneration output in $OUTPUT_DIR ==="
    exit 0
fi

echo "=== Copying to stage0 ==="
for f in "$OUTPUT_DIR"/src/*.rs; do
    cp "$f" "$STAGE0_DIR/src/$(basename "$f")"
done

echo "=== Verifying stage0 compiles ==="
if cargo check -p v2-compiler 2>&1 | tail -5; then
    echo "=== Done. Stage0 regenerated via v2 self-compile. ==="
else
    echo ""
    echo "=== Stage0 has compilation errors. ==="
    cargo check -p v2-compiler 2>&1 | grep "^error" | wc -l
    echo " errors remaining."
    exit 1
fi

rm -rf "$OUTPUT_DIR"
