#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
BIN="$ROOT/target/debug/frontier_probe_survey"
SURVEY_DIR="$ROOT/target/frontier-probe-survey"
TSV="$SURVEY_DIR/frontier_probe_survey.tsv"
MANIFEST="$SURVEY_DIR/host_frontier_probe_survey_manifest.dag"
mkdir -p "$SURVEY_DIR"

MODULES=(
  "src/v2/compiler/materialization_carriers.dag"
  "src/v2/compiler/04_infer.dag"
  "src/v2/compiler/05_eval.dag"
  "src/v2/compiler/06_translate.dag"
  "src/v2/compiler/05_emit.dag"
  "src/v2/compiler/program_partition.dag"
  "src/v2/compiler/02_parse.dag"
  "src/v2/compiler/source_authority.dag"
  "src/v2/compiler/00_compile.dag"
  "src/v2/compiler/03_ingest.dag"
  "src/v2/compiler/parse_engine_hooks.dag"
  "src/v2/compiler/use_site_verdict.dag"
  "src/v2/compiler/discovery_enumeration.dag"
  "src/v2/compiler/01_tokenize.dag"
  "src/v2/compiler/self_host.dag"
  "src/v2/compiler/07_target_carriers.dag"
  "src/v2/compiler/fold_lowering.dag"
  "src/v2/compiler/03_normalize.dag"
  "src/v2/compiler/03_resolve.dag"
  "src/v2/compiler/03_name_resolve.dag"
  "src/v2/compiler/emit_module.dag"
  "src/v2/compiler/05_emit_orchestration.dag"
  "src/v2/compiler/emit_semantic_decl.dag"
  "src/v2/compiler/emit_host.dag"
  "src/v2/compiler/emit_produced.dag"
  "src/v2/compiler/03_body_producer.dag"
  "src/v2/compiler/program_assembly.dag"
)

echo "module	self_emit_ready	blocker_class	located_stage	located_reason	probe_error" > "$TSV"
for mod in "${MODULES[@]}"; do
  echo "=== probing $mod ===" >&2
  CTRL_BUILD_BYPASS_SHIMS=1 "$BIN" \
    --source-root src/v2 \
    --module "$mod" \
    --survey-dir "$SURVEY_DIR" \
    --emit-survey-manifest "$SURVEY_DIR/tmp_manifest.dag" \
    --emit-tsv "$SURVEY_DIR/tmp_row.tsv" 2>&1 | tail -3 >&2 || true
  if [[ -f "$SURVEY_DIR/tmp_row.tsv" ]]; then
    tail -n +2 "$SURVEY_DIR/tmp_row.tsv" >> "$TSV"
  fi
done

# Final manifest from full sweep (re-run sequentially in one process would OOM; assemble from TSV via Python)
python3 - "$TSV" "$MANIFEST" <<'PY'
import sys
from pathlib import Path

tsv_path, manifest_path = sys.argv[1], sys.argv[2]
rows = []
with open(tsv_path) as f:
    header = f.readline()
    for line in f:
        parts = line.rstrip("\n").split("\t")
        if len(parts) < 5:
            continue
        module, _, blocker, stage, reason = parts[:5]
        rows.append((module, blocker, stage, reason))

def emit_receipt(module, blocker, stage, reason):
    return (
        f"FrontierProbeReceipt {{\n"
        f'  module_path: "{module}",\n'
        f"  blocker_class: {blocker},\n"
        f"  located_stage: {stage},\n"
        f"  located_reason: {reason}\n"
        f"}}"
    )

lst = "Empty"
for module, blocker, stage, reason in reversed(rows):
    head = emit_receipt(module, blocker, stage, reason)
    lst = f"Cons {{\n  head: {head},\n  tail: {lst}\n}}"

body = (
    "// GENERATED by run_frontier_survey_per_module.sh — execution receipt table.\n"
    "module v2.test.workflow.host_frontier_probe_survey_manifest\n\n"
    "import v2.compiler.self_host.frontier_probe_types { FrontierProbeReceipt }\n"
    "import v2.std.algebra { Cons, Empty }\n"
    "import v2.std.collection { List }\n"
    "import v2.std.logic { Int }\n\n"
    f"data host_frontier_probe_survey_module_count: Int = {len(rows)}\n\n"
    f"data host_frontier_probe_survey: List<FrontierProbeReceipt> = {lst}\n"
)
Path(manifest_path).write_text(body)
print(f"wrote {manifest_path} ({len(rows)} receipts)")
PY

echo "Survey complete: $MANIFEST"
