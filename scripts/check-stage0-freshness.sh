#!/usr/bin/env bash
# Verify that committed stage0 matches what regenerate-stage0.sh would produce.
#
# This is the CI gate that prevents dual-representation drift:
# - Editing stage0 Rust without updating .dag source → fails
# - Editing .dag source without regenerating stage0 → fails
#
# Usage: ./scripts/check-stage0-freshness.sh
#   Exit 0 = stage0 is fresh (matches regeneration output)
#   Exit 1 = stage0 is stale (diff shown)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
STAGE0_DIR="$ROOT/src/v2/stage0"

echo "=== Building stage0 binary ==="
cargo build -p v2-compiler --release 2>&1 | tail -1

STAGE0_CMD="cargo run -p v2-compiler --release --"
CHECK_DIR="$ROOT/.freshness-check"
rm -rf "$CHECK_DIR"

echo "=== Regenerating into temp dir ==="
$STAGE0_CMD compile \
    --source-root "$ROOT/src/v2" \
    --source-root "$ROOT/dsl" \
    --output-dir "$CHECK_DIR"

# Generate lib.rs matching the regen script's logic
{
    echo '// Generated by v2 compiler -- do not edit.'
    echo ''
    echo '#![allow(unused_imports, unused_variables, unused_mut, unused_parens, dead_code, unreachable_patterns, non_shorthand_field_patterns, suspicious_double_ref_op, clippy::all)]'
    echo ''
    for f in "$CHECK_DIR"/src/*.rs; do
        mod=$(basename "$f" .rs)
        [ "$mod" = "lib" ] && continue
        [ "$mod" = "main" ] && continue
        [ "$mod" = "v2_rt" ] && continue
        echo "pub mod $mod;"
    done
    echo 'pub mod v2_rt;'
    echo ''
    echo '#[cfg(test)]'
    echo 'mod compiler_tests;'
} > "$CHECK_DIR/src/lib.rs"

# Copy hand-maintained files (same list as regenerate-stage0.sh)
cp "$STAGE0_DIR/src/v2_rt.rs" "$CHECK_DIR/src/v2_rt.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/compiler_tests.rs" "$CHECK_DIR/src/compiler_tests.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/main.rs" "$CHECK_DIR/src/main.rs" 2>/dev/null || true
cp "$STAGE0_DIR/src/extdeps_languages_dag_syntax.rs" "$CHECK_DIR/src/extdeps_languages_dag_syntax.rs" 2>/dev/null || true

echo "=== Comparing ==="
DIFF_OUTPUT=$(diff -rq "$CHECK_DIR/src/" "$STAGE0_DIR/src/" 2>&1 || true)

rm -rf "$CHECK_DIR"

if [ -z "$DIFF_OUTPUT" ]; then
    echo "=== Stage0 is fresh — matches regeneration output. ==="
    exit 0
else
    echo "=== Stage0 is STALE — does not match regeneration output. ==="
    echo ""
    echo "$DIFF_OUTPUT"
    echo ""
    echo "Run ./scripts/regenerate-stage0.sh to update stage0."
    exit 1
fi
