#!/usr/bin/env bash
# Probe seed-retained frontier modules one subprocess at a time (memory isolation).
# Writes merged manifest + TSV under target/frontier-probe-survey/.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

BIN="${ROOT}/target/release/frontier_probe_survey"
SURVEY_DIR="${ROOT}/target/frontier-probe-survey"
MANIFEST="${SURVEY_DIR}/host_frontier_probe_survey_manifest.dag"
TSV="${SURVEY_DIR}/host_frontier_probe_survey.tsv"
PARTIAL_DIR="${SURVEY_DIR}/partial"
LOG="${SURVEY_DIR}/sweep.log"

mkdir -p "$SURVEY_DIR" "$PARTIAL_DIR"

if [[ ! -x "$BIN" ]]; then
  echo "building frontier_probe_survey..." >&2
  CTRL_BUILD_WRAP_CARGO=0 cargo build --release -p v1-compiler --bin frontier_probe_survey
fi

mapfile -t SEED_RETAINED < <(
  python3 - <<'PY'
import re
text = open("src/v2/compiler/self_host/frontier.dag").read()
rows = re.findall(
    r"data compiler_frontier_row_\S+: CompilerModuleFrontierRow = knowledge_attributed_blocker_class_seed_retained_row\(\s*module_path: \"([^\"]+)\"",
    text,
)
for path in rows:
    print(path)
PY
)

echo "curated_cargo_frontier_probe_sweep: ${#SEED_RETAINED[@]} seed-retained module(s)" | tee "$LOG"

: >"${PARTIAL_DIR}/merged.tsv"
echo -e "module\tself_emit_ready\tblocker_class\tlocated_stage\tlocated_reason\tprobe_error" >>"${PARTIAL_DIR}/merged.tsv"

for mod in "${SEED_RETAINED[@]}"; do
  slug="${mod#src/v2/}"
  slug="${slug//\//__}"
  partial_manifest="${PARTIAL_DIR}/${slug}.dag"
  partial_tsv="${PARTIAL_DIR}/${slug}.tsv"
  echo "probing ${mod}..." | tee -a "$LOG"
  if "$BIN" \
    --source-root src/v2 \
    --only-module "$mod" \
    --emit-survey-manifest "$partial_manifest" \
    --emit-tsv "$partial_tsv" \
    --survey-dir "$SURVEY_DIR"; then
    tail -n +2 "$partial_tsv" >>"${PARTIAL_DIR}/merged.tsv"
  else
    echo "FAILED ${mod}" | tee -a "$LOG"
    exit 1
  fi
done

python3 - <<'PY' "${PARTIAL_DIR}/merged.tsv" "$MANIFEST" "$TSV"
import sys
from pathlib import Path

tsv_path, manifest_path, out_tsv = map(Path, sys.argv[1:4])
rows = []
for line in tsv_path.read_text().splitlines()[1:]:
    if not line.strip():
        continue
    parts = line.split("\t")
    if len(parts) < 5:
        continue
    module_path, self_emit, blocker, stage, reason = parts[:5]
    probe_error = parts[5] if len(parts) > 5 else ""
    rows.append((module_path, blocker, stage, reason, probe_error))

out_tsv.write_text(tsv_path.read_text())

receipt_nodes = []
for module_path, blocker, stage, reason, _probe_error in rows:
    receipt_nodes.append(
        "FrontierProbeReceipt {\n"
        f'  module_path: "{module_path}",\n'
        f"  blocker_class: {blocker},\n"
        f"  located_stage: {stage},\n"
        f"  located_reason: {reason}\n"
        "}"
    )

list_body = "Empty"
while receipt_nodes:
    head = receipt_nodes.pop()
    list_body = f"Cons {{\n  head: {head},\n  tail: {list_body}\n}}"

manifest = (
    "// GENERATED by scripts/curated_cargo_frontier_probe_sweep.sh — execution receipt table.\n"
    "module v2.test.workflow.host_frontier_probe_survey_manifest\n\n"
    "import v2.compiler.self_host.frontier_probe_types { FrontierProbeReceipt }\n"
    "import v2.std.algebra { Cons, Empty }\n"
    "import v2.std.collection { List }\n"
    "import v2.std.logic { Int }\n\n"
    f"data host_frontier_probe_survey_module_count: Int = {len(rows)}\n\n"
    f"data host_frontier_probe_survey: List<FrontierProbeReceipt> = {list_body}\n"
)
manifest_path.write_text(manifest)
print(f"wrote {manifest_path} ({len(rows)} receipts)")
PY

echo "curated_cargo_frontier_probe_sweep: done" | tee -a "$LOG"
