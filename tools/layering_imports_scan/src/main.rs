//! Host transport for layering-imports gate — enumerates import facts from std/ and
//! extdeps/ layer roots. Violation semantics live in `v4.lens.layering_imports`.
//!
//! Usage:
//!   layering_imports_scan --repo-root . \
//!       --emit-dag-manifest target/v4-layering-imports-manifest.dag
//!
//! Exit codes: 0 = success; 1 = scan/write failure; 2 = usage error.

#![allow(clippy::disallowed_macros)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use regex::Regex;

#[derive(Debug, Clone, PartialEq, Eq)]
struct LayerRoot {
    layer: &'static str,
    rel_root: &'static str,
}

const LAYER_ROOTS: &[LayerRoot] = &[
    LayerRoot {
        layer: "LayerStd",
        rel_root: "src/v4/std",
    },
    LayerRoot {
        layer: "LayerStd",
        rel_root: "src/v3/std",
    },
    LayerRoot {
        layer: "LayerStd",
        rel_root: "dsl/std",
    },
    LayerRoot {
        layer: "LayerExtdeps",
        rel_root: "src/v4/extdeps",
    },
    LayerRoot {
        layer: "LayerExtdeps",
        rel_root: "dsl/extdeps",
    },
];

#[derive(Debug, Clone, PartialEq, Eq)]
struct LayerImportFact {
    layer: &'static str,
    path: String,
    import_module: String,
}

fn dag_string_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn collect_dag_files(root: &Path, rel_root: &str) -> Result<Vec<PathBuf>, String> {
    let base = root.join(rel_root);
    if !base.is_dir() {
        return Ok(Vec::new());
    }
    let mut files = Vec::new();
    walk_dag_files(&base, &mut files)?;
    files.sort();
    Ok(files)
}

fn walk_dag_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    for entry in fs::read_dir(dir).map_err(|e| format!("read_dir {}: {e}", dir.display()))? {
        let entry = entry.map_err(|e| format!("read_dir entry: {e}"))?;
        let path = entry.path();
        if path.is_dir() {
            walk_dag_files(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "dag") {
            out.push(path);
        }
    }
    Ok(())
}

fn scan_file(repo_root: &Path, path: &Path, layer: &str, import_re: &Regex) -> Result<Vec<LayerImportFact>, String> {
    let relpath = path
        .strip_prefix(repo_root)
        .map_err(|_| format!("{} not under repo root {}", path.display(), repo_root.display()))?
        .to_string_lossy()
        .replace('\\', "/");
    let text = fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))?;
    let mut facts = Vec::new();
    for line in text.lines() {
        if let Some(caps) = import_re.captures(line) {
            let module = caps.get(1).map(|m| m.as_str()).unwrap_or("").to_string();
            if !module.is_empty() {
                facts.push(LayerImportFact {
                    layer,
                    path: relpath.clone(),
                    import_module: module,
                });
            }
        }
    }
    Ok(facts)
}

fn scan_repo(repo_root: &Path) -> Result<Vec<LayerImportFact>, String> {
    let import_re = Regex::new(r"^\s*import\s+([\w.]+)")
        .map_err(|e| format!("import regex: {e}"))?;
    let mut facts = Vec::new();
    for layer_root in LAYER_ROOTS {
        for path in collect_dag_files(repo_root, layer_root.rel_root)? {
            facts.extend(scan_file(
                repo_root,
                &path,
                layer_root.layer,
                &import_re,
            )?);
        }
    }
    facts.sort_by(|a, b| {
        (&a.path, &a.import_module).cmp(&(&b.path, &b.import_module))
    });
    Ok(facts)
}

fn emit_manifest(path: &Path, facts: &[LayerImportFact]) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("mkdir {}: {e}", parent.display()))?;
    }
    let mut out = String::new();
    out.push_str("// GENERATED by layering_imports_scan — ephemeral host transport. DO NOT COMMIT.\n");
    out.push_str("module v4.test.claim.workflow.host_layering_import_manifest\n\n\n");
    out.push_str("import v4.std.collection { List }\n");
    out.push_str("import v4.lens.layering_imports { LayerExtdeps, LayerImportFact, LayerStd }\n\n\n");
    out.push_str("data host_layer_import_facts: List<LayerImportFact> = [\n");
    for (idx, fact) in facts.iter().enumerate() {
        if idx > 0 {
            out.push(',');
            out.push('\n');
        }
        out.push_str("  LayerImportFact {\n");
        out.push_str(&format!("    layer: {},\n", fact.layer));
        out.push_str(&format!(
            "    path: \"{}\",\n",
            dag_string_escape(&fact.path)
        ));
        out.push_str(&format!(
            "    import_module: \"{}\"\n",
            dag_string_escape(&fact.import_module)
        ));
        out.push_str("  }");
    }
    out.push_str("\n]\n");
    fs::write(path, out).map_err(|e| format!("write {}: {e}", path.display()))
}

fn usage() -> ! {
    eprintln!(
        "usage: layering_imports_scan --repo-root <dir> --emit-dag-manifest <path.dag>"
    );
    std::process::exit(2);
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut repo_root = None;
    let mut manifest = None;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--repo-root" => {
                i += 1;
                repo_root = Some(args.get(i).cloned().unwrap_or_else(|| usage()));
            }
            "--emit-dag-manifest" => {
                i += 1;
                manifest = Some(args.get(i).cloned().unwrap_or_else(|| usage()));
            }
            other => {
                eprintln!("layering_imports_scan: unknown argument: {other}");
                usage();
            }
        }
        i += 1;
    }
    let repo_root = repo_root.unwrap_or_else(|| {
        eprintln!("layering_imports_scan: --repo-root is required");
        usage();
    });
    let manifest = manifest.unwrap_or_else(|| {
        eprintln!("layering_imports_scan: --emit-dag-manifest is required");
        usage();
    });
    let repo_path = PathBuf::from(&repo_root);
    if !repo_path.is_dir() {
        eprintln!("layering_imports_scan: repo root is not a directory: {repo_root}");
        return ExitCode::from(1);
    }
    let facts = match scan_repo(&repo_path) {
        Ok(f) => f,
        Err(e) => {
            eprintln!("layering_imports_scan: {e}");
            return ExitCode::from(1);
        }
    };
    println!(
        "layering_imports_scan: {} import fact(s) from {} layer root(s)",
        facts.len(),
        LAYER_ROOTS.len()
    );
    if let Err(e) = emit_manifest(Path::new(&manifest), &facts) {
        eprintln!("layering_imports_scan: {e}");
        return ExitCode::from(1);
    }
    println!("layering_imports_scan: wrote manifest {manifest}");
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn import_line_regex_matches_dag_import() {
        let re = Regex::new(r"^\s*import\s+([\w.]+)").unwrap();
        let caps = re.captures("  import v4.compiler.tokenize { tokenize }").unwrap();
        assert_eq!(caps.get(1).unwrap().as_str(), "v4.compiler.tokenize");
    }
}
