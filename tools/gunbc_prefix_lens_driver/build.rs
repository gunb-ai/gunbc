//! Single authority for v0 `LENS_ID` argv validation: `src/v4/lens/registry.dag`.
//! Emits `OUT_DIR/generated_valid_lens_ids.rs` consumed by `main.rs` via `include!`.

use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let registry = manifest_dir.join("../../src/v4/lens/registry.dag");
    println!("cargo:rerun-if-changed={}", registry.display());

    let src = std::fs::read_to_string(&registry)
        .unwrap_or_else(|e| panic!("read {}: {e}", registry.display()));

    let mut ids: Vec<String> = Vec::new();
    for line in src.lines() {
        let t = line.trim_start();
        let Some(rest) = t.strip_prefix("lens_id:") else {
            continue;
        };
        let rest = rest.trim();
        if rest.len() >= 2 && rest.starts_with('"') && rest.ends_with('"') {
            ids.push(rest[1..rest.len() - 1].to_string());
        }
    }

    ids.sort_unstable();
    ids.dedup();
    assert!(
        !ids.is_empty(),
        "{} must declare at least one `lens_id: \"…\"` field",
        registry.display()
    );

    let out_path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("generated_valid_lens_ids.rs");
    let mut out = String::from(
        "// AUTO-GENERATED by tools/gunbc_prefix_lens_driver/build.rs from src/v4/lens/registry.dag.\n\
         // Do not edit.\n\n\
         /// Every `lens_id` string literal in `LensRegistryEntryV0` rows (sorted, deduped).\n\
         pub static VALID_LENS_IDS: &[&str] = &[\n",
    );
    for id in &ids {
        assert!(
            !id.contains('"') && !id.contains('\\'),
            "lens_id must be a simple slug for Rust emission: {id:?}"
        );
        out.push_str(&format!("    \"{id}\",\n"));
    }
    out.push_str("];\n");
    std::fs::write(&out_path, out).unwrap_or_else(|e| panic!("write {}: {e}", out_path.display()));
}
