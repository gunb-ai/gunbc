//! Test code generation.

use crate::analyze::{analyze_dag, DagAnalysis};
use gunbc_ir::{CardinalityCase, Dag};

/// Configuration for test generation.
#[derive(Debug, Clone)]
pub struct TestConfig {
    /// Generate boundary tests
    pub boundary_tests: bool,
    /// Generate composition tests
    pub composition_tests: bool,
    /// Generate cardinality tests for list ports
    pub cardinality_tests: bool,
    /// Test module visibility
    pub visibility: String,
}

impl Default for TestConfig {
    fn default() -> Self {
        Self {
            boundary_tests: true,
            composition_tests: true,
            cardinality_tests: true,
            visibility: "pub".to_string(),
        }
    }
}

/// Test code generator.
pub struct TestGenerator<'a, T> {
    dag: &'a Dag<T>,
    config: TestConfig,
}

impl<'a, T> TestGenerator<'a, T> {
    /// Create a new test generator for a DAG.
    pub fn new(dag: &'a Dag<T>) -> Self {
        Self {
            dag,
            config: TestConfig::default(),
        }
    }

    /// Set the test configuration.
    pub fn with_config(mut self, config: TestConfig) -> Self {
        self.config = config;
        self
    }

    /// Generate the test module code.
    pub fn generate_test_module(&self, module_name: &str, graph_builder_fn: &str) -> String {
        let analysis = analyze_dag(self.dag);
        let mut code = String::new();

        // Module header
        code.push_str(&format!(
            "//! Generated tests for {} DAG.\n",
            module_name
        ));
        code.push_str("//!\n");
        code.push_str("//! DO NOT EDIT - generated by gunbc-testgen.\n\n");

        // Imports
        code.push_str("use gunbc_exec::{execute_with_mode, BoundaryMocks, ExecutionMode};\n");
        code.push_str("use gunbc_ir::{detect_boundaries, Cardinality, Value};\n");
        code.push_str("use gunbc_test::{assert_boundary_mockable, assert_types_compatible, default_mocks};\n\n");

        // Boundary tests
        if self.config.boundary_tests {
            code.push_str(&self.generate_boundary_tests(&analysis, graph_builder_fn));
        }

        // Composition tests
        if self.config.composition_tests {
            code.push_str(&self.generate_composition_tests(&analysis, graph_builder_fn));
        }

        // Cardinality tests
        if self.config.cardinality_tests {
            code.push_str(&self.generate_cardinality_tests(&analysis, graph_builder_fn));
        }

        code
    }

    /// Generate boundary tests.
    fn generate_boundary_tests(&self, analysis: &DagAnalysis, graph_builder_fn: &str) -> String {
        let mut code = String::new();

        // Test that the graph is boundary-mockable
        code.push_str("/// Test that all boundaries can be mocked.\n");
        code.push_str("#[test]\n");
        code.push_str("fn test_boundaries_mockable() {\n");
        code.push_str(&format!("    let dag = {};\n", graph_builder_fn));
        code.push_str("    let result = assert_boundary_mockable(&dag, default_mocks());\n");
        code.push_str("    assert!(result.is_ok(), \"Boundaries should be mockable: {:?}\", result.error);\n");
        code.push_str("}\n\n");

        // Individual boundary node tests
        for boundary_node in &analysis.boundaries.boundary_nodes {
            let test_name = format!("test_boundary_{}_mockable", boundary_node.0.replace('-', "_"));
            let node_name = &boundary_node.0;

            code.push_str(&format!("/// Test that {} boundary can be mocked.\n", node_name));
            code.push_str("#[test]\n");
            code.push_str(&format!("fn {}() {{\n", test_name));
            code.push_str(&format!("    let dag = {};\n", graph_builder_fn));
            code.push_str("    let boundaries = detect_boundaries(&dag);\n");
            code.push_str(&format!(
                "    assert!(boundaries.is_boundary_node(&\"{}\".into()), \"{} should be a boundary\");\n",
                node_name, node_name
            ));
            code.push_str("    \n");
            code.push_str("    let mut mocks = BoundaryMocks::new();\n");
            
            // Add mocks for all boundary ports on this node
            for (node_id, port_name) in &analysis.boundaries.boundary_ports {
                if node_id == boundary_node {
                    code.push_str(&format!(
                        "    mocks.set_value(\"{}\", \"{}\", Value::Str(\"<MOCK>\".to_string()));\n",
                        node_id.0, port_name.0
                    ));
                }
            }
            
            code.push_str("    \n");
            code.push_str("    let log = execute_with_mode(&dag, ExecutionMode::DryRun(mocks)).unwrap();\n");
            code.push_str(&format!(
                "    let entry = log.get(\"{}\").expect(\"node should be in log\");\n",
                node_name
            ));
            code.push_str("    assert!(entry.was_intercepted, \"boundary should be intercepted in dry-run\");\n");
            code.push_str("}\n\n");
        }

        code
    }

    /// Generate composition tests.
    fn generate_composition_tests(&self, analysis: &DagAnalysis, graph_builder_fn: &str) -> String {
        let mut code = String::new();

        // Test that all edges are compatible
        code.push_str("/// Test that all edge types are compatible.\n");
        code.push_str("#[test]\n");
        code.push_str("fn test_all_edges_compatible() {\n");
        code.push_str(&format!("    let dag = {};\n", graph_builder_fn));
        code.push_str("    let results = assert_types_compatible(&dag);\n");
        code.push_str("    for result in &results {\n");
        code.push_str("        assert!(result.is_compatible(), \"Edge {} should be compatible\", result.edge);\n");
        code.push_str("    }\n");
        code.push_str("}\n\n");

        // Individual edge tests
        for edge_info in &analysis.edge_types {
            let test_name = format!(
                "test_edge_{}_{}_to_{}_{}",
                edge_info.from_node.replace('-', "_"),
                edge_info.from_port.replace('-', "_"),
                edge_info.to_node.replace('-', "_"),
                edge_info.to_port.replace('-', "_")
            );

            code.push_str(&format!(
                "/// Test edge {}.{} -> {}.{} type compatibility.\n",
                edge_info.from_node, edge_info.from_port,
                edge_info.to_node, edge_info.to_port
            ));
            code.push_str("#[test]\n");
            code.push_str(&format!("fn {}() {{\n", test_name));
            code.push_str(&format!("    // {} -> {}\n", edge_info.from_type, edge_info.to_type));
            code.push_str(&format!(
                "    assert!({}, \"Types {} and {} should be compatible\");\n",
                edge_info.compatible,
                edge_info.from_type, edge_info.to_type
            ));
            code.push_str("}\n\n");
        }

        code
    }

    /// Generate cardinality tests for list ports.
    fn generate_cardinality_tests(&self, analysis: &DagAnalysis, _graph_builder_fn: &str) -> String {
        let mut code = String::new();

        // Find ports that need cardinality tests (lists with multiple test cases)
        let list_ports: Vec<_> = analysis
            .port_cardinalities
            .iter()
            .filter(|p| p.needs_tests() && p.is_input)
            .collect();

        if list_ports.is_empty() {
            return code;
        }

        code.push_str("// ============================================================================\n");
        code.push_str("// Cardinality Tests\n");
        code.push_str("// These tests verify behavior at cardinality boundaries (empty, one, many).\n");
        code.push_str("// Actual test values should come from Mockable::cardinality_inputs().\n");
        code.push_str("// ============================================================================\n\n");

        // Generate a summary test that lists all ports with their cardinalities
        code.push_str("/// Verify cardinality annotations on ports.\n");
        code.push_str("#[test]\n");
        code.push_str("fn test_port_cardinalities() {\n");
        code.push_str("    // This test documents the expected cardinalities for list ports.\n");
        code.push_str("    // Use Mockable::cardinality_inputs() on operations to get test values.\n");
        
        for port_info in &list_ports {
            let cardinality_str = match port_info.cardinality {
                gunbc_ir::Cardinality::Zero => "Zero",
                gunbc_ir::Cardinality::One => "One",
                gunbc_ir::Cardinality::ZeroOrOne => "ZeroOrOne",
                gunbc_ir::Cardinality::ZeroOrMore => "ZeroOrMore",
                gunbc_ir::Cardinality::OneOrMore => "OneOrMore",
            };

            let cases: Vec<&str> = port_info
                .test_cases
                .iter()
                .map(|c| match c {
                    CardinalityCase::Empty => "Empty",
                    CardinalityCase::One => "One",
                    CardinalityCase::Many => "Many",
                })
                .collect();

            code.push_str(&format!(
                "    // {}.{}: {} -> test cases: [{}]\n",
                port_info.node_id,
                port_info.port_name,
                cardinality_str,
                cases.join(", ")
            ));
        }

        code.push_str("    \n");
        code.push_str("    // To run actual cardinality tests, implement Mockable for your operations\n");
        code.push_str("    // and call cardinality_inputs() to get the test values.\n");
        code.push_str("}\n\n");

        code
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use gunbc_ir::{build::*, Dag, Node};

    #[test]
    fn test_generate_test_module() {
        let mut dag: Dag<()> = Dag::new();
        dag.add_node(Node::opaque("source", vec![], vec![port("out", "String")], ()));
        dag.add_node(Node::opaque("sink", vec![port("in", "String")], vec![port("result", "String")], ()));
        dag.add_edge(edge("source", "out", "sink", "in"));

        let generator = TestGenerator::new(&dag);
        let code = generator.generate_test_module("example", "build_example_graph()");

        assert!(code.contains("test_boundaries_mockable"));
        assert!(code.contains("test_boundary_sink_mockable"));
        assert!(code.contains("test_all_edges_compatible"));
        assert!(code.contains("test_edge_source_out_to_sink_in"));
    }
}
