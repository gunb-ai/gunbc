//! CI YAML rendering from DAGs.
//!
//! This module provides the `CiRenderer` trait for generating CI workflow YAML
//! from DAG structures. Each CI provider (GitHub Actions, GitLab CI) implements
//! its own rendering strategy while sharing common node definitions.
//!
//! # Architecture
//!
//! ```text
//! Dag<T>                     CiRenderer::render()
//!   │                              │
//!   │  ┌───────────────────────────┼───────────────────────────┐
//!   │  │                           │                           │
//!   ▼  ▼                           ▼                           ▼
//! GitHubActionsRenderer      GitLabCiRenderer           (future providers)
//!   │                           │
//!   ▼                           ▼
//! steps:                    stages:
//!   - uses: actions/checkout    - build
//!   - run: cargo build          - test
//!   - run: cargo test           - lint
//! ```
//!
//! # Design Principles
//!
//! 1. **Provider-owned mapping**: Each provider owns its DAG→YAML mapping
//! 2. **Shared node definitions**: Common DAG nodes are reused across providers
//! 3. **Step granularity**: Each DAG node becomes a CI step for visibility
//! 4. **Data passing**: Node outputs become step outputs (GitHub) or artifacts (GitLab)

use crate::cargo::{CargoEnv, CargoInvocation};
use crate::git::GitConfig;
use crate::language::traits::comment::generated_header;
use crate::transport::github_actions::RunnerImage;
use crate::{Dag, NodeId};
use std::collections::HashMap;

/// Trait for rendering DAGs to CI workflow YAML.
///
/// Each CI provider implements this trait to generate its native YAML format.
/// The trait provides a uniform interface while allowing provider-specific
/// rendering strategies.
pub trait CiRenderer {
    /// The CI provider identifier (e.g., "github-actions", "gitlab-ci").
    fn provider_id(&self) -> &'static str;

    /// Render a DAG to CI workflow YAML.
    ///
    /// # Arguments
    ///
    /// * `dag` - The DAG to render
    /// * `config` - Rendering configuration (tool name, runner, etc.)
    ///
    /// # Returns
    ///
    /// The generated YAML as a string.
    fn render<T>(&self, dag: &Dag<T>, config: &RenderConfig) -> String;

    /// Get the file path where this CI config should be written.
    ///
    /// For GitHub Actions: `.github/workflows/{name}.yml`
    /// For GitLab CI: `.gitlab-ci.yml`
    fn output_path(&self, workflow_name: &str) -> String;
}

/// Configuration for CI YAML rendering.
#[derive(Debug, Clone)]
pub struct RenderConfig {
    /// Name of the workflow/pipeline.
    pub workflow_name: String,

    /// How to invoke the CI tool binary via cargo.
    pub tool: CargoInvocation,

    /// Name of the tool that generates this CI config file
    /// (e.g., "gunbc-codegen"). Used in the "Generated by" header.
    pub generator_name: String,

    /// Command to regenerate this file (e.g., "make ci-yaml").
    /// Used in the "DO NOT EDIT - regenerate with:" header.
    pub regenerate_command: String,

    /// Runner image to use. Selected from the provider's catalog
    /// (e.g., `github_actions::ubuntu_latest()`).
    pub runner: RunnerImage,

    /// Whether to use step mode (each node as separate CI step).
    pub step_mode: bool,

    /// Cargo environment configuration (term color, warnings policy).
    /// The rendering layer derives env vars from this model.
    pub cargo_env: CargoEnv,

    /// Additional non-cargo environment variables.
    pub env: HashMap<String, String>,

    /// Checkout action/config (provider-specific).
    pub checkout: Option<CheckoutConfig>,

    /// Git configuration (default branch, branching strategy).
    /// CI triggers are derived from this model.
    pub git: GitConfig,

    /// Caching configuration.
    pub cache: Option<CacheConfig>,

    /// Job-level timeout in minutes. GitHub Actions defaults to 360 (6 hours)
    /// if unset, which is far too long for most CI jobs. Default: 30 minutes.
    pub timeout_minutes: u32,

    /// Workflow-level permission scopes (e.g., `("id-token", "write")`).
    ///
    /// Rendered as a `permissions:` block in GitHub Actions. Entries are
    /// sorted by key for deterministic output.
    pub permissions: Vec<(String, String)>,

    /// Secret names to expose as environment variables in the CI run step.
    ///
    /// Each entry is a secret name; the rendering layer maps it to the
    /// provider's secret reference syntax (e.g., `${{ secrets.NAME }}` for
    /// GitHub Actions).
    pub secrets_env: Vec<String>,
}

impl Default for RenderConfig {
    fn default() -> Self {
        Self {
            workflow_name: String::new(),
            tool: CargoInvocation::default(),
            generator_name: String::new(),
            regenerate_command: String::new(),
            runner: crate::transport::github_actions::ubuntu_latest(),
            step_mode: true,
            cargo_env: CargoEnv::default(),
            env: HashMap::new(),
            checkout: Some(CheckoutConfig::default()),
            git: GitConfig::default(),
            cache: None,
            timeout_minutes: 30,
            permissions: Vec::new(),
            secrets_env: Vec::new(),
        }
    }
}

impl RenderConfig {
    /// Create a new render config with defaults.
    pub fn new(workflow_name: &str, tool: CargoInvocation) -> Self {
        Self {
            workflow_name: workflow_name.to_string(),
            tool,
            ..Self::default()
        }
    }

    /// Set the generator name and regeneration command.
    ///
    /// These appear in the file header:
    /// ```text
    /// # Generated by {generator_name}
    /// # DO NOT EDIT - regenerate with: {regenerate_command}
    /// ```
    pub fn with_generator(mut self, name: &str, command: &str) -> Self {
        self.generator_name = name.to_string();
        self.regenerate_command = command.to_string();
        self
    }

    /// Produce the standard "Generated by / DO NOT EDIT" header.
    ///
    /// Uses the language module's `generated_header` for consistency
    /// with all other generated files in the workspace.
    pub fn header(&self, comment_prefix: &str) -> String {
        generated_header(
            &self.generator_name,
            &self.regenerate_command,
            comment_prefix,
        )
    }

    /// Set the runner image (selected from the provider's catalog).
    pub fn with_runner(mut self, runner: RunnerImage) -> Self {
        self.runner = runner;
        self
    }

    /// Disable step mode (run full DAG in one step).
    pub fn without_step_mode(mut self) -> Self {
        self.step_mode = false;
        self
    }

    /// Set cargo environment configuration.
    pub fn with_cargo_env(mut self, cargo_env: CargoEnv) -> Self {
        self.cargo_env = cargo_env;
        self
    }

    /// Add a non-cargo environment variable.
    pub fn with_env(mut self, key: &str, value: &str) -> Self {
        self.env.insert(key.to_string(), value.to_string());
        self
    }

    /// Set git configuration (default branch, branching strategy).
    pub fn with_git(mut self, git: GitConfig) -> Self {
        self.git = git;
        self
    }

    /// Enable caching.
    pub fn with_cache(mut self, cache: CacheConfig) -> Self {
        self.cache = Some(cache);
        self
    }

    /// Set workflow-level permissions.
    ///
    /// Accepts `(scope, level)` pairs like `("id-token", "write")`.
    /// Entries are sorted by key for deterministic output.
    pub fn with_permissions(mut self, mut perms: Vec<(String, String)>) -> Self {
        perms.sort_by(|a, b| a.0.cmp(&b.0));
        self.permissions = perms;
        self
    }

    /// Set secret names to expose as environment variables in the CI run step.
    pub fn with_secrets_env(mut self, secrets: Vec<String>) -> Self {
        self.secrets_env = secrets;
        self
    }

    /// Build the complete set of environment variables for CI rendering.
    ///
    /// Merges cargo-derived env vars with any manually-added env vars.
    /// Cargo env takes precedence for keys it owns (CARGO_TERM_COLOR, RUSTFLAGS).
    pub fn all_env(&self) -> Vec<(String, String)> {
        let mut result: Vec<(String, String)> = self.cargo_env.to_env_map();
        for (k, v) in &self.env {
            // Don't duplicate keys that cargo_env already provides
            if !result.iter().any(|(rk, _)| rk == k) {
                result.push((k.clone(), v.clone()));
            }
        }
        result
    }
}

