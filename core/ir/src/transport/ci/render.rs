/// Emit a YAML block only if `items` is non-empty.
///
/// Writes `header\n`, then each formatted item as a line, then a trailing blank line.
/// Skips entirely when `items` is empty. This is the standard pattern for
/// YAML sections like `env:`, `variables:`, `branches:`, `stages:`, etc.
pub fn yaml_block<T>(yaml: &mut String, header: &str, items: &[T], fmt: impl Fn(&T) -> String) {
    if items.is_empty() {
        return;
    }
    yaml.push_str(header);
    yaml.push('\n');
    for item in items {
        yaml.push_str(&fmt(item));
        yaml.push('\n');
    }
    yaml.push('\n');
}

/// Checkout configuration.
#[derive(Debug, Clone)]
pub struct CheckoutConfig {
    /// Fetch depth (0 for full history, 1 for shallow).
    pub fetch_depth: Option<u32>,
    /// Submodules config ("true", "recursive", or empty).
    pub submodules: Option<String>,
}

impl Default for CheckoutConfig {
    fn default() -> Self {
        Self {
            fetch_depth: Some(1),
            submodules: None,
        }
    }
}

/// Cache configuration.
#[derive(Debug, Clone)]
pub struct CacheConfig {
    /// Cache key pattern.
    pub key: String,
    /// Paths to cache.
    pub paths: Vec<String>,
    /// Restore keys (fallback).
    pub restore_keys: Vec<String>,
}

impl CacheConfig {
    /// Create a Rust/Cargo cache config.
    ///
    /// The key includes `github.sha` so every run saves a new cache entry
    /// (required for incremental builds — `actions/cache` skips saving on
    /// exact key hit). Restore keys fall back to the closest Cargo.lock match,
    /// then any OS match. GitHub's 10 GB LRU eviction handles cleanup.
    pub fn rust() -> Self {
        Self {
            key: "cargo-${{ runner.os }}-${{ hashFiles('**/Cargo.lock') }}-${{ github.sha }}"
                .to_string(),
            paths: vec![
                "~/.cargo/bin/".to_string(),
                "~/.cargo/registry/index/".to_string(),
                "~/.cargo/registry/cache/".to_string(),
                "~/.cargo/git/db/".to_string(),
                "target/".to_string(),
            ],
            restore_keys: vec![
                "cargo-${{ runner.os }}-${{ hashFiles('**/Cargo.lock') }}-".to_string(),
                "cargo-${{ runner.os }}-".to_string(),
            ],
        }
    }
}

