//! CommentPrefix SubDag: Add comment syntax to content.
//!
//! # I/O Contract
//!
//! Inputs:
//! - `content`: String - Content to comment
//! - `prefix`: String - Comment prefix (e.g., "#", "//", "///")
//! - `multiline`: Bool - Whether to use block comment syntax
//!
//! Outputs:
//! - `commented`: String - Commented content

use crate::dag::{Dag, Port};
use crate::language::LanguageOp;
use crate::node::Node;

/// Comment syntax for a format/language.
#[derive(Debug, Clone)]
pub struct CommentSyntax {
    /// Line comment prefix (e.g., "#", "//")
    pub line_prefix: &'static str,
    /// Block comment start (e.g., "/*")
    pub block_start: Option<&'static str>,
    /// Block comment end (e.g., "*/")
    pub block_end: Option<&'static str>,
    /// Doc comment prefix (e.g., "///", "//!")
    pub doc_prefix: Option<&'static str>,
}

/// Makefile/Shell/YAML/TOML comment syntax.
pub const HASH_COMMENTS: CommentSyntax = CommentSyntax {
    line_prefix: "#",
    block_start: None,
    block_end: None,
    doc_prefix: None,
};

/// Rust comment syntax.
pub const RUST_COMMENTS: CommentSyntax = CommentSyntax {
    line_prefix: "//",
    block_start: Some("/*"),
    block_end: Some("*/"),
    doc_prefix: Some("///"),
};

/// Python comment syntax.
pub const PYTHON_COMMENTS: CommentSyntax = CommentSyntax {
    line_prefix: "#",
    block_start: Some("\"\"\""),
    block_end: Some("\"\"\""),
    doc_prefix: None,
};

/// JavaScript/TypeScript comment syntax.
pub const JS_COMMENTS: CommentSyntax = CommentSyntax {
    line_prefix: "//",
    block_start: Some("/*"),
    block_end: Some("*/"),
    doc_prefix: Some("/**"),
};

/// Build the CommentPrefix SubDag node.
///
/// This SubDag adds comment syntax to content.
///
/// # Example
///
/// ```ignore
/// let comment_node = build_comment_prefix_subdag();
/// // Execute with content = "hello", prefix = "#"
/// // → commented = "# hello"
/// ```
pub fn build_comment_prefix_subdag() -> Node<LanguageOp> {
    let mut inner = Dag::new();

    // Add comment node
    inner.add_node(Node::opaque(
        "add_comment",
        vec![
            Port::scalar("content", "String"),
            Port::scalar("prefix", "String"),
        ],
        vec![Port::scalar("commented", "String")],
        LanguageOp::AddComment,
    ));

    // Create the SubDag node with interface
    Node::subdag("comment_prefix", inner)
}

/// Get comment syntax for a language/format.
pub fn comment_syntax_for(id: &str) -> Option<&'static CommentSyntax> {
    match id {
        "rust" => Some(&RUST_COMMENTS),
        "python" => Some(&PYTHON_COMMENTS),
        "javascript" | "typescript" => Some(&JS_COMMENTS),
        "makefile" | "gitignore" | "yaml" | "toml" | "shell" | "bash" => Some(&HASH_COMMENTS),
        _ => None,
    }
}

/// Add line comments to content.
pub fn add_line_comment(content: &str, prefix: &str) -> String {
    content
        .lines()
        .map(|line| {
            if line.is_empty() {
                prefix.to_string()
            } else {
                format!("{} {}", prefix, line)
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Add block comment to content.
pub fn add_block_comment(content: &str, start: &str, end: &str) -> String {
    format!("{}\n{}\n{}", start, content, end)
}

/// Generate a "DO NOT EDIT" header for generated files.
pub fn generated_header(generator: &str, regenerate_cmd: &str, prefix: &str) -> String {
    format!(
        "{} Generated by {}\n{} DO NOT EDIT - regenerate with: {}",
        prefix, generator, prefix, regenerate_cmd
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_comment_prefix_subdag_is_subdag() {
        let node = build_comment_prefix_subdag();
        assert!(node.is_subdag());
        assert_eq!(node.id.0, "comment_prefix");
    }

    #[test]
    fn test_comment_prefix_subdag_interface() {
        let node = build_comment_prefix_subdag();

        // Check inputs (inferred from inner DAG entrypoints)
        assert_eq!(node.inputs.len(), 2);
        assert!(node.inputs.iter().any(|p| p.name.0 == "content"));
        assert!(node.inputs.iter().any(|p| p.name.0 == "prefix"));

        // Check outputs (inferred from inner DAG boundaries)
        assert_eq!(node.outputs.len(), 1);
        assert!(node.outputs.iter().any(|p| p.name.0 == "commented"));
    }

    #[test]
    fn test_add_line_comment() {
        assert_eq!(add_line_comment("hello", "#"), "# hello");
        assert_eq!(add_line_comment("line1\nline2", "//"), "// line1\n// line2");
        assert_eq!(
            add_line_comment("before\n\nafter", "#"),
            "# before\n#\n# after"
        );
    }

    #[test]
    fn test_add_block_comment() {
        assert_eq!(add_block_comment("content", "/*", "*/"), "/*\ncontent\n*/");
    }

    #[test]
    fn test_generated_header() {
        let header = generated_header(
            "gunbc-makegen",
            "cargo run -p gunbc-dag --bin gunbc-makegen --release",
            "#",
        );
        assert!(header.contains("# Generated by gunbc-makegen"));
        assert!(header.contains(
            "# DO NOT EDIT - regenerate with: cargo run -p gunbc-dag --bin gunbc-makegen --release"
        ));
    }

    #[test]
    fn test_comment_syntax_for() {
        assert_eq!(comment_syntax_for("rust").unwrap().line_prefix, "//");
        assert_eq!(comment_syntax_for("makefile").unwrap().line_prefix, "#");
        assert_eq!(comment_syntax_for("gitignore").unwrap().line_prefix, "#");
    }
}
