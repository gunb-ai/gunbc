//! Emit data-only `.dag` files from structured data.
//!
//! Produces valid `.dag` syntax containing only `module`, `type`, and `data`
//! declarations. No `fn`, `func`, or `service` items. This enables downstream
//! DSL modules to import compiled artifacts as structured data.

use serde_json::Value as JsonValue;

/// A single data entry to emit.
pub struct DataEntry {
    /// Data declaration name (e.g., `entrypoints`).
    pub name: String,
    /// DSL type expression (e.g., `List<EntrypointInfo>`).
    pub type_expr: String,
    /// JSON value to serialize as a DSL literal.
    pub value: JsonValue,
}

/// A type definition to emit.
pub struct TypeDef {
    /// Type name (e.g., `EntrypointInfo`).
    pub name: String,
    /// Fields as `(name, type_expr)` pairs.
    pub fields: Vec<(String, String)>,
}

/// Emit a data-only `.dag` file.
///
/// Produces a valid `.dag` file with:
/// - A `module` declaration
/// - Zero or more `type` definitions
/// - Zero or more `data` declarations
///
/// The output is deterministic (sorted entries, canonical formatting).
pub fn emit_data_dag(module_name: &str, types: &[TypeDef], data: &[DataEntry]) -> String {
    let mut out = String::new();

    // Header
    out.push_str("// Generated by daglang-emit artifact emitter.\n");
    out.push_str("// DO NOT EDIT — regenerate by recompiling the source module.\n\n");
    out.push_str(&format!("module {module_name}\n"));

    // Type definitions
    for ty in types {
        out.push_str(&format!("\ntype {} {{\n", ty.name));
        for (field_name, field_type) in &ty.fields {
            out.push_str(&format!("  {field_name}: {field_type}\n"));
        }
        out.push_str("}\n");
    }

    // Data declarations
    for entry in data {
        out.push('\n');
        let value_str = json_to_dag_literal(&entry.value, 0);
        out.push_str(&format!(
            "data {}: {} = {}\n",
            entry.name, entry.type_expr, value_str
        ));
    }

    out
}

/// Convert a JSON value to a DAG literal expression.
fn json_to_dag_literal(value: &JsonValue, indent: usize) -> String {
    match value {
        JsonValue::Null => "null".to_string(),
        JsonValue::Bool(b) => if *b { "true" } else { "false" }.to_string(),
        JsonValue::Number(n) => n.to_string(),
        JsonValue::String(s) => format!("\"{}\"", escape_dag_string(s)),
        JsonValue::Array(items) => {
            if items.is_empty() {
                return "[]".to_string();
            }
            // Single-line for short lists of scalars
            if items.len() <= 3 && items.iter().all(is_scalar) {
                let inner: Vec<String> = items.iter().map(|v| json_to_dag_literal(v, 0)).collect();
                return format!("[{}]", inner.join(", "));
            }
            let child_indent = indent + 2;
            let pad = " ".repeat(child_indent);
            let close_pad = " ".repeat(indent);
            let mut parts = Vec::new();
            for item in items {
                parts.push(format!("{pad}{}", json_to_dag_literal(item, child_indent)));
            }
            format!("[\n{}\n{close_pad}]", parts.join(",\n"))
        }
        JsonValue::Object(map) => {
            if map.is_empty() {
                return "{}".to_string();
            }
            let child_indent = indent + 2;
            let pad = " ".repeat(child_indent);
            let close_pad = " ".repeat(indent);
            let mut parts = Vec::new();
            for (k, v) in map {
                parts.push(format!(
                    "{pad}{k}: {}",
                    json_to_dag_literal(v, child_indent)
                ));
            }
            format!("{{\n{}\n{close_pad}}}", parts.join(",\n"))
        }
    }
}

/// Escape a string for DAG string literals.
fn escape_dag_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\t', "\\t")
}

/// Check if a JSON value is a scalar (non-nested).
fn is_scalar(v: &JsonValue) -> bool {
    matches!(
        v,
        JsonValue::Null | JsonValue::Bool(_) | JsonValue::Number(_) | JsonValue::String(_)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emit_empty_module() {
        let result = emit_data_dag("generated.empty", &[], &[]);
        assert!(result.contains("module generated.empty"));
        assert!(result.contains("// Generated by daglang-emit"));
    }

    #[test]
    fn emit_type_def() {
        let types = vec![TypeDef {
            name: "EntrypointInfo".to_string(),
            fields: vec![
                ("func_name".to_string(), "String".to_string()),
                ("module".to_string(), "String".to_string()),
            ],
        }];
        let result = emit_data_dag("generated.test", &types, &[]);
        assert!(result.contains("type EntrypointInfo {"));
        assert!(result.contains("  func_name: String"));
        assert!(result.contains("  module: String"));
    }

    #[test]
    fn emit_string_list_data() {
        let data = vec![DataEntry {
            name: "paths".to_string(),
            type_expr: "List<String>".to_string(),
            value: serde_json::json!(["clippy.toml", "Makefile"]),
        }];
        let result = emit_data_dag("generated.test", &[], &data);
        assert!(result.contains("data paths: List<String> = "));
        assert!(result.contains("\"clippy.toml\""));
        assert!(result.contains("\"Makefile\""));
    }

    #[test]
    fn emit_record_list_data() {
        let data = vec![DataEntry {
            name: "entrypoints".to_string(),
            type_expr: "List<EntrypointInfo>".to_string(),
            value: serde_json::json!([
                {"func_name": "pragma", "module": "tools.pragma"},
                {"func_name": "makegen", "module": "tools.makegen"}
            ]),
        }];
        let result = emit_data_dag("generated.test", &[], &data);
        assert!(result.contains("data entrypoints: List<EntrypointInfo>"));
        assert!(result.contains("func_name: \"pragma\""));
        assert!(result.contains("module: \"tools.pragma\""));
    }

    #[test]
    fn json_to_dag_literal_scalars() {
        assert_eq!(json_to_dag_literal(&serde_json::json!(null), 0), "null");
        assert_eq!(json_to_dag_literal(&serde_json::json!(true), 0), "true");
        assert_eq!(json_to_dag_literal(&serde_json::json!(42), 0), "42");
        assert_eq!(
            json_to_dag_literal(&serde_json::json!("hello"), 0),
            "\"hello\""
        );
    }

    #[test]
    fn json_to_dag_literal_escapes_strings() {
        assert_eq!(
            json_to_dag_literal(&serde_json::json!("line1\nline2"), 0),
            "\"line1\\nline2\""
        );
        assert_eq!(
            json_to_dag_literal(&serde_json::json!("say \"hi\""), 0),
            "\"say \\\"hi\\\"\""
        );
    }

    #[test]
    fn emit_empty_list() {
        assert_eq!(json_to_dag_literal(&serde_json::json!([]), 0), "[]");
    }

    #[test]
    fn emit_empty_object() {
        assert_eq!(json_to_dag_literal(&serde_json::json!({}), 0), "{}");
    }
}
