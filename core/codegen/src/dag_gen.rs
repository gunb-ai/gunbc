//! DAG code generation from declarative definitions.
//!
//! Generates complete graph.rs files from DagDef structures,
//! including:
//! - GraphOp enum
//! - Executable impl
//! - build_*_graph() function
//!
//! Uses the Code IR and `RustCodeRenderer` to produce source text.

use crate::registry::{DagDef, EdgeDef, NodeDef, PortDef, ToolDef};
use crate::testgen::render_rust::plain_rust_renderer;
use gunbc_ir::code_ir::*;
use gunbc_ir::language::NamingCase;
use gunbc_ir::render_ir::CodeRenderer;
use gunbc_ir::types::Cardinality;
use std::collections::HashSet;

/// Generate a complete graph.rs file from a tool definition.
pub fn generate_graph_rs(tool: &ToolDef) -> Option<String> {
    let dag = tool.dag.as_ref()?;
    let file = build_source_file(tool, dag);
    Some(plain_rust_renderer().render_source_file(&file))
}

/// Build a `SourceFile` IR for a graph.rs file.
fn build_source_file(tool: &ToolDef, dag: &DagDef) -> SourceFile {
    let mut items = Vec::new();

    // Imports
    for import in build_imports(tool, dag) {
        items.push(import);
    }

    // GraphOp enum
    items.push(build_graph_op_enum(tool, dag));

    // Executable impl
    items.push(build_executable_impl(tool, dag));

    // Graph builder function
    items.push(build_graph_builder(tool, dag));

    SourceFile {
        doc: vec![
            format!("Generated graph builder for {}.", tool.meta.tool_name),
            String::new(),
            "This file is auto-generated by gunbc-codegen.".to_string(),
            "DO NOT EDIT - regenerate with: make daggen".to_string(),
        ],
        items,
    }
}

/// Build import items.
fn build_imports(tool: &ToolDef, dag: &DagDef) -> Vec<Item> {
    let mut items = vec![
        Item::Raw("use gunbc_exec::{ExecError, Executable};".to_string()),
        Item::Raw("use gunbc_ir::{build::*, Dag, Edge, Node, Value};".to_string()),
        Item::Raw("use std::collections::HashMap;".to_string()),
    ];

    // Collect unique operation crates
    let crates: HashSet<&str> = dag
        .nodes
        .iter()
        .map(|n| n.op_crate.as_str())
        .filter(|c| !c.is_empty())
        .collect();

    for crate_name in crates {
        if crate_name == "gunbc_primitives" {
            items.push(Item::Raw("use gunbc_primitives::PrimitiveOp;".to_string()));
        } else {
            items.push(Item::Raw(format!("use {};", crate_name)));
        }
    }

    // Add tool-specific imports if using local ops
    let has_local_ops = dag.nodes.iter().any(|n| n.op_crate.is_empty());
    if has_local_ops {
        items.push(Item::Raw(format!(
            "use crate::ops::{}Op;",
            NamingCase::PascalCase.apply(&tool.meta.tool_name)
        )));
    }

    items
}

/// Build the GraphOp enum item.
fn build_graph_op_enum(tool: &ToolDef, dag: &DagDef) -> Item {
    let enum_name = format!(
        "{}GraphOp",
        NamingCase::PascalCase.apply(&tool.meta.tool_name)
    );

    // Collect unique operation types
    let mut variants = vec![];
    let mut seen = HashSet::new();

    for node in &dag.nodes {
        let variant_name = if node.op_crate == "gunbc_primitives" {
            "Primitive(PrimitiveOp)".to_string()
        } else if node.op_crate.is_empty() {
            format!(
                "Local({}Op)",
                NamingCase::PascalCase.apply(&tool.meta.tool_name)
            )
        } else {
            format!("{}({})", node.op_type, node.op_type)
        };

        if seen.insert(variant_name.clone()) {
            variants.push(variant_name);
        }
    }

    Item::Enum(EnumDef {
        name: enum_name,
        is_pub: true,
        derives: vec!["Debug".to_string(), "Clone".to_string()],
        variants,
        doc: vec![format!(
            "Operation type for {} graphs.",
            tool.meta.tool_name
        )],
    })
}

/// Build the Executable impl item.
fn build_executable_impl(tool: &ToolDef, dag: &DagDef) -> Item {
    let enum_name = format!(
        "{}GraphOp",
        NamingCase::PascalCase.apply(&tool.meta.tool_name)
    );

    // Collect unique match arms
    let mut arms = vec![];
    let mut seen = HashSet::new();

    for node in &dag.nodes {
        let (pattern, delegate) = if node.op_crate == "gunbc_primitives" {
            (
                format!("{}::Primitive(op)", enum_name),
                "op.execute(inputs)".to_string(),
            )
        } else if node.op_crate.is_empty() {
            (
                format!("{}::Local(op)", enum_name),
                "op.execute(inputs)".to_string(),
            )
        } else {
            (
                format!("{}::{}(op)", enum_name, node.op_type),
                "op.execute(inputs)".to_string(),
            )
        };

        if seen.insert(pattern.clone()) {
            arms.push(MatchArm {
                pattern,
                body: vec![Stmt::TailExpr(Expr::RawCode(delegate))],
            });
        }
    }

    Item::Impl(ImplBlock {
        type_name: enum_name,
        trait_name: Some("Executable".to_string()),
        items: vec![FnDef {
            name: "execute".to_string(),
            is_pub: false,
            params: vec![
                ("&self".to_string(), String::new()),
                (
                    "inputs".to_string(),
                    "HashMap<String, Value>".to_string(),
                ),
            ],
            return_type: Some("Result<HashMap<String, Value>, ExecError>".to_string()),
            body: vec![Stmt::TailExpr(Expr::Match {
                expr: Box::new(Expr::Var("self".to_string())),
                arms,
            })],
            doc: vec![],
            attributes: vec![],
        }],
    })
}

/// Build the build_*_graph() function item.
fn build_graph_builder(tool: &ToolDef, dag: &DagDef) -> Item {
    let fn_name = format!("build_{}_graph", tool.meta.tool_name);
    let enum_name = format!(
        "{}GraphOp",
        NamingCase::PascalCase.apply(&tool.meta.tool_name)
    );

    let mut body = vec![];

    // let mut dag = Dag::new();
    body.push(Stmt::Let {
        name: "dag".to_string(),
        mutable: true,
        expr: Expr::RawCode("Dag::new()".to_string()),
    });
    body.push(Stmt::Blank);

    // Node additions
    for node in &dag.nodes {
        body.push(Stmt::Comment(format!("Node: {}", node.id)));
        body.push(Stmt::Expr(Expr::RawCode(generate_node_code(
            node,
            &enum_name,
        ))));
        body.push(Stmt::Blank);
    }

    // Edge additions
    body.push(Stmt::Comment("Wire up the pipeline".to_string()));
    for edge in &dag.edges {
        body.push(Stmt::Expr(Expr::RawCode(generate_edge_code(edge))));
    }
    body.push(Stmt::Blank);

    // Return
    body.push(Stmt::TailExpr(Expr::Var("dag".to_string())));

    // Parse args string into params vec
    let params = if tool.meta.graph_builder_args.is_empty() {
        vec![]
    } else {
        // The args string is like "extensions: Vec<String>, public: bool"
        // We pass it as a single raw param to preserve the exact format
        vec![(tool.meta.graph_builder_args.clone(), String::new())]
    };

    Item::Fn(FnDef {
        name: fn_name,
        is_pub: true,
        params,
        return_type: Some(format!("Dag<{}>", enum_name)),
        body,
        doc: vec![format!("Build the {} graph.", tool.meta.tool_name)],
        attributes: vec![],
    })
}

/// Generate code for a single node (raw expression text).
fn generate_node_code(node: &NodeDef, enum_name: &str) -> String {
    let inputs = node
        .inputs
        .iter()
        .map(generate_port_code)
        .collect::<Vec<_>>()
        .join(", ");

    let outputs = node
        .outputs
        .iter()
        .map(generate_port_code)
        .collect::<Vec<_>>()
        .join(", ");

    let op = if node.op_crate == "gunbc_primitives" {
        format!("{}::Primitive(PrimitiveOp::{})", enum_name, node.op_variant)
    } else if node.op_crate.is_empty() {
        format!("{}::Local({})", enum_name, node.op_variant)
    } else {
        format!("{}::{}({})", enum_name, node.op_type, node.op_variant)
    };

    format!(
        "dag.add_node(Node::opaque(\n\
         \x20       \"{id}\",\n\
         \x20       vec![{inputs}],\n\
         \x20       vec![{outputs}],\n\
         \x20       {op},\n\
         \x20   ))",
        id = node.id,
        inputs = inputs,
        outputs = outputs,
        op = op,
    )
}

/// Generate code for a single port.
fn generate_port_code(port: &PortDef) -> String {
    if port.cardinality == Cardinality::ONE {
        format!("port(\"{}\", \"{}\")", port.name, port.type_id)
    } else if port.cardinality == Cardinality::ZERO_OR_ONE {
        format!("optional(\"{}\", \"{}\")", port.name, port.type_id)
    } else if port.cardinality == Cardinality::ZERO_OR_MORE {
        format!("list(\"{}\", \"{}\")", port.name, port.type_id)
    } else if port.cardinality == Cardinality::ONE_OR_MORE {
        format!("non_empty_list(\"{}\", \"{}\")", port.name, port.type_id)
    } else {
        format!(
            "Port::with_cardinality(\"{}\", \"{}\", Cardinality::new({}, {}))",
            port.name,
            port.type_id,
            port.cardinality.min,
            match port.cardinality.max {
                Some(m) => format!("Some({})", m),
                None => "None".to_string(),
            }
        )
    }
}

/// Generate code for a single edge.
fn generate_edge_code(edge: &EdgeDef) -> String {
    format!(
        "dag.add_edge(Edge::new(\"{}\", \"{}\", \"{}\", \"{}\"))",
        edge.from_node, edge.from_port, edge.to_node, edge.to_port
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry::all_tools;

    #[test]
    fn test_generate_port_code() {
        let port = PortDef::scalar("input", "String");
        assert_eq!(generate_port_code(&port), "port(\"input\", \"String\")");

        let port = PortDef::optional("input", "String");
        assert_eq!(generate_port_code(&port), "optional(\"input\", \"String\")");

        let port = PortDef::list("items", "String");
        assert_eq!(generate_port_code(&port), "list(\"items\", \"String\")");
    }

    #[test]
    fn test_naming_case_pascal() {
        // Verify language module's PascalCase works for type names
        assert_eq!(NamingCase::PascalCase.apply("makegen"), "Makegen");
        assert_eq!(NamingCase::PascalCase.apply("buck2"), "Buck2");
        assert_eq!(NamingCase::PascalCase.apply(""), "");
    }

    #[test]
    fn test_generate_makegen_graph() {
        // Find makegen tool
        let makegen = all_tools()
            .into_iter()
            .find(|t| t.meta.tool_name == "makegen")
            .expect("makegen tool should exist");

        // Check that it has a DAG definition
        assert!(makegen.has_dag(), "makegen should have a declarative DAG");

        // Generate the graph.rs
        let graph_rs = generate_graph_rs(&makegen);
        assert!(graph_rs.is_some(), "should generate graph.rs");

        let code = graph_rs.unwrap();

        // Verify key components are present
        assert!(
            code.contains("MakegenGraphOp"),
            "should have MakegenGraphOp enum"
        );
        assert!(
            code.contains("build_makegen_graph"),
            "should have build function"
        );
        assert!(
            code.contains("load_registry"),
            "should have load_registry node"
        );
        assert!(
            code.contains("render_makefile"),
            "should have render_makefile node"
        );
        assert!(
            code.contains("write_makefile"),
            "should have write_makefile node"
        );
    }
}
