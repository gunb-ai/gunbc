//! CLI contract test generation.
//!
//! Generates integration tests that call `gunbc_cli::parse()` in-process
//! to verify that each tool's CLI schema parses sample arguments correctly.
//! No subprocess spawning — tests are fast and immune to binary-name issues.

use crate::cli_gen::CliEntrypoint;
use crate::registry::ToolDef;
use std::collections::BTreeMap;

#[derive(Debug, Clone)]
pub struct CliContractTool {
    pub tool_name: String,
    pub bin_name: String,
    pub entrypoints: Vec<CliEntrypoint>,
}

/// Group tools by cargo package for per-crate CLI contract test generation.
pub fn group_cli_contract_tools(tools: &[ToolDef]) -> BTreeMap<String, Vec<CliContractTool>> {
    let mut grouped: BTreeMap<String, Vec<CliContractTool>> = BTreeMap::new();

    for tool in tools {
        let Some(invocation) = &tool.invocation else {
            continue;
        };

        let package = invocation
            .package
            .as_ref()
            .unwrap_or(&invocation.binary)
            .clone();

        grouped
            .entry(package)
            .or_default()
            .push(CliContractTool {
                tool_name: tool.meta.tool_name.clone(),
                bin_name: invocation.binary.clone(),
                entrypoints: tool.entrypoints.clone(),
            });
    }

    for tools in grouped.values_mut() {
        tools.sort_by(|a, b| a.tool_name.cmp(&b.tool_name));
    }

    grouped
}

/// Render a CLI contract test file for a crate's tools.
///
/// Generated tests use `gunbc_cli::parse()` for in-process argument parsing
/// instead of spawning subprocesses.
pub fn render_cli_contract_tests(tools: &[CliContractTool]) -> String {
    let mut out = String::new();

    out.push_str("// Generated by gunbc-codegen.\n");
    out.push_str("// DO NOT EDIT - regenerate with: make codegen\n\n");

    let needs_cardinality = tools
        .iter()
        .any(|t| t.entrypoints.iter().any(|ep| ep.is_repeatable()));

    out.push_str("use gunbc_cli::{parse, CliParam};\n");
    if needs_cardinality {
        out.push_str("use gunbc_ir::{Cardinality, Value};\n");
    } else {
        out.push_str("use gunbc_ir::Value;\n");
    }
    out.push_str("use gunbc_test::{guard_test, FermiCost, TestClass};\n\n");

    for tool in tools {
        out.push_str(&render_tool_test(tool));
        out.push('\n');
    }

    out
}

fn render_tool_test(tool: &CliContractTool) -> String {
    let test_name = format!("cli_contract_{}", sanitize_ident(&tool.tool_name));
    let guard_name = format!("cli_contract_{}", tool.tool_name);

    // Build schema construction lines
    let mut schema_lines: Vec<String> = Vec::new();
    for ep in &tool.entrypoints {
        let mut chain = format!("        CliParam::new(\"{}\", \"{}\")", ep.port_name, ep.type_id);
        if ep.cardinality.allows_many() {
            chain.push_str(".with_cardinality(Cardinality::ZERO_OR_MORE)");
        }
        if let Some(c) = ep.short_flag {
            chain.push_str(&format!(".short('{}')", c));
        }
        if let Some(ref d) = ep.default_value {
            chain.push_str(&format!(".default(\"{}\")", escape_rust_string(d)));
        }
        chain.push(',');
        schema_lines.push(chain);
    }

    // Build argv entries and assertions
    let mut argv_entries: Vec<String> = vec![
        format!("\"{}\"", tool.tool_name),
        "\"--dry-run\"".to_string(),
    ];
    let mut assertions: Vec<String> = Vec::new();

    for ep in &tool.entrypoints {
        let flag = format!("--{}", ep.flag_name());
        if ep.is_repeatable() {
            let (v1, v2) = sample_repeatable_values(ep);
            argv_entries.push(format!("\"{}\"", escape_rust_string(&flag)));
            argv_entries.push(format!("\"{}\"", escape_rust_string(&v1)));
            argv_entries.push(format!("\"{}\"", escape_rust_string(&flag)));
            argv_entries.push(format!("\"{}\"", escape_rust_string(&v2)));

            assertions.push(format!(
                "    assert_eq!(\n        result.values[\"{}\"],\n        Value::str_list(vec![\"{}\".into(), \"{}\".into()]),\n        \"repeatable param '{}' mismatch\"\n    );",
                ep.port_name,
                escape_rust_string(&v1),
                escape_rust_string(&v2),
                ep.port_name
            ));
            continue;
        }

        match ep.type_id.as_str() {
            "Bool" => {
                argv_entries.push(format!("\"{}\"", escape_rust_string(&flag)));
                assertions.push(format!(
                    "    assert_eq!(result.values[\"{}\"], Value::Bool(true), \"bool param '{}' mismatch\");",
                    ep.port_name, ep.port_name
                ));
            }
            "Int" => {
                let value = sample_int_value(ep);
                argv_entries.push(format!("\"{}\"", escape_rust_string(&flag)));
                argv_entries.push(format!("\"{}\"", escape_rust_string(&value)));
                assertions.push(format!(
                    "    assert_eq!(result.values[\"{}\"], Value::Int({}), \"int param '{}' mismatch\");",
                    ep.port_name, value, ep.port_name
                ));
            }
            _ => {
                let value = sample_string_value(ep);
                argv_entries.push(format!("\"{}\"", escape_rust_string(&flag)));
                argv_entries.push(format!("\"{}\"", escape_rust_string(&value)));
                assertions.push(format!(
                    "    assert_eq!(result.values[\"{}\"], Value::Str(\"{}\".into()), \"string param '{}' mismatch\");",
                    ep.port_name,
                    escape_rust_string(&value),
                    ep.port_name
                ));
            }
        }
    }

    // dry_run assertion
    assertions.push("    assert!(result.dry_run, \"dry_run should be true\");".to_string());

    let argv_str = argv_entries.join(", ");

    let mut body = String::new();
    body.push_str(&format!("#[test]\nfn {}() {{\n", test_name));
    body.push_str(&format!(
        "    if !guard_test(\"{}\", TestClass::Hermetic, FermiCost::XS, &[], &[]) {{\n",
        guard_name
    ));
    body.push_str("        return;\n    }\n");
    body.push_str("    let schema = vec![\n");
    for line in &schema_lines {
        body.push_str(line);
        body.push('\n');
    }
    body.push_str("    ];\n");
    body.push_str(&format!(
        "    let argv: Vec<String> = [{}]\n        .iter().map(|s| s.to_string()).collect();\n",
        argv_str
    ));
    body.push_str("    let result = parse(&argv, &schema).expect(\"parse should succeed\");\n");

    for assertion in &assertions {
        body.push_str(assertion);
        body.push('\n');
    }

    body.push_str("}\n");
    body
}

fn sanitize_ident(name: &str) -> String {
    let mut out = String::new();
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

fn sample_string_value(ep: &CliEntrypoint) -> String {
    let lower = ep.port_name.to_lowercase();
    let mut value = if lower.contains("repo") {
        "test-repo".to_string()
    } else if lower.contains("manifest") {
        "deps.toml".to_string()
    } else if lower == "path" || lower.contains("makefile") {
        "Makefile.test".to_string()
    } else if lower.contains("path") {
        "out/path".to_string()
    } else if lower.contains("base") || lower.contains("branch") || lower.contains("ref") {
        "feature/test".to_string()
    } else if lower.contains("ext") {
        ".rs".to_string()
    } else {
        format!("{}_value", ep.port_name)
    };

    if let Some(default) = ep.default_value.as_deref() {
        if value == default {
            value = format!("{}_override", ep.port_name);
        }
    }

    value
}

fn sample_int_value(ep: &CliEntrypoint) -> String {
    let mut value = "42".to_string();
    if let Some(default) = ep.default_value.as_deref() {
        if default == value {
            value = "7".to_string();
        }
    }
    value
}

fn sample_repeatable_values(ep: &CliEntrypoint) -> (String, String) {
    let lower = ep.port_name.to_lowercase();
    if lower.contains("ext") {
        return (".rs".to_string(), ".toml".to_string());
    }

    let first = format!("{}_one", ep.port_name);
    let second = format!("{}_two", ep.port_name);
    (first, second)
}

fn escape_rust_string(value: &str) -> String {
    let mut out = String::new();
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(ch),
        }
    }
    out
}
