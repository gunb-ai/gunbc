use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR should be set"));
    let generated_dir = manifest_dir.join("src/generated");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR should be set"));
    let out_file = out_dir.join("generated_tests_mods.rs");

    println!("cargo:rerun-if-changed={}", generated_dir.display());

    let mut generated_files = generated_module_paths(&generated_dir);
    generated_files.sort();

    let mut output = String::from("// @generated by build.rs\n");
    for path in &generated_files {
        println!("cargo:rerun-if-changed={}", path.display());
        let stem = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .expect("generated test file should have a UTF-8 stem");
        output.push_str(&format!("#[path = {:?}]\nmod {};\n", path, stem));
    }

    fs::write(out_file, output).expect("should write generated module index");
}

fn generated_module_paths(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Vec::new();
    };

    entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("rs"))
        .collect()
}
