#[derive(Clone, Debug, PartialEq, Eq)]
enum Locator {
    Exact(String),
    Family {
        dir: String,
        prefix: String,
        suffix: String,
    },
}

#[derive(Clone, Debug)]
struct RegistryRow {
    kind: String,
    locator: Locator,
    phase: String,
    journal_phase: String,
    #[allow(dead_code)]
    required_for_settlement: bool,
    optional_worker: bool,
}

fn parse_locator(pattern: &str) -> Result<Locator, String> {
    if !pattern.contains('*') {
        if pattern.is_empty() {
            return Err("empty locator pattern".to_string());
        }
        return Ok(Locator::Exact(pattern.to_string()));
    }
    let (dir, filename) = pattern
        .rsplit_once('/')
        .ok_or_else(|| format!("family locator {pattern:?} has no directory component"))?;
    let (prefix, suffix) = filename
        .split_once('*')
        .ok_or_else(|| format!("family locator {pattern:?} has no wildcard in its filename"))?;
    if suffix.contains('*') || dir.contains('*') {
        return Err(format!(
            "family locator {pattern:?} carries more than one wildcard"
        ));
    }
    Ok(Locator::Family {
        dir: dir.to_string(),
        prefix: prefix.to_string(),
        suffix: suffix.to_string(),
    })
}

fn parse_registry_rows(text: &str) -> Result<Vec<RegistryRow>, String> {
    let mut rows: Vec<RegistryRow> = Vec::new();
    for (index, raw) in text.lines().enumerate() {
        let line = raw.trim_end_matches('\r');
        if line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split('|').collect();
        if parts.len() != 5 {
            return Err(format!(
                "registry line {} has {} fields, expected 5: {line:?}",
                index + 1,
                parts.len()
            ));
        }
        let required_for_settlement = match parts[4] {
            "1" => true,
            "0" => false,
            other => {
                return Err(format!(
                    "registry line {} has required_for_settlement={other:?}, expected 0 or 1",
                    index + 1
                ))
            }
        };
        let phase = parts[2].to_string();
        rows.push(RegistryRow {
            kind: parts[0].to_string(),
            locator: parse_locator(parts[1])
                .map_err(|e| format!("registry line {}: {e}", index + 1))?,
            optional_worker: phase == "OptionalWorker",
            phase,
            journal_phase: parts[3].to_string(),
            required_for_settlement,
        });
    }
    if rows.is_empty() {
        return Err("registry fingerprint carries zero rows".to_string());
    }
    for i in 0..rows.len() {
        for j in (i + 1)..rows.len() {
            if rows[i].kind == rows[j].kind {
                return Err(format!("registry carries duplicate kind {}", rows[i].kind));
            }
        }
    }
    Ok(rows)
}

/// The registry, parsed once from the generated bytes. A malformed generated file is a
/// build-artifact defect with no honest degraded reading — the process stops rather than
/// running against a partial row set it would then report as complete.
fn rows() -> &'static [RegistryRow] {
    static ROWS: OnceLock<Vec<RegistryRow>> = OnceLock::new();
    ROWS.get_or_init(|| {
        parse_registry_rows(FLOOR_EVIDENCE_REGISTRY_FINGERPRINT).unwrap_or_else(|e| {
            panic!("dag/gunbc/ci_floor_population_receipt_registry.fingerprint is unparseable: {e}")
        })
    })
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PhaseStandingExact {
    PhaseNotReached,
    PhaseEntered,
    PhaseCompleted,
    PhaseRefused,
    PhaseInterrupted,
    PhaseStandingUnknown,
}

fn pattern_of(locator: &Locator) -> String {
    match locator {
        Locator::Exact(p) => p.clone(),
        Locator::Family {
            dir,
            prefix,
            suffix,
        } => format!("{dir}/{prefix}*{suffix}"),
    }
}

/// Port of `.dag` `registry_locator_matches_relpath`, in the strict reading the
/// observation join already used: a family path must sit directly under the declared
/// directory with the declared prefix/suffix, not merely contain those substrings.
fn locator_matches_relpath(locator: &Locator, path: &str) -> bool {
    if path.contains('*') {
        return false;
    }
    match locator {
        Locator::Exact(p) => path == p,
        Locator::Family {
            dir,
            prefix,
            suffix,
        } => {
            let dir_prefix = format!("{dir}/");
            let Some(filename) = path.strip_prefix(&dir_prefix) else {
                return false;
            };
            filename.starts_with(prefix.as_str())
                && filename.ends_with(suffix.as_str())
                && filename.len() >= prefix.len() + suffix.len()
        }
    }
}

fn fingerprint_from_rows() -> String {
    rows()
        .iter()
        .map(|r| {
            format!(
                "{}|{}|{}|{}|{}",
                r.kind,
                pattern_of(&r.locator),
                r.phase,
                r.journal_phase,
                if r.required_for_settlement { "1" } else { "0" }
            )
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn find_row(kind: &str) -> Option<&'static RegistryRow> {
    rows().iter().find(|r| r.kind == kind)
}

fn is_family_kind(kind: &str) -> bool {
    matches!(
        find_row(kind).map(|r| &r.locator),
        Some(Locator::Family { .. })
    )
}

pub fn floor_evidence_root(attempt: &str) -> PathBuf {
    PathBuf::from(EVIDENCE_ROOT_PREFIX).join(attempt)
}

fn sha256_bytes(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

fn sha256_file(path: &Path) -> Result<(u64, String), String> {
    let bytes = fs::read(path).map_err(|e| format!("read {}: {e}", path.display()))?;
    Ok((bytes.len() as u64, sha256_bytes(&bytes)))
}

fn relative_path_escapes_root(relative_path: &str) -> bool {
    if relative_path.is_empty()
        || relative_path.starts_with('/')
        || relative_path.contains("..")
        || Path::new(relative_path).is_absolute()
    {
        return true;
    }
    for c in Path::new(relative_path).components() {
        if matches!(
            c,
            std::path::Component::ParentDir | std::path::Component::RootDir
        ) {
            return true;
        }
    }
    false
}

/// Observation-fragment filename for one receipt (blocker 5, #7785 commit 4A). A
/// singleton kind (any `Locator::Exact` row) owns exactly one fragment file named after
/// the kind, so a second write for the same kind is a filesystem-visible collision
/// rather than a silently-appended row; a family kind (`WorkerTerminal`) is keyed by the
/// receipt's own basename so N workers get N fragments.
fn observation_fragment_relpath(kind: &str, relative_path: &str) -> String {
    if is_family_kind(kind) {
        let basename = Path::new(relative_path)
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_else(|| relative_path.to_string());
        format!("{OBSERVATIONS_DIR}/{kind}-{basename}.obs.tsv")
    } else {
        format!("{OBSERVATIONS_DIR}/{kind}.obs.tsv")
    }
}

/// Atomic write under `target/floor-evidence/<attempt>/` plus an atomic per-receipt
/// observation fragment (blocker 5, #7785 commit 4A): write receipt tmp → write obs tmp
/// → rename receipt → rename obs — a best-effort atomic PAIR, not a single fsync unit.
/// A crash between the two renames leaves a published receipt with no observation
/// fragment, which the finalizer reads as `MissingAfterProducerReached` (a real, typed
/// state) rather than as a false `ObservedPresent` — it never claims presence it cannot
/// prove, and it never partially-writes a shared file that a concurrent worker could
/// also be appending to (the defect this fragment split replaces).
pub fn write_floor_receipt(
    attempt: &str,
    kind: &str,
    relative_path: &str,
    body: &[u8],
    producer_phase: &str,
) -> Result<PathBuf, String> {
    if relative_path_escapes_root(relative_path) {
        return Err(format!(
            "write_floor_receipt refused unsafe relative path {relative_path:?}"
        ));
    }
    // The write side is held to the SAME registry contract as the load side (#7785
    // commit 4B). Validating only on load meant a producer could publish a receipt at a
    // path its kind does not own and learn about it, at best, one finalize later.
    let row = find_row(kind).ok_or_else(|| {
        format!("write_floor_receipt refused unknown kind {kind:?} — not a row in the floor-evidence registry")
    })?;
    if producer_phase != row.phase {
        return Err(format!(
            "write_floor_receipt refused {kind} declaring producer_phase={producer_phase:?}; registry row expects {:?}",
            row.phase
        ));
    }
    if !locator_matches_relpath(&row.locator, relative_path) {
        return Err(format!(
            "write_floor_receipt refused UnknownObservedPath: {kind} owns {} but was asked to write {relative_path:?}",
            pattern_of(&row.locator)
        ));
    }
    let singleton = matches!(row.locator, Locator::Exact(_));

    let root = floor_evidence_root(attempt);
    let path = root.join(relative_path);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("mkdir {}: {e}", parent.display()))?;
    }
    let digest = sha256_bytes(body);
    let obs_rel = observation_fragment_relpath(kind, relative_path);
    let obs_path = root.join(&obs_rel);

    // A singleton kind is published exactly once per attempt. Renaming over an existing
    // receipt destroyed the earlier bytes AND left the observation fragment describing
    // whichever write happened to land last — an attempt's evidence silently rewritten
    // rather than a second producer refused.
    if singleton {
        if path.exists() {
            return Err(format!(
                "write_floor_receipt refused replacement of singleton {kind} receipt already published at {}",
                path.display()
            ));
        }
        if obs_path.exists() {
            return Err(format!(
                "write_floor_receipt refused replacement of singleton {kind} observation fragment already published at {}",
                obs_path.display()
            ));
        }
    }

    let receipt_tmp = path.with_extension(format!("tmp-{}", std::process::id()));
    let _ = fs::remove_file(&receipt_tmp);
    {
        let mut f = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&receipt_tmp)
            .map_err(|e| format!("write {}: {e}", receipt_tmp.display()))?;
        f.write_all(body)
            .map_err(|e| format!("write {}: {e}", receipt_tmp.display()))?;
    }

    if let Some(parent) = obs_path.parent() {
        if let Err(e) = fs::create_dir_all(parent) {
            let _ = fs::remove_file(&receipt_tmp);
            return Err(format!("mkdir {}: {e}", parent.display()));
        }
    }
    let obs_body = format!(
        "{kind}\t{relative_path}\t{}\t{digest}\t{producer_phase}\n",
        body.len()
    );
    let obs_tmp = obs_path.with_extension(format!("tmp-{}", std::process::id()));
    if let Err(e) = fs::write(&obs_tmp, obs_body.as_bytes()) {
        let _ = fs::remove_file(&receipt_tmp);
        return Err(format!("write {}: {e}", obs_tmp.display()));
    }

    if let Err(e) = fs::rename(&receipt_tmp, &path) {
        let _ = fs::remove_file(&receipt_tmp);
        let _ = fs::remove_file(&obs_tmp);
        return Err(format!("publish {}: {e}", path.display()));
    }
    if let Err(e) = fs::rename(&obs_tmp, &obs_path) {
        let _ = fs::remove_file(&obs_tmp);
        return Err(format!("publish {}: {e}", obs_path.display()));
    }
    Ok(path)
}

pub fn install_floor_evidence_root(attempt: &str) -> Result<PathBuf, String> {
    let root = floor_evidence_root(attempt);
    fs::create_dir_all(&root).map_err(|e| format!("mkdir {}: {e}", root.display()))?;
    let journal = root.join(PHASE_JOURNAL_REL);
    if let Some(parent) = journal.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("mkdir {}: {e}", parent.display()))?;
    }
    // Touch so the dump step can distinguish absent vs empty when read.
    if !journal.exists() {
        fs::write(&journal, "").map_err(|e| format!("touch {}: {e}", journal.display()))?;
    }
    // No legacy `target/floor-phase-journal.tsv` symlink/copy (#7785 commit 4A, blocker 2):
    // the workflow composes the SAME attempt-scoped path directly at the GitHub Actions
    // expression level (v2.workflow.ci_floor_peak_emit `ci_floor_phase_journal_path`), so
    // every consumer — this process, the peak-post step, the falsifier step — reads the
    // one real file rather than a second alias that a stale symlink target could break.
    let journal_for_env = journal.canonicalize().unwrap_or_else(|_| journal.clone());
    std::env::set_var("GUNBC_FLOOR_PHASE_JOURNAL", &journal_for_env);
    Ok(root)
}

fn parse_state(state: &str) -> PhaseStandingExact {
    let s = state.trim().to_ascii_lowercase();
    if s.contains("interrupt") || s.contains("killed") || s.contains("abort") || s == "interrupted"
    {
        PhaseStandingExact::PhaseInterrupted
    } else if s == "completed" || s == "passed" {
        PhaseStandingExact::PhaseCompleted
    } else if s == "refused" || s == "failed" {
        PhaseStandingExact::PhaseRefused
    } else if s == "started" || s == "running" || s == "entered" {
        PhaseStandingExact::PhaseEntered
    } else {
        PhaseStandingExact::PhaseStandingUnknown
    }
}

fn merge_standing(cur: PhaseStandingExact, next: PhaseStandingExact) -> PhaseStandingExact {
    use PhaseStandingExact::*;
    match (cur, next) {
        (_, PhaseInterrupted) | (PhaseInterrupted, _) => PhaseInterrupted,
        (_, PhaseRefused) | (PhaseRefused, _) => PhaseRefused,
        (_, PhaseCompleted) | (PhaseCompleted, _) => PhaseCompleted,
        (_, PhaseEntered) | (PhaseEntered, _) => PhaseEntered,
        (PhaseStandingUnknown, other) | (other, PhaseStandingUnknown) => other,
        (PhaseNotReached, other) => other,
    }
}

/// Which invocations may answer for a phase (#7785 commit 4B). The floor journal is one
/// append log written by SEVERAL processes: a coordinator plus the workers it spawns.
/// Reducing it to `phase -> standing` let any writer answer for any phase, so a child's
/// `completed` could stand in for a coordinator-owned phase the coordinator never
/// entered — a false claim about who did what, in the file whose only job is saying so.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StandingScope {
    /// Invocations with no parent — the process the CI step actually launched.
    Root,
    /// Invocations spawned by another executor invocation (floor workers).
    NonRoot,
}

/// Phase standing keyed by `(invocation, phase)`. Standings merge only WITHIN one
/// invocation (a phase legitimately moves started -> completed inside one process);
/// across invocations they are kept apart and read through a declared scope.
#[derive(Clone, Debug, Default)]
pub struct PhaseJournalIndex {
    standing: HashMap<(String, String), PhaseStandingExact>,
    parent_of: HashMap<String, String>,
    conflicting_parent: Vec<String>,
}

fn normalize_parent(raw: &str) -> String {
    let trimmed = raw.trim();
    if trimmed == "-" {
        String::new()
    } else {
        trimmed.to_string()
    }
}

pub fn parse_phase_journal(body: &str) -> PhaseJournalIndex {
    let mut index = PhaseJournalIndex::default();
    for line in body.lines() {
        let line = line.trim_end_matches(['\r', '\n']);
        if line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split('\t').collect();
        // unix_millis walk_attempt invocation parent plan_site pid phase state detail
        let (invocation, parent, phase, state) = if parts.len() >= 9 {
            (
                parts[2].trim().to_string(),
                normalize_parent(parts[3]),
                parts[6].to_string(),
                parts[7],
            )
        } else if parts.len() >= 4 {
            // Backward compatibility with the pre-4B five-column shape
            // (`millis pid phase state detail`): a writer that predates invocation
            // identity is read as an unparented invocation named after its pid, never
            // silently folded into whichever invocation happens to be first.
            (
                format!("legacy-{}", parts[1].trim()),
                String::new(),
                parts[2].to_string(),
                parts[3],
            )
        } else {
            continue;
        };
        if invocation.is_empty() {
            continue;
        }
        match index.parent_of.get(&invocation) {
            Some(existing) if *existing != parent => {
                if !index.conflicting_parent.contains(&invocation) {
                    index.conflicting_parent.push(invocation.clone());
                }
            }
            Some(_) => {}
            None => {
                index.parent_of.insert(invocation.clone(), parent);
            }
        }
        let standing = parse_state(state);
        let entry = index
            .standing
            .entry((invocation, phase))
            .or_insert(PhaseStandingExact::PhaseNotReached);
        *entry = merge_standing(*entry, standing);
    }
    index
}

impl PhaseJournalIndex {
    fn invocation_in_scope(&self, invocation: &str, scope: StandingScope) -> bool {
        let is_root = self
            .parent_of
            .get(invocation)
            .map(|p| p.is_empty())
            .unwrap_or(false);
        match scope {
            StandingScope::Root => is_root,
            StandingScope::NonRoot => !is_root,
        }
    }

    /// Standing for `phase` as written by invocations in `scope`. Invocations that never
    /// wrote the phase contribute nothing (`PhaseNotReached` when none did). Two
    /// invocations in the same scope that DISAGREE about a phase refuse: merging them
    /// would fabricate one standing out of two genuinely different observations.
    pub fn standing_in_scope(
        &self,
        phase: &str,
        scope: StandingScope,
    ) -> Result<PhaseStandingExact, String> {
        if !self.conflicting_parent.is_empty() {
            return Err(format!(
                "phase journal declares conflicting parents for invocation(s) {:?}",
                self.conflicting_parent
            ));
        }
        let mut found: Vec<(&str, PhaseStandingExact)> = self
            .standing
            .iter()
            .filter(|((inv, ph), _)| ph == phase && self.invocation_in_scope(inv, scope))
            .map(|((inv, _), standing)| (inv.as_str(), *standing))
            .collect();
        found.sort_by(|a, b| a.0.cmp(b.0));
        match found.split_first() {
            None => Ok(PhaseStandingExact::PhaseNotReached),
            Some((&(_, first), rest)) => {
                if let Some((inv, other)) = rest.iter().find(|(_, s)| *s != first) {
                    return Err(format!(
                        "phase {phase:?} has divergent standings across {scope:?} invocations: {}={:?} vs {inv}={other:?}",
                        found[0].0, first
                    ));
                }
                Ok(first)
            }
        }
    }

    fn standing_for_row(&self, row: &RegistryRow) -> Result<PhaseStandingExact, String> {
        for scope in producer_phase_scopes(&row.phase) {
            let standing = self.standing_in_scope(&row.journal_phase, *scope)?;
            if standing != PhaseStandingExact::PhaseNotReached {
                return Ok(standing);
            }
        }
        Ok(PhaseStandingExact::PhaseNotReached)
    }
}

/// Which invocations own a producer phase, in the order they may answer for it.
///
/// `OptionalWorker` and `AfterFloorAlways` are coordinator facts: the coordinator
/// observes its workers and finalizes the attempt, so ONLY a root invocation may answer
/// for them — this is what stops a worker's own row from standing in for the
/// coordinator's observation.
///
/// The remaining phases belong to whichever process runs the walk. Under the CI floor
/// coordinator that is a spawned worker; a plan with no coordinator (the falsifier, a
/// local run) runs the walk in the root process itself. Both are named, worker first, so
/// the answer comes from the walk process in either topology rather than being reported
/// as never-reached in one of them.
fn producer_phase_scopes(producer_phase: &str) -> &'static [StandingScope] {
    match producer_phase {
        "OptionalWorker" | "AfterFloorAlways" => &[StandingScope::Root],
        _ => &[StandingScope::NonRoot, StandingScope::Root],
    }
}

fn standing_label_missing(optional_worker: bool, phase: PhaseStandingExact) -> &'static str {
    match phase {
        PhaseStandingExact::PhaseNotReached | PhaseStandingExact::PhaseStandingUnknown => {
            if optional_worker {
                "NotApplicable"
            } else {
                "MissingBeforeProducerReached"
            }
        }
        PhaseStandingExact::PhaseEntered
        | PhaseStandingExact::PhaseCompleted
        | PhaseStandingExact::PhaseRefused => "MissingAfterProducerReached",
        PhaseStandingExact::PhaseInterrupted => "ProducerInterrupted",
    }
}

#[derive(Clone, Debug)]
struct Observation {
    kind: String,
    relative_path: String,
    size: u64,
    digest: String,
    #[allow(dead_code)]
    producer_phase: String,
}

/// Enumerate `observations/*.obs.tsv` fragments only (blocker 5, #7785 commit 4A) — never
/// a shared append-log. Refuses loudly (never silently ignores) on: an unknown kind, a
/// path that escapes `FloorEvidenceRoot`, a second fragment for a singleton kind, a
/// duplicate `(kind, path)` pair, or a fragment whose declared `producer_phase` disagrees
/// with the registry row it names.
fn load_observation_fragments(root: &Path) -> Result<Vec<Observation>, String> {
    let dir = root.join(OBSERVATIONS_DIR);
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut fragment_paths: Vec<PathBuf> = fs::read_dir(&dir)
        .map_err(|e| format!("read {}: {e}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|p| {
            p.file_name()
                .map(|n| n.to_string_lossy().ends_with(".obs.tsv"))
                .unwrap_or(false)
        })
        .collect();
    // Deterministic order so a duplicate refusal names the same pair on every run.
    fragment_paths.sort();

    let mut out: Vec<Observation> = Vec::new();
    for frag_path in &fragment_paths {
        let body = fs::read_to_string(frag_path)
            .map_err(|e| format!("read {}: {e}", frag_path.display()))?;
        let lines: Vec<&str> = body.lines().filter(|l| !l.trim().is_empty()).collect();
        if lines.len() != 1 {
            return Err(format!(
                "observation fragment {} must carry exactly one row, found {}",
                frag_path.display(),
                lines.len()
            ));
        }
        let parts: Vec<&str> = lines[0].split('\t').collect();
        if parts.len() != 5 {
            return Err(format!(
                "malformed observation fragment row in {}: {:?}",
                frag_path.display(),
                lines[0]
            ));
        }
        let kind = parts[0].to_string();
        let rel = parts[1].to_string();
        let size: u64 = parts[2].parse().map_err(|_| {
            format!(
                "bad size in observation fragment {}: {:?}",
                frag_path.display(),
                lines[0]
            )
        })?;
        let digest = parts[3].to_string();
        let producer_phase = parts[4].to_string();

        let Some(row) = find_row(&kind) else {
            return Err(format!(
                "observation fragment {} names unknown kind {kind:?} — refused rather than ignored",
                frag_path.display()
            ));
        };

        if relative_path_escapes_root(&rel) {
            return Err(format!(
                "observation fragment {} path escapes FloorEvidenceRoot: {rel:?}",
                frag_path.display()
            ));
        }

        if producer_phase != row.phase {
            return Err(format!(
                "observation fragment {} declares producer_phase={producer_phase:?} but registry row {kind} expects {:?}",
                frag_path.display(),
                row.phase
            ));
        }

        if !locator_matches_relpath(&row.locator, &rel) {
            return Err(format!(
                "observation fragment {} claims kind {kind} at UnknownObservedPath {rel:?}; registry row owns {}",
                frag_path.display(),
                pattern_of(&row.locator)
            ));
        }

        out.push(Observation {
            kind,
            relative_path: rel,
            size,
            digest,
            producer_phase,
        });
    }

    for row in rows() {
        if matches!(row.locator, Locator::Family { .. }) {
            continue;
        }
        let count = out.iter().filter(|o| o.kind == row.kind).count();
        if count > 1 {
            return Err(format!(
                "duplicate observation fragments for singleton kind {} ({count} fragments; expected at most one)",
                row.kind
            ));
        }
    }

    for i in 0..out.len() {
        for j in (i + 1)..out.len() {
            if out[i].kind == out[j].kind && out[i].relative_path == out[j].relative_path {
                return Err(format!(
                    "duplicate observation for (kind={}, path={})",
                    out[i].kind, out[i].relative_path
                ));
            }
        }
    }

    Ok(out)
}

fn env_or_empty(key: &str) -> String {
    std::env::var(key).unwrap_or_default()
}

fn is_git_object_hex(s: &str) -> bool {
    (s.len() == 40 || s.len() == 64) && s.chars().all(|c| c.is_ascii_hexdigit())
}

fn walk_attempt_segment_ok(raw: &str) -> bool {
    !(raw.is_empty()
        || raw == "."
        || raw == ".."
        || raw.contains('/')
        || raw.contains('\\')
        || raw.contains('\n')
        || raw.contains('\r')
        || raw.contains('\0'))
}

enum SubjectOutcome {
    Observed {
        run_id: String,
        run_attempt: String,
        job_key: String,
        tested_commit: String,
        source_head_commit: String,
        tree: String,
        walk: String,
    },
    Refused {
        cause: String,
        run_id: String,
        run_attempt: String,
        job_key: String,
        tested_commit: String,
        source_head_commit: String,
        tree: String,
        walk: String,
    },
}

/// The commit whose branch head the run was requested for, read from the event payload
/// GitHub itself wrote. On a `pull_request` event `GITHUB_SHA` is the ephemeral MERGE
/// commit, which exists nowhere in the contributor's history — reporting it as the
/// subject's head made the evidence unaddressable from the branch it describes. Parsed
/// with the real JSON reader rather than a substring scan, so a nested `head` object
/// elsewhere in the payload cannot be mistaken for the pull request's own.
fn pull_request_head_sha_from_event() -> Option<String> {
    let path = std::env::var("GITHUB_EVENT_PATH").ok()?;
    if path.is_empty() {
        return None;
    }
    let body = fs::read_to_string(&path).ok()?;
    let value: serde_json::Value = serde_json::from_str(&body).ok()?;
    let sha = value
        .get("pull_request")?
        .get("head")?
        .get("sha")?
        .as_str()?;
    if sha.is_empty() {
        None
    } else {
        Some(sha.to_string())
    }
}

fn observe_local_subject() -> SubjectOutcome {
    let run_id = env_or_empty("GITHUB_RUN_ID");
    let run_attempt = env_or_empty("GITHUB_RUN_ATTEMPT");
    let job_key = env_or_empty("GITHUB_JOB");
    let tested_commit = env_or_empty("GITHUB_SHA");
    let event_name = env_or_empty("GITHUB_EVENT_NAME");
    let mut walk = env_or_empty("GUNBC_WALK_ATTEMPT_ID");
    if walk.is_empty() && !run_id.is_empty() && !run_attempt.is_empty() && !job_key.is_empty() {
        walk = format!("{run_id}-{run_attempt}-{job_key}");
    }
    let mut tree = env_or_empty("GUNBC_TESTED_TREE");
    if tree.is_empty() && !tested_commit.is_empty() {
        if let Ok(out) = Command::new("git")
            .args(["log", "-1", "--format=%T", &tested_commit])
            .output()
        {
            if out.status.success() {
                tree = String::from_utf8_lossy(&out.stdout).trim().to_string();
            }
        }
    }
    let mut source_head_commit = env_or_empty("GUNBC_SOURCE_HEAD_COMMIT");
    if source_head_commit.is_empty() && event_name == "pull_request" {
        source_head_commit = pull_request_head_sha_from_event().unwrap_or_default();
    }
    if source_head_commit.is_empty()
        && matches!(
            event_name.as_str(),
            "push" | "schedule" | "workflow_dispatch"
        )
    {
        // On these events the tested ref IS the source ref: GitHub checks out the pushed
        // commit itself, so the two coordinates coincide by construction rather than by
        // assumption.
        source_head_commit = tested_commit.clone();
    }

    let refuse = |cause: &str| SubjectOutcome::Refused {
        cause: cause.to_string(),
        run_id: run_id.clone(),
        run_attempt: run_attempt.clone(),
        job_key: job_key.clone(),
        tested_commit: tested_commit.clone(),
        source_head_commit: source_head_commit.clone(),
        tree: tree.clone(),
        walk: walk.clone(),
    };

    if run_id.is_empty() {
        return refuse("missing-github_run_id");
    }
    if run_attempt.is_empty() {
        return refuse("missing-github_run_attempt");
    }
    if job_key.is_empty() {
        return refuse("missing-github_job_key");
    }
    if tested_commit.is_empty() {
        return refuse("missing-tested_commit");
    }
    if !is_git_object_hex(&tested_commit) {
        return refuse("invalid-tested_commit");
    }
    if source_head_commit.is_empty() {
        return refuse("missing-source_head_commit");
    }
    if !is_git_object_hex(&source_head_commit) {
        return refuse("invalid-source_head_commit");
    }
    if tree.is_empty() {
        return refuse("missing-tested_tree");
    }
    if !is_git_object_hex(&tree) {
        return refuse("invalid-tested_tree");
    }
    if walk.is_empty() {
        return refuse("missing-walk_attempt_id");
    }
    if !walk_attempt_segment_ok(&walk) {
        return refuse("invalid-walk_attempt_id");
    }
    SubjectOutcome::Observed {
        run_id,
        run_attempt,
        job_key,
        tested_commit,
        source_head_commit,
        tree,
        walk,
    }
}

fn observations_for_row<'a>(
    row: &RegistryRow,
    observations: &'a [Observation],
) -> Vec<&'a Observation> {
    observations
        .iter()
        .filter(|o| o.kind == row.kind && locator_matches_relpath(&row.locator, &o.relative_path))
        .collect()
}

/// Writes `floor_evidence_root` and `walk_attempt` to `$GITHUB_OUTPUT` (blocker 1, #7785
/// commit 4A) so the downstream `always()` upload step can address the EXACT attempt
/// root (`${{ steps.finalize_floor_evidence.outputs.floor_evidence_root }}`) instead of
/// a `target/floor-evidence/*` wildcard that would sweep in every sibling attempt a
/// reused self-hosted `target/` happens to still be carrying. A no-op (never an error)
/// when `GITHUB_OUTPUT` is unset — local/dev invocations have nothing to write into.
fn write_github_output_kv(pairs: &[(&str, &str)]) -> Result<(), String> {
    let path = match std::env::var("GITHUB_OUTPUT") {
        Ok(p) if !p.is_empty() => p,
        _ => return Ok(()),
    };
    let mut body = String::new();
    for (k, v) in pairs {
        body.push_str(&format!("{k}={v}\n"));
    }
    let mut file = fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&path)
        .map_err(|e| format!("open GITHUB_OUTPUT {path}: {e}"))?;
    file.write_all(body.as_bytes())
        .map_err(|e| format!("write GITHUB_OUTPUT {path}: {e}"))?;
    Ok(())
}

/// Finalize one attempt root from observation fragments + exact journal phase standing.
/// Refuses incomplete subject (non-zero exit). Never scrapes sibling attempt roots.
pub fn finalize_floor_evidence() -> Result<ExitCode, ExitCode> {
    let computed = fingerprint_from_rows();
    if computed.trim() != FLOOR_EVIDENCE_REGISTRY_FINGERPRINT.trim() {
        eprintln!(
            "::error::finalize-floor-evidence: seed registry fingerprint drifted from dag/gunbc/ci_floor_population_receipt_registry.fingerprint"
        );
        return Err(ExitCode::from(1));
    }

    let subject = observe_local_subject();
    let (walk, subject_ok, subject_lines, refuse_cause) = match &subject {
        SubjectOutcome::Observed {
            run_id,
            run_attempt,
            job_key,
            tested_commit,
            source_head_commit,
            tree,
            walk,
        } => (
            walk.clone(),
            true,
            format!(
                "subject_status=Observed\nrun_id={run_id}\nrun_attempt={run_attempt}\njob_key={job_key}\ntested_commit={tested_commit}\nsource_head_commit={source_head_commit}\ntested_tree={tree}\nwalk_attempt={walk}\n"
            ),
            None,
        ),
        SubjectOutcome::Refused {
            cause,
            run_id,
            run_attempt,
            job_key,
            tested_commit,
            source_head_commit,
            tree,
            walk,
        } => (
            walk.clone(),
            false,
            format!(
                "subject_status=Refused\nsubject_refuse_cause={cause}\nrun_id={run_id}\nrun_attempt={run_attempt}\njob_key={job_key}\ntested_commit={tested_commit}\nsource_head_commit={source_head_commit}\ntested_tree={tree}\nwalk_attempt={walk}\n"
            ),
            Some(cause.clone()),
        ),
    };

    if walk.is_empty() || !walk_attempt_segment_ok(&walk) {
        eprintln!(
            "::error::finalize-floor-evidence: walk_attempt required to select FloorEvidenceRoot (cause={})",
            refuse_cause.as_deref().unwrap_or("missing-or-invalid-walk_attempt")
        );
        return Err(ExitCode::from(1));
    }

    let root = floor_evidence_root(&walk);
    if let Err(e) = fs::create_dir_all(&root) {
        eprintln!(
            "::error::finalize-floor-evidence: mkdir {}: {e}",
            root.display()
        );
        return Err(ExitCode::from(1));
    }

    // Write the exact attempt outputs BEFORE anything below can fail (blocker 1): the
    // upload step downstream runs `if: always()`, so even a later refusal in this same
    // finalize must leave a valid exact `floor_evidence_root` output behind it.
    if let Err(e) = write_github_output_kv(&[
        ("floor_evidence_root", &root.display().to_string()),
        ("walk_attempt", &walk),
    ]) {
        eprintln!("::error::finalize-floor-evidence: {e}");
        return Err(ExitCode::from(1));
    }

    let observations = match load_observation_fragments(&root) {
        Ok(o) => o,
        Err(e) => {
            eprintln!("::error::finalize-floor-evidence: {e}");
            return Err(ExitCode::from(1));
        }
    };

    let journal_path = root.join(PHASE_JOURNAL_REL);
    let journal = match fs::read_to_string(&journal_path) {
        Ok(body) => parse_phase_journal(&body),
        Err(_) => PhaseJournalIndex::default(),
    };

    // PhaseJournal itself is present when the journal file exists (even if empty).
    let journal_file_present = journal_path.is_file();

    let mut out = String::new();
    out.push_str(SCHEMA);
    out.push('\n');
    // Honest header (blocker 6, #7785 commit 4A): a SHA-256 of the canonical fingerprint
    // bytes, not the raw multiline blob — the field name says exactly what it is.
    let registry_fingerprint_sha256 =
        sha256_bytes(FLOOR_EVIDENCE_REGISTRY_FINGERPRINT.trim().as_bytes());
    out.push_str(&format!(
        "registry_fingerprint_sha256={registry_fingerprint_sha256}\n"
    ));
    out.push_str(&subject_lines);
    out.push_str(
        "kind\texpected_pattern\tobserved_path\tstanding\tproducer_phase\tsize_bytes\tcontent_digest\n",
    );

    let mut row_count = 0usize;
    for row in rows() {
        let pattern = pattern_of(&row.locator);
        let phase_standing = match journal.standing_for_row(row) {
            Ok(standing) => standing,
            Err(e) => {
                eprintln!("::error::finalize-floor-evidence: {e}");
                return Err(ExitCode::from(1));
            }
        };

        if row.kind == "PhaseJournal" {
            if journal_file_present {
                match sha256_file(&journal_path) {
                    Ok((size, digest)) => {
                        out.push_str(&format!(
                            "{}\t{}\t{}\tObservedPresent\t{}\t{}\t{}\n",
                            row.kind,
                            pattern,
                            journal_path.display(),
                            row.phase,
                            size,
                            digest
                        ));
                        row_count += 1;
                    }
                    Err(e) => {
                        eprintln!("::error::finalize-floor-evidence: {e}");
                        return Err(ExitCode::from(1));
                    }
                }
            } else {
                let standing = standing_label_missing(row.optional_worker, phase_standing);
                out.push_str(&format!(
                    "{}\t{}\t\t{}\t{}\t0\t\n",
                    row.kind, pattern, standing, row.phase
                ));
                row_count += 1;
            }
            continue;
        }

        let matches = observations_for_row(row, &observations);
        if matches.is_empty() {
            let standing = standing_label_missing(row.optional_worker, phase_standing);
            out.push_str(&format!(
                "{}\t{}\t\t{}\t{}\t0\t\n",
                row.kind, pattern, standing, row.phase
            ));
            row_count += 1;
            continue;
        }
        for obs in matches {
            // Verify digest against bytes under this root only — refuse foreign paths.
            let abs = root.join(&obs.relative_path);
            match sha256_file(&abs) {
                Ok((size, digest)) => {
                    if digest != obs.digest {
                        eprintln!(
                            "::error::finalize-floor-evidence: observation digest drift for {} (obs={} file={})",
                            abs.display(),
                            obs.digest,
                            digest
                        );
                        return Err(ExitCode::from(1));
                    }
                    if size != obs.size {
                        eprintln!(
                            "::error::finalize-floor-evidence: observation size drift for {}",
                            abs.display()
                        );
                        return Err(ExitCode::from(1));
                    }
                    out.push_str(&format!(
                        "{}\t{}\t{}\tObservedPresent\t{}\t{}\t{}\n",
                        row.kind,
                        pattern,
                        abs.display(),
                        row.phase,
                        size,
                        digest
                    ));
                    row_count += 1;
                }
                Err(e) => {
                    eprintln!("::error::finalize-floor-evidence: {e}");
                    return Err(ExitCode::from(1));
                }
            }
        }
    }

    // Honest self-digest (blocker 6): computed over exactly the bytes written above —
    // schema, header, subject, column header, and every data row — BEFORE this trailer
    // line is appended, so a reader can reproduce it by hashing the file with its last
    // line stripped. Never claimed as a `content_digest` path-digest row inside the
    // body it describes.
    let manifest_body_digest = sha256_bytes(out.as_bytes());
    out.push_str(&format!("manifest_body_digest={manifest_body_digest}\n"));

    let manifest_path = root.join(MANIFEST_REL);
    let mut file = match fs::File::create(&manifest_path) {
        Ok(f) => f,
        Err(e) => {
            eprintln!(
                "::error::finalize-floor-evidence: create {}: {e}",
                manifest_path.display()
            );
            return Err(ExitCode::from(1));
        }
    };
    if let Err(e) = file.write_all(out.as_bytes()).and_then(|_| file.sync_all()) {
        eprintln!(
            "::error::finalize-floor-evidence: write {}: {e}",
            manifest_path.display()
        );
        return Err(ExitCode::from(1));
    }

    eprintln!(
        "[floor-population-evidence] wrote {} schema={} rows={} subject_ok={subject_ok} attempt={walk}",
        manifest_path.display(),
        SCHEMA,
        row_count
    );

    if !subject_ok {
        eprintln!(
            "::error::finalize-floor-evidence: LocalSubjectRefused cause={}",
            refuse_cause.unwrap_or_else(|| "unknown".to_string())
        );
        return Err(ExitCode::from(1));
    }
    Ok(ExitCode::SUCCESS)
}

