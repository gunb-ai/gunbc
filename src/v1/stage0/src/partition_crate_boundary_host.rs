//! Host realization for `v1.compiler.stage0_crates` — the derived stage0 partition's
//! crate boundary files, produced from the authority and adjudicated against the tree.
//!
//! WHY THIS MODULE EXISTS AT ALL. The producer was already modeled and complete:
//! `stage0_crate_boundary_emit_outcome` renders every partition crate's `lib.rs` and
//! `Cargo.toml` from `gunbc.stage0_crate_partition_generated`, whose authority is
//! `v2.workflow.rust_crate_partition`. What it did not have, from the 2026-08-20 regen
//! cut until this module, was a CALLER. `regen_stage0` was deleted at the root and
//! `--required-regen` never covered these files, so the derivation stood in the tree
//! with zero executed route while the committed files it describes were edited by hand.
//! The `//! Generated by regen_stage0 -- do not edit.` header on each of those files
//! therefore named a producer that did not exist: a refusal whose only sanctioned
//! remedy is unavailable, which is the laundering trap DESIGN records twice.
//!
//! PRODUCTION PRECEDES ADJUDICATION, and the ordering is carried by the type rather
//! than by discipline. Every verdict below is reached THROUGH a `Rendered` population,
//! so "refused, having produced nothing to compare" has no spelling except the one arm
//! where the carrier itself refused to render. That is the same construction
//! `v2.workflow.required_regen` adopted after the regen cut shipped a gate whose only
//! closing move did not exist.

use std::fs;
use std::path::PathBuf;

use super::workspace_root;
use crate::v1_compiler_stage0_crates::{
    stage0_crate_boundary_emit_outcome, Stage0CrateBoundaryEmitOutcome,
};

/// One rendered boundary file, beside what the tree currently holds at its path.
///
/// `committed` is `None` for a path with no file, which is a DIFFERENT state from a file
/// whose bytes differ — a missing mirror is the shape a newly rostered crate takes on the
/// commit that introduces it, and collapsing the two would report it as ordinary drift.
#[derive(Debug, Clone)]
pub struct RenderedBoundaryFile {
    pub path: String,
    pub rendered: String,
    pub committed: Option<String>,
}

impl RenderedBoundaryFile {
    pub fn disposition(&self) -> BoundaryFileDisposition {
        match &self.committed {
            None => BoundaryFileDisposition::Absent,
            Some(bytes) if *bytes == self.rendered => BoundaryFileDisposition::Matches,
            Some(_) => BoundaryFileDisposition::Drifted,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BoundaryFileDisposition {
    /// The committed bytes are exactly what the authority renders.
    Matches,
    /// A file exists and its bytes are not what the authority renders — a hand edit, or
    /// an authority change whose projection was never installed.
    Drifted,
    /// No file at the path. A crate rostered but never written.
    Absent,
}

impl BoundaryFileDisposition {
    pub fn name(self) -> &'static str {
        match self {
            BoundaryFileDisposition::Matches => "matches",
            BoundaryFileDisposition::Drifted => "drifted",
            BoundaryFileDisposition::Absent => "absent",
        }
    }
}

/// THE OUTCOME IS REACHED THROUGH THE RENDERED POPULATION, NEVER BESIDE IT.
///
/// `CarrierRefused` is the one arm that carries no files, and it is reachable only where the
/// modeled producer itself refused — a module assigned to no crate, or a package with no
/// `crate_dir`. Every other verdict names the population it was computed against, so a
/// consumer can never read a verdict without also holding what produced it.
#[derive(Debug)]
pub enum PartitionCrateBoundaryOutcome {
    /// The authority refused to render. Nothing was compared, and the cause says why.
    CarrierRefused { cause: String },
    /// Rendered, and adjudicated against the tree.
    Rendered {
        files: Vec<RenderedBoundaryFile>,
        /// Paths written by this run. Empty in read-only mode BY CONSTRUCTION, so a
        /// non-empty list is proof a write was requested and performed.
        written: Vec<String>,
    },
}

impl PartitionCrateBoundaryOutcome {
    /// Files whose committed bytes are not what the authority renders, in path order.
    ///
    /// A carrier refusal answers EMPTY here, which is why no caller may gate on this alone —
    /// `did not render` and `rendered, nothing drifted` are different states and this
    /// method cannot tell them apart. Gate on the outcome, not on the count.
    pub fn divergent(&self) -> Vec<&RenderedBoundaryFile> {
        match self {
            PartitionCrateBoundaryOutcome::CarrierRefused { .. } => Vec::new(),
            PartitionCrateBoundaryOutcome::Rendered { files, .. } => files
                .iter()
                .filter(|f| f.disposition() != BoundaryFileDisposition::Matches)
                .collect(),
        }
    }
}

/// The command that regenerates these files.
///
/// It is a constant rather than prose in a message because the refusal below MUST name a
/// route that exists. This whole class was produced by a generated file whose header named
/// a producer deleted five days earlier, and an author who meets a refusal offering no
/// remedy does exactly what the last one did: hand-edits the artifact.
pub const PARTITION_CRATE_PRODUCING_COMMAND: &str =
    "claim_executor --emit-partition-crates --write";

fn absolute(path: &str) -> PathBuf {
    workspace_root().join(path)
}

/// Render every partition boundary file from the authority and read what the tree holds.
///
/// `write` installs the rendered bytes. Writing happens BEFORE any verdict is returned, so
/// a caller cannot receive a refusal that names a file this run declined to produce.
pub fn run_partition_crate_boundary(write: bool) -> PartitionCrateBoundaryOutcome {
    let rendered = match &*stage0_crate_boundary_emit_outcome() {
        Stage0CrateBoundaryEmitOutcome::Stage0CrateBoundaryEmitRefused { cause } => {
            return PartitionCrateBoundaryOutcome::CarrierRefused {
                cause: format!("{cause:?}"),
            };
        }
        Stage0CrateBoundaryEmitOutcome::Stage0CrateBoundaryEmitOk { files } => files
            .iter()
            .map(|f| {
                let path = f.path.clone();
                let committed = fs::read_to_string(absolute(&path)).ok();
                RenderedBoundaryFile {
                    path,
                    rendered: f.content.clone(),
                    committed,
                }
            })
            .collect::<Vec<_>>(),
    };

    let mut written = Vec::new();
    if write {
        for file in &rendered {
            if file.disposition() == BoundaryFileDisposition::Matches {
                continue;
            }
            let target = absolute(&file.path);
            if let Some(parent) = target.parent() {
                let _ = fs::create_dir_all(parent);
            }
            match fs::write(&target, &file.rendered) {
                Ok(()) => written.push(file.path.clone()),
                Err(e) => {
                    // A failed write is not a quiet skip: it becomes a carrier refusal, so a
                    // run that could not install its own output can never report as a
                    // successful production.
                    return PartitionCrateBoundaryOutcome::CarrierRefused {
                        cause: format!("write failed for {}: {e}", file.path),
                    };
                }
            }
        }
    }

    PartitionCrateBoundaryOutcome::Rendered {
        files: rendered,
        written,
    }
}
