//! Host realization for `v1.compiler.stage0_crates` — the derived stage0 partition's
//! crate boundary files, produced from the authority and adjudicated against the tree.
//!
//! WHY THIS MODULE EXISTS. `stage0_crate_boundary_emit_outcome` already rendered every
//! partition crate's `lib.rs` and `Cargo.toml` from `gunbc.stage0_crate_partition_generated`
//! (authority `v2.workflow.rust_crate_partition`) but had no CALLER from the 2026-08-20 regen
//! cut until this module: `regen_stage0` was deleted at the root and `--required-regen` never
//! covered these files, so the committed files were hand-edited while their
//! `//! Generated by regen_stage0 -- do not edit.` header named a producer that did not exist —
//! a refusal with no sanctioned remedy, the laundering trap DESIGN records twice.
//!
//! PRODUCTION PRECEDES ADJUDICATION, carried by the type: every verdict is reached THROUGH a
//! `Rendered` population, so "refused, produced nothing to compare" has no spelling except the
//! arm where the carrier itself refused to render — the construction `v2.workflow.required_regen`
//! adopted after the regen cut shipped a gate whose only closing move did not exist.

use std::fs;
use std::path::PathBuf;

use super::workspace_root;
use crate::v1_compiler_stage0_crates::{
    stage0_crate_boundary_emit_outcome, Stage0CrateBoundaryEmitOutcome,
};

/// One rendered boundary file, beside what the tree currently holds at its path.
///
/// `committed` is `None` for a path with no file — a DIFFERENT state from differing bytes: a
/// newly rostered crate has a missing mirror on its introducing commit, not ordinary drift.
#[derive(Debug, Clone)]
pub struct RenderedBoundaryFile {
    pub path: String,
    pub rendered: String,
    pub committed: Option<String>,
}

impl RenderedBoundaryFile {
    pub fn disposition(&self) -> BoundaryFileDisposition {
        match &self.committed {
            None => BoundaryFileDisposition::Absent,
            Some(bytes) if *bytes == self.rendered => BoundaryFileDisposition::Matches,
            Some(_) => BoundaryFileDisposition::Drifted,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BoundaryFileDisposition {
    /// The committed bytes are exactly what the authority renders.
    Matches,
    /// A file exists and its bytes are not what the authority renders — a hand edit, or
    /// an authority change whose projection was never installed.
    Drifted,
    /// No file at the path. A crate rostered but never written.
    Absent,
}

impl BoundaryFileDisposition {
    pub fn name(self) -> &'static str {
        match self {
            BoundaryFileDisposition::Matches => "matches",
            BoundaryFileDisposition::Drifted => "drifted",
            BoundaryFileDisposition::Absent => "absent",
        }
    }
}

/// THE OUTCOME IS REACHED THROUGH THE RENDERED POPULATION, NEVER BESIDE IT.
///
/// `CarrierRefused` is the one file-less arm, reachable only where the modeled producer itself
/// refused — a module assigned to no crate, or a package with no `crate_dir`. Every other
/// verdict names the population it was computed against.
#[derive(Debug)]
pub enum PartitionCrateBoundaryOutcome {
    /// The authority refused to render. Nothing was compared, and the cause says why.
    CarrierRefused { cause: String },
    /// Rendered, and adjudicated against the tree.
    Rendered {
        files: Vec<RenderedBoundaryFile>,
        /// Paths written by this run. Empty in read-only mode BY CONSTRUCTION.
        written: Vec<String>,
    },
}

impl PartitionCrateBoundaryOutcome {
    /// Files whose committed bytes are not what the authority renders, in path order.
    ///
    /// A carrier refusal answers EMPTY here, so `did not render` and `rendered, nothing
    /// drifted` are indistinguishable by this method. Gate on the outcome, not on the count.
    pub fn divergent(&self) -> Vec<&RenderedBoundaryFile> {
        match self {
            PartitionCrateBoundaryOutcome::CarrierRefused { .. } => Vec::new(),
            PartitionCrateBoundaryOutcome::Rendered { files, .. } => files
                .iter()
                .filter(|f| f.disposition() != BoundaryFileDisposition::Matches)
                .collect(),
        }
    }
}

/// The command that regenerates these files.
///
/// A constant, not prose in a message, because the refusal below MUST name a route that exists:
/// this class came from a header naming a producer deleted five days earlier, and an author met
/// by a refusal with no remedy hand-edits the artifact.
pub const PARTITION_CRATE_PRODUCING_COMMAND: &str =
    "claim_executor --emit-partition-crates --write";

fn absolute(path: &str) -> PathBuf {
    workspace_root().join(path)
}

/// Render every partition boundary file from the authority and read what the tree holds.
///
/// `write` installs the rendered bytes BEFORE any verdict is returned, so no refusal can name a
/// file this run declined to produce.
pub fn run_partition_crate_boundary(write: bool) -> PartitionCrateBoundaryOutcome {
    let rendered = match &*stage0_crate_boundary_emit_outcome() {
        Stage0CrateBoundaryEmitOutcome::Stage0CrateBoundaryEmitRefused { cause } => {
            return PartitionCrateBoundaryOutcome::CarrierRefused {
                cause: format!("{cause:?}"),
            };
        }
        Stage0CrateBoundaryEmitOutcome::Stage0CrateBoundaryEmitOk { files } => files
            .iter()
            .map(|f| {
                let path = f.path.clone();
                let committed = fs::read_to_string(absolute(&path)).ok();
                RenderedBoundaryFile {
                    path,
                    rendered: f.content.clone(),
                    committed,
                }
            })
            .collect::<Vec<_>>(),
    };

    let mut written = Vec::new();
    if write {
        for file in &rendered {
            if file.disposition() == BoundaryFileDisposition::Matches {
                continue;
            }
            let target = absolute(&file.path);
            if let Some(parent) = target.parent() {
                let _ = fs::create_dir_all(parent);
            }
            match fs::write(&target, &file.rendered) {
                Ok(()) => written.push(file.path.clone()),
                Err(e) => {
                    // A failed write becomes a carrier refusal, never a quiet skip.
                    return PartitionCrateBoundaryOutcome::CarrierRefused {
                        cause: format!("write failed for {}: {e}", file.path),
                    };
                }
            }
        }
    }

    PartitionCrateBoundaryOutcome::Rendered {
        files: rendered,
        written,
    }
}

/// THE SECOND CONJUNCT: the produced crates COMPILE.
///
/// Drift answers "does the projection match its authority" and is STRUCTURALLY SILENT on "is
/// the authority complete"; only compiling answers the second. The failures are independent in
/// both directions — measured, not argued:
///
///   - The defect behind this module had drift ZERO across four projection links (authority,
///     generated `.dag`, emitted Rust mirror, hand `lib.rs`) and the crate did not compile.
///   - The emit-shell manifest found later on the same branch had real drift and a passing
///     build, because dependency ORDER is cosmetic to cargo.
///
/// So neither check subsumes the other and the phase carries both.
///
/// PACKAGE NAMES COME FROM THE AUTHORITY — the rows the renderer walks — never a hand roster,
/// so a crate added to the partition is compiled here without anyone remembering to add it.
#[derive(Debug)]
pub enum PartitionCompileOutcome {
    /// The toolchain was never invoked. Carries why: "not attempted" and "attempted and found
    /// nothing" must not share a spelling.
    NotAttempted { reason: String },
    /// Launched but no exit status of its own — killed, or the spawn failed. THIS IS NOT A
    /// ZERO-FINDING RUN: an OOM kill exits 137 with an empty diagnostic population, which reads as
    /// a clean build unless the disposition says otherwise.
    DidNotComplete { detail: String },
    /// The compiler ran to completion and reported. `status` is its own exit status.
    Completed {
        status: i32,
        packages: Vec<String>,
        /// The packages cargo itself said it could not compile, parsed from its `could not
        /// compile `X`` lines. THE REFUSAL MUST NAME WHICH, not only how many: `status=101
        /// packages=7` sends the author back to re-run the build by hand. Empty when cargo failed
        /// without attributing to a package (resolver or manifest error), hence reported beside
        /// the status rather than instead of it.
        failed_packages: Vec<String>,
        stderr_tail: String,
    },
}

impl PartitionCompileOutcome {
    /// Only a completed, zero-status compile passes; every other arm, including never
    /// launched, refuses.
    pub fn passed(&self) -> bool {
        matches!(self, PartitionCompileOutcome::Completed { status: 0, .. })
    }

    pub fn summary(&self) -> String {
        match self {
            PartitionCompileOutcome::NotAttempted { reason } => {
                format!("NotAttempted reason={reason}")
            }
            PartitionCompileOutcome::DidNotComplete { detail } => {
                format!("DidNotComplete detail={detail}")
            }
            PartitionCompileOutcome::Completed {
                status,
                packages,
                failed_packages,
                ..
            } => {
                if failed_packages.is_empty() {
                    format!("Completed status={status} packages={}", packages.len())
                } else {
                    format!(
                        "Completed status={status} packages={} failed=[{}]",
                        packages.len(),
                        failed_packages.join(" ")
                    )
                }
            }
        }
    }
}

/// Compile every package the partition authority declares.
///
/// `-p <pkg>` per row rather than `--workspace`, so the subject is exactly the partition and a
/// failure elsewhere cannot be attributed to it. The inverse selector let this class hide:
/// `-p v1-compiler --bins` builds every bin target OF THAT ONE PACKAGE and never reaches these
/// sibling packages.
pub fn compile_partition_crates(packages: &[String]) -> PartitionCompileOutcome {
    if packages.is_empty() {
        return PartitionCompileOutcome::NotAttempted {
            reason: "the authority declared no partition packages".to_string(),
        };
    }
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let mut command = std::process::Command::new(&cargo);
    command.arg("build").arg("--release");
    for package in packages {
        command.arg("-p").arg(package);
    }
    command.current_dir(workspace_root());
    match command.output() {
        Err(e) => PartitionCompileOutcome::DidNotComplete {
            detail: format!("spawning {cargo} failed: {e}"),
        },
        Ok(output) => match output.status.code() {
            // No exit code means a signal ended it (OOM kill); never readable as a clean build.
            None => PartitionCompileOutcome::DidNotComplete {
                detail: format!("{cargo} terminated by signal without an exit status"),
            },
            Some(status) => {
                let stderr = String::from_utf8_lossy(&output.stderr);
                let tail: Vec<&str> = stderr.lines().rev().take(12).collect();
                PartitionCompileOutcome::Completed {
                    status,
                    packages: packages.to_vec(),
                    failed_packages: failed_packages_from_stderr(&stderr),
                    stderr_tail: tail.into_iter().rev().collect::<Vec<_>>().join("\n"),
                }
            }
        },
    }
}

/// The package names the partition authority declares, read from the rendered rows.
pub fn partition_package_names() -> Vec<String> {
    crate::gunbc_stage0_crate_partition_generated::generated_partition_crate_rows()
        .iter()
        .map(|row| row.package_name.clone())
        .collect()
}

/// The packages cargo attributed a compilation failure to, read from its own output.
///
/// Cargo ends a failed package with ``error: could not compile `NAME` (lib) due to N previous
/// errors``. Parsing that reads the toolchain's own attribution rather than re-deriving it.
fn failed_packages_from_stderr(stderr: &str) -> Vec<String> {
    let mut found: Vec<String> = Vec::new();
    for line in stderr.lines() {
        let Some(rest) = line.split_once("could not compile `") else {
            continue;
        };
        let Some((name, _)) = rest.1.split_once('`') else {
            continue;
        };
        if !found.iter().any(|f| f == name) {
            found.push(name.to_string());
        }
    }
    found
}
