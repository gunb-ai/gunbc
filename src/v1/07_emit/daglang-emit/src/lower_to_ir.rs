//! Computation → AbstractIR lowering.
//!
//! Converts an `EmitPlan` into target-agnostic `code_ir` constructs (`Stmt`,
//! `Expr`, `Item`). This is the bridge from "what" ([`Computation`]) to
//! "how" (structured code), while remaining language-agnostic.
//!
//! **Owned by**: Task 8 (dsl-codegen-tasks.md)

use std::collections::HashMap;

use crate::computation::{
    AggregateKind, Computation, JsonOpKind, PureBody, StringOpKind, TransportKind,
};
use crate::plan::{EmitPlan, EmitStep, InputBinding};
use daglang_syntax::ast::EmitCollectionFamily;
use gunbc_ir::code_ir::{CallObligation, Expr, FnDef, Item, SourceFile, Stmt};
use gunbc_ir::ValueExpr;

/// Lower an [`EmitPlan`] into AbstractIR (`SourceFile`) with a single `main`.
///
/// Each [`EmitStep`] is lowered into one or more statements in `main`:
/// - `Pure` steps become let-bindings / expressions.
/// - `Transport` steps become prepare → execute → parse calls.
/// - `ResourceAcquire` steps become resource acquisition calls.
/// - `Collection` steps become collection op calls.
pub fn lower_plan_to_abstract_ir(plan: &EmitPlan) -> SourceFile {
    let output_vars = build_output_var_map(plan);
    let mut body = Vec::new();

    for (step_index, step) in plan.steps.iter().enumerate() {
        body.push(Stmt::comment(format!(
            "step {step_index}: {}",
            step.node_id
        )));
        body.extend(lower_step(step_index, step, &output_vars));
        body.push(Stmt::Blank);
    }

    if body.last().is_some_and(|stmt| matches!(stmt, Stmt::Blank)) {
        body.pop();
    }

    let params = plan
        .entrypoints
        .iter()
        .map(|entrypoint| {
            (
                sanitize_identifier(&entrypoint.name),
                map_abstract_type(&entrypoint.abstract_type),
            )
        })
        .collect::<Vec<_>>();

    let main_fn = FnDef {
        name: "main".to_string(),
        is_pub: true,
        params,
        return_type: None,
        body,
        doc: vec![
            "Generated by daglang-emit from EmitPlan.".to_string(),
            "Lowered at AbstractIR tier (target-independent).".to_string(),
        ],
        attributes: Vec::new(),
    };

    SourceFile {
        doc: vec!["Generated source file from daglang EmitPlan.".to_string()],
        items: vec![Item::Fn(main_fn)],
    }
}

fn build_output_var_map(plan: &EmitPlan) -> HashMap<(usize, String), String> {
    let mut output_vars = HashMap::new();

    for (step_index, step) in plan.steps.iter().enumerate() {
        for output in &step.output_bindings {
            output_vars.insert(
                (step_index, output.port.clone()),
                format!("step_{step_index}_{}", sanitize_identifier(&output.port)),
            );
        }
    }

    output_vars
}

fn lower_step(
    step_index: usize,
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    let mut input_name_to_expr = HashMap::new();
    let input_names = expected_input_names(step, step.input_sources.len());
    let ordered_inputs = step
        .input_sources
        .iter()
        .enumerate()
        .map(|(input_index, binding)| {
            let expr = lower_input_binding(binding, output_vars);
            let name = input_names
                .get(input_index)
                .cloned()
                .unwrap_or_else(|| format!("input_{input_index}"));
            input_name_to_expr.insert(name, expr.clone());
            expr
        })
        .collect::<Vec<_>>();

    match &step.computation {
        Computation::Pure { body, .. } => lower_pure_step(
            step_index,
            body,
            &ordered_inputs,
            &input_name_to_expr,
            step,
            output_vars,
        ),
        Computation::Transport { execute, .. } => {
            lower_transport_step(step_index, *execute, &ordered_inputs, step, output_vars)
        }
        Computation::ResourceAcquire {
            handle_type,
            handle_value,
        } => lower_resource_step(step_index, handle_type, handle_value, step, output_vars),
        Computation::Collection { family, .. } => {
            lower_collection_step(step_index, family, &ordered_inputs, step, output_vars)
        }
    }
}

fn lower_pure_step(
    step_index: usize,
    body: &PureBody,
    ordered_inputs: &[Expr],
    input_name_to_expr: &HashMap<String, Expr>,
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    match body {
        PureBody::Conditional {
            condition,
            then_port,
            else_port,
        } => {
            let cond_expr = resolve_input(condition, input_name_to_expr);
            let then_body = step
                .output_bindings
                .iter()
                .map(|output| {
                    let var_name = output_var_name(step_index, &output.port, output_vars);
                    let value = if output.port == *then_port {
                        Expr::bool_lit(true)
                    } else if else_port.as_ref().is_some_and(|port| *port == output.port) {
                        Expr::bool_lit(false)
                    } else {
                        Expr::Value(ValueExpr::Unit)
                    };
                    Stmt::let_bind(var_name, value)
                })
                .collect::<Vec<_>>();

            let else_body = step
                .output_bindings
                .iter()
                .map(|output| {
                    let var_name = output_var_name(step_index, &output.port, output_vars);
                    let value = if output.port == *then_port {
                        Expr::bool_lit(false)
                    } else if else_port.as_ref().is_some_and(|port| *port == output.port) {
                        Expr::bool_lit(true)
                    } else {
                        Expr::Value(ValueExpr::Unit)
                    };
                    Stmt::let_bind(var_name, value)
                })
                .collect::<Vec<_>>();

            vec![Stmt::Expr(Expr::If {
                cond: Box::new(cond_expr),
                then_body,
                else_body: Some(else_body),
            })]
        }
        PureBody::Compare { left, right } => {
            let compare_expr = Expr::BinOp {
                left: Box::new(resolve_input(left, input_name_to_expr)),
                op: "==".to_string(),
                right: Box::new(resolve_input(right, input_name_to_expr)),
            };
            lower_compare_outputs(step_index, compare_expr, step, output_vars)
        }
        PureBody::Literal(value) => {
            assign_outputs(step_index, step, json_value_to_expr(value), output_vars)
        }
        PureBody::PrepareTransport { kind } => assign_outputs(
            step_index,
            step,
            Expr::call_with_obligation(
                format!("prepare_{}", transport_kind_name(*kind)),
                ordered_inputs.to_vec(),
                CallObligation::ServiceTransportPrepare,
            ),
            output_vars,
        ),
        PureBody::Template { pattern, vars } => {
            let args = vars
                .iter()
                .map(|var| resolve_input(var, input_name_to_expr))
                .collect::<Vec<_>>();
            assign_outputs(
                step_index,
                step,
                Expr::FormatStr {
                    template: pattern.clone(),
                    args,
                },
                output_vars,
            )
        }
        PureBody::StringOp(kind) => {
            let func = format!("string_{}", string_op_name(kind));
            assign_outputs(
                step_index,
                step,
                Expr::call(func, ordered_inputs.to_vec()),
                output_vars,
            )
        }
        PureBody::JsonOp(kind) => {
            let func = format!("json_{}", json_op_name(kind));
            assign_outputs(
                step_index,
                step,
                Expr::call(func, ordered_inputs.to_vec()),
                output_vars,
            )
        }
        PureBody::Aggregate { strategy, .. } => {
            let func = format!("aggregate_{}", aggregate_name(strategy));
            assign_outputs(
                step_index,
                step,
                Expr::call(func, ordered_inputs.to_vec()),
                output_vars,
            )
        }
        PureBody::ServiceCall(metadata) => {
            let func = format!(
                "service_{}_{}",
                sanitize_identifier(&metadata.service),
                sanitize_identifier(&metadata.method)
            );
            let obligation = metadata.config.iter().find_map(|(key, value)| {
                if key != "phase" {
                    return None;
                }
                match value.as_str() {
                    "prepare" => Some(CallObligation::ServiceTransportPrepare),
                    "parse" => Some(CallObligation::ServiceTransportParse),
                    _ => None,
                }
            });
            let expr = obligation.map_or_else(
                || Expr::call(func.clone(), ordered_inputs.to_vec()),
                |obligation| {
                    Expr::call_with_obligation(func.clone(), ordered_inputs.to_vec(), obligation)
                },
            );
            assign_outputs(step_index, step, expr, output_vars)
        }
    }
}

fn lower_compare_outputs(
    step_index: usize,
    compare_expr: Expr,
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    let mut statements = Vec::new();
    let has_fresh = step
        .output_bindings
        .iter()
        .any(|output| output.port == "fresh");

    if has_fresh {
        let fresh_var = output_var_name(step_index, "fresh", output_vars);
        statements.push(Stmt::let_bind(&fresh_var, compare_expr.clone()));
    }

    for output in &step.output_bindings {
        if output.port == "fresh" {
            continue;
        }

        let var_name = output_var_name(step_index, &output.port, output_vars);
        let expr = if output.port == "skip" && has_fresh {
            Expr::var(output_var_name(step_index, "fresh", output_vars)).logical_not()
        } else if output.port == "skip" {
            compare_expr.clone().logical_not()
        } else {
            compare_expr.clone()
        };
        statements.push(Stmt::let_bind(var_name, expr));
    }

    if statements.is_empty() {
        statements.push(Stmt::Expr(compare_expr));
    }

    statements
}

fn lower_transport_step(
    step_index: usize,
    kind: TransportKind,
    ordered_inputs: &[Expr],
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    let prepare_var = format!("step_{step_index}_request");
    let execute_var = format!("step_{step_index}_response");
    let kind_name = transport_kind_name(kind);

    let mut statements = vec![
        Stmt::let_bind(
            prepare_var.clone(),
            Expr::call_with_obligation(
                format!("prepare_{kind_name}"),
                ordered_inputs.to_vec(),
                CallObligation::ServiceTransportPrepare,
            ),
        ),
        Stmt::let_bind(
            execute_var.clone(),
            Expr::call_with_obligation(
                format!("execute_{kind_name}"),
                vec![Expr::var(prepare_var)],
                CallObligation::ServiceTransportExecute,
            ),
        ),
    ];

    if step.output_bindings.is_empty() {
        statements.push(Stmt::Expr(Expr::var(execute_var)));
        return statements;
    }

    for output in &step.output_bindings {
        let var_name = output_var_name(step_index, &output.port, output_vars);
        let parse_call = Expr::call_with_obligation(
            format!("parse_{}_{}", kind_name, sanitize_identifier(&output.port)),
            vec![Expr::var(execute_var.clone())],
            CallObligation::ServiceTransportParse,
        );
        statements.push(Stmt::let_bind(var_name, parse_call));
    }

    statements
}

fn lower_resource_step(
    step_index: usize,
    handle_type: &str,
    handle_value: &str,
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    let acquire_call = Expr::call_with_obligation(
        "acquire_resource",
        vec![Expr::str_lit(handle_type), Expr::str_lit(handle_value)],
        CallObligation::ResourceAcquire,
    );
    assign_outputs(step_index, step, acquire_call, output_vars)
}

fn lower_collection_step(
    step_index: usize,
    family: &EmitCollectionFamily,
    ordered_inputs: &[Expr],
    step: &EmitStep,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    let func = format!("collection_{}", collection_family_name(family));
    assign_outputs(
        step_index,
        step,
        Expr::call(func, ordered_inputs.to_vec()),
        output_vars,
    )
}

fn assign_outputs(
    step_index: usize,
    step: &EmitStep,
    expr: Expr,
    output_vars: &HashMap<(usize, String), String>,
) -> Vec<Stmt> {
    if step.output_bindings.is_empty() {
        return vec![Stmt::Expr(expr)];
    }

    step.output_bindings
        .iter()
        .map(|output| {
            Stmt::let_bind(
                output_var_name(step_index, &output.port, output_vars),
                expr.clone(),
            )
        })
        .collect::<Vec<_>>()
}

fn lower_input_binding(
    binding: &InputBinding,
    output_vars: &HashMap<(usize, String), String>,
) -> Expr {
    match binding {
        InputBinding::FromStep { step_index, port } => {
            let fallback = format!("step_{step_index}_{}", sanitize_identifier(port));
            let name = output_vars
                .get(&(*step_index, port.clone()))
                .cloned()
                .unwrap_or(fallback);
            Expr::var(name)
        }
        InputBinding::FromEntrypoint { port } => Expr::var(sanitize_identifier(port)),
        InputBinding::Constant(value) => json_value_to_expr(value),
    }
}

fn expected_input_names(step: &EmitStep, fallback_len: usize) -> Vec<String> {
    match &step.computation {
        Computation::Pure { inputs, .. } => inputs.iter().map(|input| input.name.clone()).collect(),
        Computation::Transport { prepare, .. } => prepare.input_ports.clone(),
        Computation::ResourceAcquire { .. } | Computation::Collection { .. } => (0..fallback_len)
            .map(|idx| format!("input_{idx}"))
            .collect::<Vec<_>>(),
    }
}

fn resolve_input(name: &str, input_name_to_expr: &HashMap<String, Expr>) -> Expr {
    input_name_to_expr
        .get(name)
        .cloned()
        .unwrap_or_else(|| Expr::var(sanitize_identifier(name)))
}

fn output_var_name(
    step_index: usize,
    port: &str,
    output_vars: &HashMap<(usize, String), String>,
) -> String {
    output_vars
        .get(&(step_index, port.to_string()))
        .cloned()
        .unwrap_or_else(|| format!("step_{step_index}_{}", sanitize_identifier(port)))
}

fn json_value_to_expr(value: &serde_json::Value) -> Expr {
    match value {
        serde_json::Value::Null => Expr::Value(ValueExpr::Unit),
        serde_json::Value::Bool(value) => Expr::bool_lit(*value),
        serde_json::Value::Number(number) => number
            .as_i64()
            .map(Expr::int)
            .unwrap_or_else(|| Expr::Value(ValueExpr::Json(value.clone()))),
        serde_json::Value::String(value) => Expr::str_lit(value.clone()),
        serde_json::Value::Array(_) | serde_json::Value::Object(_) => {
            Expr::Value(ValueExpr::Json(value.clone()))
        }
    }
}

fn string_op_name(kind: &StringOpKind) -> &'static str {
    match kind {
        StringOpKind::Concat { .. } => "concat",
        StringOpKind::Split { .. } => "split",
        StringOpKind::Filter { .. } => "filter",
        StringOpKind::Map { .. } => "map",
        StringOpKind::Join { .. } => "join",
    }
}

fn json_op_name(kind: &JsonOpKind) -> &'static str {
    match kind {
        JsonOpKind::Extract { .. } => "extract",
        JsonOpKind::Parse => "parse",
        JsonOpKind::Serialize => "serialize",
    }
}

fn aggregate_name(kind: &AggregateKind) -> &'static str {
    match kind {
        AggregateKind::AllTrue => "all_true",
        AggregateKind::AnyTrue => "any_true",
        AggregateKind::Concat => "concat",
        AggregateKind::Merge => "merge",
        AggregateKind::CollectList => "collect_list",
    }
}

fn collection_family_name(family: &EmitCollectionFamily) -> &'static str {
    match family {
        EmitCollectionFamily::Map => "map",
        EmitCollectionFamily::Filter => "filter",
        EmitCollectionFamily::Fold => "fold",
        EmitCollectionFamily::Sort => "sort",
    }
}

fn transport_kind_name(kind: TransportKind) -> &'static str {
    match kind {
        TransportKind::FileRead => "file_read",
        TransportKind::FileWrite => "file_write",
        TransportKind::FileExists => "file_exists",
        TransportKind::ShellExec => "shell_exec",
        TransportKind::HttpRequest => "http_request",
        TransportKind::DirectoryList => "directory_list",
    }
}

fn map_abstract_type(abstract_type: &str) -> String {
    crate::type_mapping::resolve_and_emit(abstract_type, None, crate::type_mapping::Backend::Rust)
}

fn sanitize_identifier(value: &str) -> String {
    let mut out = value
        .chars()
        .map(|ch| if ch.is_alphanumeric() { ch } else { '_' })
        .collect::<String>();
    if out.is_empty() {
        out.push('_');
    }
    if out.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

