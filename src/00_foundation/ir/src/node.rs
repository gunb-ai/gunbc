/// Structural classification of a node's role in the DAG.
///
/// Set by the lowerer (from `ObligationCategory`) and read by the executor,
/// testgen, and derive — replacing the duplicated port-type heuristics
/// (`type_id.0 == "TransportRequest"`, etc.) with a single source of truth.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum NodeKind {
    /// Executes transport I/O (consumes TransportRequest).
    TransportExecute,
    /// Prepares a transport request.
    TransportPrepare,
    /// Parses a transport response.
    TransportParse,
    /// Provides a tool environment (emits ToolHandle).
    ToolEnvironment,
    /// Consumes a tool handle.
    ToolConsumer,
    /// Provides a resource (emits FilesystemHandle, Credential, etc.).
    ResourceEnvironment,
    /// Acquires a resource.
    ResourceAcquire,
    /// Releases a resource.
    ResourceRelease,
    /// Feeds a callable's declared parameter into the DAG as an input source.
    ParamSource,
    /// Pure computation (no I/O boundary).
    #[default]
    Pure,
}

impl NodeKind {
    /// Whether this node participates in a transport triplet (prepare/execute/parse).
    pub fn is_transport(&self) -> bool {
        matches!(
            self,
            NodeKind::TransportPrepare | NodeKind::TransportExecute | NodeKind::TransportParse
        )
    }
}

/// Transport protocol class for service operations.
///
/// Set by the lowerer from DSL `transport` blocks. Read by testgen, fidelity
/// analysis, and derive — replacing `Any`-based downcasting of `LoweredOp`
/// with a first-class metadata field on `Node`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ServiceTransportClass {
    /// Transport class could not be determined.
    Unknown,
    /// Shell command execution (local process).
    ShellLocal,
    /// REST API calls over HTTP/HTTPS (network).
    RestNetwork,
    /// Filesystem operations (local I/O boundary).
    FileBoundary,
    /// In-process / direct function call (no I/O).
    LocalDirect,
    /// Stub transport for interface capabilities compiled without a concrete binding.
    /// DryRun-compatible; errors in Real mode when no concrete binding exists.
    InterfaceStub,
}

impl ServiceTransportClass {
    /// Transport cost classification (mirrors `transport_depth` in `std/fidelity.dag`).
    ///
    /// Single authoritative source for the transport→FermiDepth mapping.
    /// The DSL `transport_depth()` function should be kept in sync.
    pub fn fermi_depth(&self) -> &'static str {
        match self {
            Self::LocalDirect => "Xs",
            Self::InterfaceStub => "Xs",
            Self::ShellLocal => "S",
            Self::FileBoundary => "S",
            Self::RestNetwork => "L",
            Self::Unknown => "Xl",
        }
    }

    /// Whether this transport class is hermetic (can be fully mocked in DryRun).
    ///
    /// Single authoritative source for the transport→hermetic mapping.
    /// The DSL `transport_hermetic()` function should be kept in sync.
    pub fn is_hermetic(&self) -> bool {
        match self {
            Self::LocalDirect => true,
            Self::InterfaceStub => true,
            Self::ShellLocal => true,
            Self::FileBoundary => true,
            Self::RestNetwork => false,
            Self::Unknown => false,
        }
    }
}

/// Source location for a lowered node, linking back to the `.dag` source (CP-51).
///
/// Enables post-lowering stages (verify, derive, emit, error reporting) to
/// point errors at the original source location rather than generated node IDs.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum NodeOrigin {
    /// Node derived directly from a user-authored AST item.
    UserCode {
        /// Source file path (relative to dsl root).
        file: String,
        /// Module path (e.g., "tools.clippy").
        module: String,
        /// Item name within the module (e.g., "clippy_lint").
        item: String,
        /// Byte offset range in the source file.
        span_start: usize,
        /// End of byte offset range.
        span_end: usize,
    },
    /// Node generated by pattern expansion (service call triplet, content_upsert, loop).
    PatternExpansion {
        /// Source file where the pattern was invoked.
        file: String,
        /// Module path.
        module: String,
        /// Item containing the pattern invocation.
        item: String,
        /// Byte offset range in the source file.
        span_start: usize,
        /// End of byte offset range.
        span_end: usize,
        /// Kind of pattern that generated this node.
        pattern_kind: String,
    },
    /// Node from the standard library (not user-authored).
    Stdlib {
        /// Module path (e.g., "std.patterns").
        module: String,
    },
    /// Origin not tracked (backward compat with pre-CP-51 DAGs).
    #[default]
    Unknown,
}

/// A node in the DAG, generic over its operation type.
///
/// Nodes are pure transformations of inputs to outputs.
/// World-writes are determined structurally by boundary detection,
/// not by node annotations.
///
/// # Tool Acquisition
///
/// Tools are acquired via an environment node that flows ToolHandle values
/// through DAG edges. Nodes that need tools declare `tool:*` input ports
/// and receive handles from upstream environment nodes.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Node<T> {
    /// Unique identifier for this node
    pub id: NodeId,
    /// Input ports
    pub inputs: Vec<Port>,
    /// Output ports
    pub outputs: Vec<Port>,
    /// The node's body: either an opaque operation or a nested sub-DAG
    pub body: NodeBody<T>,
    /// I/O examples for test generation.
    ///
    /// Each example specifies concrete input values and expected output values.
    /// Testgen uses these to generate per-node unit tests that call
    /// `execute_single_node` with the given inputs and verify the outputs.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub examples: Vec<NodeIoExample>,
    /// Optional execution log detail override for this node/composition.
    ///
    /// For SubDag nodes, this acts as a compositional default for all lowered
    /// descendants unless overridden more specifically by nested nodes/ports.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub log_detail: Option<LogDetailLevel>,
    /// Structural classification of this node's role.
    ///
    /// Set by the lowerer from `ObligationCategory`. The executor reads this
    /// instead of re-deriving node kind from port type strings.
    ///
    /// Defaults to `Pure` for backward compatibility with serialized DAGs
    /// that predate this field. The lowerer stamps all nodes via
    /// `stamp_node_kinds()` before they reach the executor.
    #[serde(default)]
    pub kind: NodeKind,
    /// Canonical identity of the service operation this node represents.
    ///
    /// Stamped by the lowerer from `ServiceCallMetadata` on transport nodes,
    /// and by freshness steps via `FreshnessStep::subsumes`. Used for
    /// composition-level overlap detection: if two nodes in a composed DAG
    /// share the same `OperationKey`, the composition is rejected as a
    /// duplicate upsert.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub operation_key: Option<OperationKey>,
    /// Transport protocol class for this node's service operation.
    ///
    /// Stamped by the lowerer from `ServiceCallMetadata` on transport triplet
    /// nodes (prepare/execute/parse). `None` for pure computation nodes.
    /// Read by testgen and fidelity analysis instead of `Any`-downcasting
    /// through `LoweredOp`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub transport_class: Option<ServiceTransportClass>,
    /// Static fingerprint for compile-time redundancy detection (C22).
    ///
    /// When two transport nodes share the same fingerprint, they perform
    /// provably identical work. The validator rejects such duplicates.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub static_fingerprint: Option<StaticFingerprint>,
    /// Source origin linking this node to its `.dag` source location (CP-51).
    ///
    /// Defaults to `Unknown` for backward compatibility with serialized DAGs.
    /// The lowerer stamps all user-code nodes with `UserCode` or
    /// `PatternExpansion` origin.
    #[serde(default)]
    pub origin: NodeOrigin,
}

impl<T> Node<T> {
    /// Create a new opaque node.
    pub fn opaque(id: impl Into<NodeId>, inputs: Vec<Port>, outputs: Vec<Port>, op: T) -> Self {
        Self {
            id: id.into(),
            inputs,
            outputs,
            body: NodeBody::Opaque(op),
            examples: Vec::new(),
            log_detail: None,
            kind: NodeKind::Pure,
            operation_key: None,
            transport_class: None,
            static_fingerprint: None,
            origin: NodeOrigin::default(),
        }
    }

    /// Create a sub-DAG node with interface inferred from the inner DAG.
    ///
    /// Input ports are derived from the inner DAG's entrypoints (unconnected
    /// input ports). Output ports are derived from the inner DAG's boundaries
    /// (unconnected output ports). This makes it impossible to declare an
    /// interface that doesn't match the inner structure.
    ///
    /// Guards are stripped from inferred ports — use [`with_input_guard`] to
    /// add routing guards after construction.
    pub fn subdag(id: impl Into<NodeId>, dag: Dag<T>) -> Self {
        let entrypoints = detect_entrypoints(&dag);
        let boundaries = detect_boundaries(&dag);

        // Build input ports from entrypoints, deduplicated by name.
        // Guards are stripped — they're an internal routing concern.
        let mut seen_inputs = HashSet::new();
        let mut inputs = Vec::new();
        for (node_id, port_name, _) in &entrypoints.entrypoint_ports {
            if seen_inputs.insert(port_name.clone()) {
                if let Some(node) = dag.get_node(node_id) {
                    if let Some(port) = node.inputs.iter().find(|p| &p.name == port_name) {
                        let mut inferred = Port::with_cardinality(
                            port.name.0.as_str(),
                            port.type_id.0.as_str(),
                            port.cardinality,
                        );
                        // Preserve resource_access so SubDag auto-inference
                        // doesn't lose Write/Exclusive mode information.
                        inferred.resource_access = port.resource_access;
                        // Preserve multiplicity (fan-in ports stay fan-in).
                        inferred.multiplicity = port.multiplicity;
                        inputs.push(inferred);
                    }
                }
            }
        }

        // Build output ports from boundaries, deduplicated by name.
        let mut seen_outputs = HashSet::new();
        let mut outputs = Vec::new();
        for (node_id, port_name) in &boundaries.boundary_ports {
            if seen_outputs.insert(port_name.clone()) {
                if let Some(node) = dag.get_node(node_id) {
                    if let Some(port) = node.outputs.iter().find(|p| &p.name == port_name) {
                        let mut inferred = Port::with_cardinality(
                            port.name.0.as_str(),
                            port.type_id.0.as_str(),
                            port.cardinality,
                        );
                        inferred.resource_access = port.resource_access;
                        inferred.multiplicity = port.multiplicity;
                        outputs.push(inferred);
                    }
                }
            }
        }

        // Sort by name for deterministic interface ordering.
        inputs.sort_by(|a, b| a.name.0.cmp(&b.name.0));
        outputs.sort_by(|a, b| a.name.0.cmp(&b.name.0));

        Self {
            id: id.into(),
            inputs,
            outputs,
            body: NodeBody::SubDag(dag, SubDagKind::default()),
            examples: Vec::new(),
            log_detail: None,
            kind: NodeKind::Pure,
            operation_key: None,
            transport_class: None,
            static_fingerprint: None,
            origin: NodeOrigin::default(),
        }
    }

    /// Add an I/O example for test generation.
    ///
    /// Examples are used by testgen to generate per-node unit tests.
    /// Each example specifies concrete input values and expected output values.
    ///
    /// ```text
    /// Node::opaque("prepare", inputs, outputs, MyOp::Prepare)
    ///     .with_example(
    ///         [("input".into(), Value::Str("hello".into()))].into(),
    ///         [("output".into(), Value::Str("HELLO".into()))].into(),
    ///     )
    /// ```
    pub fn with_example(
        mut self,
        inputs: HashMap<String, Value>,
        expected_outputs: HashMap<String, Value>,
    ) -> Self {
        self.examples.push(NodeIoExample {
            inputs,
            expected_outputs,
            description: None,
        });
        self
    }

    /// Attach source provenance to the node.
    pub fn with_origin(mut self, origin: NodeOrigin) -> Self {
        self.origin = origin;
        self
    }

    /// Add a described I/O example for test generation.
    ///
    /// Like `with_example`, but includes a description used in the generated
    /// test function name and doc comment.
    pub fn with_described_example(
        mut self,
        description: impl Into<String>,
        inputs: HashMap<String, Value>,
        expected_outputs: HashMap<String, Value>,
    ) -> Self {
        self.examples.push(NodeIoExample {
            inputs,
            expected_outputs,
            description: Some(description.into()),
        });
        self
    }

    /// Set the structural node kind.
    pub fn with_kind(mut self, kind: NodeKind) -> Self {
        self.kind = kind;
        self
    }

    /// Set the operation key for composition overlap detection.
    pub fn with_operation_key(mut self, key: OperationKey) -> Self {
        self.operation_key = Some(key);
        self
    }

    /// Set the transport protocol class for this node.
    pub fn with_transport_class(mut self, tc: ServiceTransportClass) -> Self {
        self.transport_class = Some(tc);
        self
    }

    /// Set an execution log detail override for this node.
    pub fn with_log_detail(mut self, log_detail: LogDetailLevel) -> Self {
        self.log_detail = Some(log_detail);
        self
    }

    /// Set an execution log detail override for a specific input port.
    ///
    /// # Panics
    ///
    /// Panics if no input port with the given name exists.
    pub fn with_input_log_detail(
        mut self,
        port: impl Into<PortName>,
        log_detail: LogDetailLevel,
    ) -> Self {
        let port_name: PortName = port.into();
        let input = self
            .inputs
            .iter_mut()
            .find(|p| p.name == port_name)
            .unwrap_or_else(|| panic!("no input port '{}' on node '{}'", port_name, self.id));
        input.log_detail = Some(log_detail);
        self
    }

    /// Add a routing guard to an input port.
    ///
    /// Used by pattern builders (Branch, If) to control conditional execution.
    ///
    /// # Panics
    ///
    /// Panics if no input port with the given name exists.
    pub fn with_input_guard(mut self, port: &str, guard: Predicate) -> Self {
        let port_name: PortName = port.into();
        let p = self
            .inputs
            .iter_mut()
            .find(|p| p.name == port_name)
            .unwrap_or_else(|| panic!("no input port '{}' on node '{}'", port, self.id));
        p.guard = Some(guard);
        self
    }

    /// Override the cardinality of an output port.
    ///
    /// Used by pattern builders when the SubDag's runtime behavior differs
    /// from the inner boundary's declared cardinality (e.g., If pattern
    /// produces optional output even though the inner boundary is scalar).
    pub(crate) fn with_output_cardinality(mut self, port: &str, cardinality: Cardinality) -> Self {
        let port_name: PortName = port.into();
        let p = self
            .outputs
            .iter_mut()
            .find(|p| p.name == port_name)
            .unwrap_or_else(|| panic!("no output port '{}' on node '{}'", port, self.id));
        p.cardinality = cardinality;
        self
    }

    /// Map the operation type for this node, recursively for sub-DAGs.
    pub fn map_ops<U, F>(self, f: &mut F) -> Node<U>
    where
        F: FnMut(T) -> U,
    {
        let body = match self.body {
            NodeBody::Opaque(op) => NodeBody::Opaque(f(op)),
            NodeBody::SubDag(dag, kind) => NodeBody::SubDag(dag.map_ops(f), kind),
        };

        Node {
            id: self.id,
            inputs: self.inputs,
            outputs: self.outputs,
            body,
            examples: self.examples,
            log_detail: self.log_detail,
            kind: self.kind,
            operation_key: self.operation_key,
            transport_class: self.transport_class,
            static_fingerprint: self.static_fingerprint,
            origin: self.origin,
        }
    }

    /// Check if this node is opaque (not a sub-DAG).
    pub fn is_opaque(&self) -> bool {
        matches!(self.body, NodeBody::Opaque(_))
    }

    /// Check if this node is a sub-DAG.
    pub fn is_subdag(&self) -> bool {
        matches!(self.body, NodeBody::SubDag(..))
    }
}

/// Structural classification of a SubDag node (CP-35).
///
/// Stamped at build time by `LoopBuilder`/`BranchBuilder` so that the executor
/// can dispatch without reverse-engineering the internal DAG topology.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq)]
pub enum SubDagKind {
    /// Unclassified composition (default for backward compat).
    #[default]
    Regular,
    /// Loop pattern: unpack → body → pack.
    Loop {
        /// Port name carrying the per-element value into the body.
        element_port: String,
        /// Non-element input ports forwarded from the unpack node.
        extra_input_ports: Vec<String>,
    },
}

/// The body of a node: either an opaque operation or a nested sub-DAG.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum NodeBody<T> {
    /// An opaque operation — we trust it, don't look inside
    Opaque(T),
    /// A nested sub-DAG — same structure, recursive.
    /// The `SubDagKind` classifies the pattern (loop, branch, regular).
    SubDag(Dag<T>, SubDagKind),
}

/// An I/O example for a node, used by testgen to generate per-node unit tests.
///
/// This is the "on-node" form of examples — it uses exact `Value` matching
/// for expected outputs. For richer matching (contains, non-empty, predicates),
/// use `NodeExample` + `OutputMatcher` from `gunbc-test` via MockSpec.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NodeIoExample {
    /// Input values keyed by port name.
    pub inputs: HashMap<String, Value>,
    /// Expected output values keyed by port name (exact match).
    pub expected_outputs: HashMap<String, Value>,
    /// Optional description for the generated test name.
    pub description: Option<String>,
}
