#!/usr/bin/env python3
"""ACCEPTANCE ITEM 4 (msg_4199351d): the sparse fold's still_missing_after decision
is the ONE authority for "does this call need a second argument round".

This deletes the coarse outer gate call_needs_generic_rebinding_pass and its helper
expr_contains_lambda from src/v1/04_infer.dag -- no per-site check is added -- and
replaces them with the bare fold.  The .dag is the authority; the stage0 mirror is
regenerated by the CI producer afterwards (this script never touches it).

Fail-closed: every anchor must match EXACTLY ONCE or the script exits 4 without
writing.  Run with --check to only verify the anchors (used by the A/B harness to
prove the treatment tree really has the gate deleted).
"""
import sys, subprocess, pathlib

DAG = "src/v1/04_infer.dag"

GATE_BLOCK = """// Second pass of a call is admitted only when the old trigger would have run one:
// the callee has generics, discovery produced a nonempty substitution, and some
// argument contains a lambda. Per-argument recheck is then a subset of that pass.
fn call_needs_generic_rebinding_pass(call_args: List<Node>, generic_names: List<String>, subst: Map<String, Node>) -> Bool {
  if generic_names |> count == 0 {
    false
  } else if map_is_empty(subst) {
    false
  } else {
    call_args |> any(a => expr_contains_lambda(n: arg_value(n: a)))
  }
}

"""

HELPER_BLOCK = """fn expr_contains_lambda(n: Node) -> Bool {
  is_lambda_expr(e: n) || (n.children |> any(c => expr_contains_lambda(n: c)))
}

"""

GATED_FOLD = """  if !call_needs_generic_rebinding_pass(call_args: call_args, generic_names: generic_names, subst: discovered.subst) {
    first_state
  } else {
    fold(discovered.readings |> enumerate, init: first_state, f: (st, pair) =>
"""

BARE_FOLD = """  fold(discovered.readings |> enumerate, init: first_state, f: (st, pair) =>
"""

# The gated fold's closing: "    )\n  }\n}" (fold close + else close + if close)
# becomes "    )\n}" (fold close + fn close).  Anchored by the fold body tail so we
# only touch THIS fold.
GATED_TAIL = """      } else {
        st
      }
    )
  }
}
"""
BARE_TAIL = """      } else {
        st
      }
    )
}
"""

def edits():
    return [(GATE_BLOCK, ""), (HELPER_BLOCK, ""), (GATED_FOLD, BARE_FOLD), (GATED_TAIL, BARE_TAIL)]

def main():
    check = "--check" in sys.argv
    path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else pathlib.Path(DAG)
    if not path.exists():
        print("MISSING", path); return 2
    s = path.read_text()
    for old, new in edits():
        n = s.count(old)
        if n != 1:
            print("DELETE-GATE ANCHOR NOT UNIQUE (%d) in %s: %r" % (n, path, old[:70]))
            return 4
    if s.count("call_needs_generic_rebinding_pass") != 2:
        print("DELETE-GATE unexpected gate reference count: %d" % s.count("call_needs_generic_rebinding_pass"))
        return 4
    if s.count("expr_contains_lambda") != 3:
        print("DELETE-GATE unexpected helper reference count: %d" % s.count("expr_contains_lambda"))
        return 4
    for old, new in edits():
        s = s.replace(old, new)
    if "call_needs_generic_rebinding_pass" in s or "expr_contains_lambda" in s:
        print("DELETE-GATE left residue"); return 4
    if check:
        print("DELETE-GATE APPLIES CLEANLY (check-only)"); return 0
    path.write_text(s)
    print("DELETE-GATE OK %s: gate+helper deleted, sparse fold is the sole authority" % path)
    return 0

if __name__ == "__main__":
    sys.exit(main())
