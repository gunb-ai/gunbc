// DSL fn body evaluation tests — prove the evaluator handles makegen rendering
// ============================================================================

/// Compile the makegen project and extract fn bodies from the lowered DAG.
fn makegen_fn_bodies() -> HashMap<String, LoweredFnBody> {
    let dsl_root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../dsl");
    let dag_file = dsl_root.join("tools/makegen.dag");
    let context = DriverContext {
        roots: vec![dsl_root],
        target_file: Some(dag_file),
    };
    let output = compile_from_context(&context).expect("makegen should compile");
    let mut bodies = HashMap::new();
    for node in &output.lowered_dag.nodes {
        if let NodeBody::Opaque(LoweredOp::Callable {
            kind: CallableKind::Fn,
            name,
            fn_body: Some(body),
            ..
        }) = &node.body
        {
            bodies.insert(name.clone(), *body.clone());
        }
    }
    bodies
}

/// `render_header()` — zero-input fn, constant string output.
#[test]
fn dsl_eval_render_header() {
    let fns = makegen_fn_bodies();
    let body = fns
        .get("render_header")
        .expect("render_header fn body should exist");
    let result = daglang_lower::eval::evaluate_fn_body(body, &HashMap::new(), &fns)
        .expect("render_header should evaluate");
    let header = result
        .get("return")
        .and_then(Value::as_str)
        .expect("render_header should return a string");
    assert_eq!(
        header,
        "# Generated by gunbc-makegen\n\
         # DO NOT EDIT - regenerate with: cargo run -p gunbc-dag --bin gunbc-makegen\n"
    );
}

