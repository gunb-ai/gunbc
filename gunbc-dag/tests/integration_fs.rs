#![allow(clippy::disallowed_methods)] // Integration tests use direct fs for test verification

use gunbc_dag::{build_bootstrap_graph, build_makegen_graph};
use gunbc_exec::{execute_with_mode_and_inputs, BoundaryMocks, ExecutionMode};
use gunbc_infra::test_utils::{cleanup_dir, temp_dir};
use gunbc_ir::{detect_entrypoints, Value};
use gunbc_lib_transport::test_backend::VirtualTransportBackend;
use gunbc_lib_transport::TransportBackendGuard;
use gunbc_test::{guard_test, FermiCost, TestClass};
use std::env;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, OnceLock};

struct TempWorkspace {
    root: PathBuf,
}

impl TempWorkspace {
    fn new(label: &str) -> Self {
        Self { root: temp_dir(label) }
    }

    fn path(&self) -> &Path {
        &self.root
    }
}

impl Drop for TempWorkspace {
    fn drop(&mut self) {
        cleanup_dir(&self.root);
    }
}

static TEST_LOCK: OnceLock<Mutex<()>> = OnceLock::new();

fn test_lock() -> &'static Mutex<()> {
    TEST_LOCK.get_or_init(|| Mutex::new(()))
}

struct CurrentDirGuard {
    original: PathBuf,
}

impl CurrentDirGuard {
    fn new(path: &Path) -> Self {
        let original = env::current_dir().expect("get current dir");
        env::set_current_dir(path).expect("set current dir");
        Self { original }
    }
}

impl Drop for CurrentDirGuard {
    fn drop(&mut self) {
        let _ = env::set_current_dir(&self.original);
    }
}

#[derive(Clone, Copy, Debug)]
enum BackendKind {
    Virtual,
    Real,
}

const COST_VIRTUAL: FermiCost = FermiCost::XS;
const COST_REAL_FS: FermiCost = FermiCost::S;
const COST_REAL_SHELL: FermiCost = FermiCost::M;

fn should_run_case(name: &str, cost: FermiCost, requires: &[&str]) -> bool {
    guard_test(name, TestClass::Integration, cost, requires, &[])
}

fn input_mocks_for_entrypoints<T: Clone>(
    dag: &gunbc_ir::Dag<T>,
    mut value_for: impl FnMut(&str, &str) -> Option<Value>,
) -> BoundaryMocks {
    let mut mocks = BoundaryMocks::new();
    let entrypoints = detect_entrypoints(dag);
    for (node_id, port_name, _) in &entrypoints.entrypoint_ports {
        if let Some(value) = value_for(&node_id.0, &port_name.0) {
            mocks.set_input(node_id.0.clone(), port_name.0.clone(), value);
        }
    }
    mocks
}

fn run_makegen_case(kind: BackendKind) {
    let dag = build_makegen_graph().expect("graph should build");
    let path = "Makefile";

    let input_mocks = input_mocks_for_entrypoints(&dag, |_node_id, port_name| {
        match port_name {
            "path" => Some(Value::Str(path.to_string())),
            "check_mode" => Some(Value::Bool(false)),
            _ => None,
        }
    });

    match kind {
        BackendKind::Virtual => {
            let backend = Arc::new(VirtualTransportBackend::new());
            let _guard = TransportBackendGuard::install(backend.clone());

            execute_with_mode_and_inputs(&dag, ExecutionMode::Real, Some(&input_mocks))
                .expect("execute makegen");

            let content = backend
                .read_file(path)
                .expect("Makefile should exist in virtual FS");
            assert!(
                content.contains("Generated by gunbc-makegen"),
                "Makefile header missing"
            );
        }
        BackendKind::Real => {
            let workspace = TempWorkspace::new("makegen-real-fs");
            let _cwd = CurrentDirGuard::new(workspace.path());

            execute_with_mode_and_inputs(&dag, ExecutionMode::Real, Some(&input_mocks))
                .expect("execute makegen");

            let makefile_path = workspace.path().join(path);
            let content = std::fs::read_to_string(&makefile_path).expect("Makefile should exist");
            assert!(
                content.contains("Generated by gunbc-makegen"),
                "Makefile header missing"
            );
        }
    }
}

fn run_bootstrap_case(kind: BackendKind) {
    let dag = build_bootstrap_graph().expect("graph should build");

    let input_mocks = input_mocks_for_entrypoints(&dag, |node_id, port_name| match port_name {
        "check_mode" => Some(Value::Bool(false)),
        "path" => {
            if node_id.contains("makefile") {
                Some(Value::Str("Makefile".to_string()))
            } else if node_id.contains("gitignore") {
                Some(Value::Str(".gitignore".to_string()))
            } else {
                None
            }
        }
        _ => None,
    });

    match kind {
        BackendKind::Virtual => {
            let backend = Arc::new(VirtualTransportBackend::new());
            backend.create_dir_all("crates/example");
            let _guard = TransportBackendGuard::install(backend.clone());

            execute_with_mode_and_inputs(&dag, ExecutionMode::Real, Some(&input_mocks))
                .expect("execute bootstrap");

            let makefile = backend
                .read_file("Makefile")
                .expect("Makefile should exist in virtual FS");
            let gitignore = backend
                .read_file(".gitignore")
                .expect(".gitignore should exist in virtual FS");

            assert!(
                makefile.contains("Generated by gunbc-makegen"),
                "Makefile header missing"
            );
            assert!(
                gitignore.contains("Generated by gunbc-bootstrap"),
                ".gitignore header missing"
            );
        }
        BackendKind::Real => {
            if cfg!(windows) {
                eprintln!("skipping bootstrap real-fs integration on Windows (uses 'find')");
                return;
            }

            let workspace = TempWorkspace::new("bootstrap-real-fs");
            let crates_dir = workspace.path().join("crates").join("example");
            std::fs::create_dir_all(&crates_dir).expect("create crates/example");

            let _cwd = CurrentDirGuard::new(workspace.path());
            execute_with_mode_and_inputs(&dag, ExecutionMode::Real, Some(&input_mocks))
                .expect("execute bootstrap");

            let makefile_path = workspace.path().join("Makefile");
            let gitignore_path = workspace.path().join(".gitignore");

            let makefile = std::fs::read_to_string(&makefile_path).expect("Makefile should exist");
            let gitignore =
                std::fs::read_to_string(&gitignore_path).expect(".gitignore should exist");

            assert!(
                makefile.contains("Generated by gunbc-makegen"),
                "Makefile header missing"
            );
            assert!(
                gitignore.contains("Generated by gunbc-bootstrap"),
                ".gitignore header missing"
            );
        }
    }
}

#[test]
fn test_makegen_fs_writes_makefile() {
    let _lock = test_lock().lock().expect("lock test");

    if should_run_case(
        "test_makegen_fs_writes_makefile::virtual",
        COST_VIRTUAL,
        &[],
    ) {
        run_makegen_case(BackendKind::Virtual);
    }

    if should_run_case(
        "test_makegen_fs_writes_makefile::real",
        COST_REAL_FS,
        &[],
    ) {
        run_makegen_case(BackendKind::Real);
    }
}

#[test]
fn test_bootstrap_fs_writes_outputs() {
    let _lock = test_lock().lock().expect("lock test");

    if should_run_case(
        "test_bootstrap_fs_writes_outputs::virtual",
        COST_VIRTUAL,
        &[],
    ) {
        run_bootstrap_case(BackendKind::Virtual);
    }

    if should_run_case(
        "test_bootstrap_fs_writes_outputs::real",
        COST_REAL_SHELL,
        &["shell", "find"],
    ) {
        run_bootstrap_case(BackendKind::Real);
    }
}
