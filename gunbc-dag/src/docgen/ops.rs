fn details_block(title: &str, tests: &[TestCase]) -> String {
    let mut out = Vec::new();
    out.push("<details>".to_string());
    out.push(format!("<summary><strong>{}</strong></summary>", title));
    out.push(String::new());
    for test in tests {
        out.push(format!("- {} — {}", test.name, test.description));
    }
    out.push(String::new());
    out.push("</details>".to_string());
    out.join("\n")
}

fn replace_section(doc: &str, key: &str, replacement: &str) -> Result<String, ExecError> {
    let begin = format!("<!-- BEGIN GENERATED:{key} -->");
    let end = format!("<!-- END GENERATED:{key} -->");

    let start = doc.find(&begin)
        .ok_or_else(|| ExecError::new(format!("docgen: missing begin marker: {begin}")))?;
    let rest = &doc[start + begin.len()..];
    let end_rel = rest.find(&end)
        .ok_or_else(|| ExecError::new(format!("docgen: missing end marker: {end}")))?;

    let before = &doc[..start + begin.len()];
    let after = &rest[end_rel..];
    Ok(format!("{before}\n{replacement}\n{after}"))
}

fn wrap_rust(snippet: &str) -> String {
    format!("```rust\n{}\n```", snippet.trim_end())
}

fn wrap_rust_with_prefix(prefix: &str, snippet: &str) -> String {
    format!("```rust\n{}\n{}\n```", prefix, snippet.trim_end())
}

fn strip_module_docs(src: &str) -> String {
    let mut out = Vec::new();
    let mut skipping = true;
    for line in src.lines() {
        if skipping {
            if line.trim_start().starts_with("//!") || line.trim().is_empty() {
                continue;
            }
            skipping = false;
        }
        out.push(line.to_string());
    }
    out.join("\n")
}

fn extract_fn(src: &str, fn_name: &str) -> Option<String> {
    let lines: Vec<&str> = src.lines().collect();
    let target = format!("fn {fn_name}");
    for (idx, line) in lines.iter().enumerate() {
        if !line.contains(&target) {
            continue;
        }

        let mut start = idx;
        while start > 0 {
            let prev = lines[start - 1].trim_start();
            if prev.starts_with("///") || prev.starts_with("#[") {
                start -= 1;
                continue;
            }
            if prev.is_empty() {
                start -= 1;
                continue;
            }
            break;
        }

        let mut buf = Vec::new();
        let mut brace_count = 0i32;
        let mut saw_brace = false;
        for line in &lines[start..] {
            buf.push((*line).to_string());
            for ch in line.chars() {
                if ch == '{' {
                    brace_count += 1;
                    saw_brace = true;
                } else if ch == '}' {
                    brace_count -= 1;
                }
            }
            if saw_brace && brace_count == 0 {
                break;
            }
        }

        if !buf.is_empty() {
            return Some(buf.join("\n"));
        }
    }

    None
}

fn strip_guard_test(src: &str) -> String {
    let mut out = Vec::new();
    let mut skip_guard = false;
    for line in src.lines() {
        let trimmed = line.trim();
        if line.contains("guard_test(") {
            skip_guard = true;
            continue;
        }
        if skip_guard {
            if trimmed == "return ();" || trimmed == "return();" || trimmed == "return ()" {
                continue;
            }
            if trimmed == "};" {
                skip_guard = false;
                continue;
            }
        }
        out.push(line.to_string());
    }
    out.join("\n")
}

fn normalize_colons(src: &str) -> String {
    let mut s = src.replace(" :: ", "::");
    s = s.replace(" ::", "::");
    s = s.replace(":: ", "::");
    s = s.replace("::\n", "::");
    s
}

fn read_to_string(path: &str) -> Result<String, ExecError> {
    fs::read_to_string(path).map_err(|e| ExecError::new(format!("failed to read {path}: {e}")))
}

#[derive(Debug, Clone)]
struct TestCase {
    name: String,
    description: String,
}

fn collect_tests_from_file(path: &str) -> Result<Vec<TestCase>, ExecError> {
    let content = read_to_string(path)?;
    Ok(collect_tests_from_content(&content, false))
}

fn collect_tests_from_dir(dir: &Path, exclude: &[&str]) -> Result<Vec<TestCase>, ExecError> {
    let mut files = Vec::new();
    collect_rs_files(dir, &mut files)?;
    files.sort();

    let mut tests = Vec::new();
    for path in files {
        if let Some(name) = path.file_name().and_then(|s| s.to_str()) {
            if exclude.iter().any(|ex| ex == &name) {
                continue;
            }
        }
        let content = read_to_string(path.to_str().unwrap_or_default())?;
        tests.extend(collect_tests_from_content(&content, true));
    }

    tests.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(tests)
}

fn collect_rs_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), ExecError> {
    for entry in fs::read_dir(dir).map_err(|e| ExecError::new(format!("failed to read {dir:?}: {e}")))? {
        let entry = entry.map_err(|e| ExecError::new(format!("failed to read dir entry: {e}")))?;
        let path = entry.path();
        if path.is_dir() {
            collect_rs_files(&path, out)?;
        } else if path.extension().and_then(|s| s.to_str()) == Some("rs") {
            out.push(path);
        }
    }
    Ok(())
}

fn collect_tests_from_content(content: &str, allow_non_test_attr: bool) -> Vec<TestCase> {
    let mut tests = Vec::new();
    let mut doc_lines: Vec<String> = Vec::new();
    let mut saw_test_attr = false;

    for line in content.lines() {
        let trimmed = line.trim_start();

        if trimmed.starts_with("///") {
            doc_lines.push(trimmed.trim_start_matches("///").trim().to_string());
            continue;
        }

        if trimmed.starts_with("#[test]") {
            saw_test_attr = true;
            continue;
        }

        if trimmed.starts_with("#[") && allow_non_test_attr {
            continue;
        }

        if let Some(name) = parse_fn_name(trimmed) {
            if saw_test_attr || name.starts_with("test_") {
                let desc = if !doc_lines.is_empty() {
                    first_sentence(&doc_lines.join(" "))
                } else {
                    name_to_desc(&name)
                };
                tests.push(TestCase {
                    name,
                    description: desc,
                });
            }
            doc_lines.clear();
            saw_test_attr = false;
            continue;
        }

        if !trimmed.is_empty() {
            doc_lines.clear();
        }
    }

    tests
}

fn parse_fn_name(line: &str) -> Option<String> {
    let idx = line.find("fn ")?;
    let rest = &line[idx + 3..];
    let name: String = rest
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect();
    if name.is_empty() { None } else { Some(name) }
}

fn first_sentence(text: &str) -> String {
    if let Some(pos) = text.find('.') {
        text[..=pos].trim().to_string()
    } else {
        text.trim().to_string()
    }
}

fn name_to_desc(name: &str) -> String {
    let raw = name.strip_prefix("test_").unwrap_or(name);
    let spaced = raw.replace('_', " ");
    let mut chars = spaced.chars();
    match chars.next() {
        None => spaced,
        Some(first) => {
            let mut result = String::new();
            result.extend(first.to_uppercase());
            result.push_str(chars.as_str());
            result
        }
    }
}
