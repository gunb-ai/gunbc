/// Render Makefile content without the header.
///
/// This is called by `MakefileRenderer::render_content()` and produces
/// the body of the Makefile without the "Generated by" header.
fn render_makefile_content(registry: &ToolRegistry, config: &BuildConfig) -> String {
    let mut output = String::new();

    // Naming convention header (from the-gunbai)
    output.push_str("# Naming convention:\n");
    output.push_str("#   make <target>      - verify only (CI-safe, fails on issues)\n");
    output.push_str("#   make <target>-fix  - auto-fix then verify (for dev)\n");
    output.push_str("#\n");
    output.push_str("# Dev workflow:     make test-fix  (fix everything, then test)\n");
    output.push_str("# CI verification:  make test      (verify fmt + lint + test)\n\n");

    // Default goal
    output.push_str(".DEFAULT_GOAL := help\n\n");

    // Phony targets - include core targets, meta targets, and tool targets
    output.push_str(".PHONY: help codegen ensure-codegen build clean testgen testgen-check fmt-fix lint-fix");

    // Add meta targets (with check and fix variants)
    for meta in &registry.meta_targets {
        output.push_str(&format!(" {}", meta.name));
        if meta.has_check_variant {
            output.push_str(&format!(" {}-check", meta.name));
        }
        if meta.has_fix_variant {
            output.push_str(&format!(" {}-fix", meta.name));
        }
    }

    // Add tool targets
    for tool in &registry.tools {
        output.push_str(&format!(" {} {}-dry", tool.short_name, tool.short_name));
        for extra in &tool.extra_targets {
            output.push_str(&format!(" {}-{}", tool.short_name, extra.suffix));
        }
    }
    output.push_str("\n\n");

    // Core build system targets
    output.push_str(&render_core_targets(config));

    // Help target
    output.push_str(&render_help_target(registry));

    // Meta targets (test, check, fmt, clippy)
    output.push_str(&render_meta_targets(registry, config));

    // Tool targets
    for tool in &registry.tools {
        output.push_str(&render_tool_target(tool));
        output.push_str(&render_dry_run_target(tool));
        for extra in &tool.extra_targets {
            output.push_str(&render_extra_target(tool, extra));
        }
    }

    output
}

/// Render core build system targets using BuildConfig.
fn render_core_targets(config: &BuildConfig) -> String {
    let mut output = String::new();

    // Codegen source tracking: find all Rust sources that affect generated output.
    // When any source in core/codegen or core/ir changes, the stamp becomes stale
    // and Make will re-run codegen before building any dependent target.
    output.push_str("# Codegen source tracking: rebuild generated files when sources change\n");
    output.push_str("CODEGEN_SOURCES := $(shell find core/codegen/src core/ir/src -name '*.rs' 2>/dev/null)\n\n");

    // Stamp file as a real Make target with source dependencies.
    // Make compares timestamps: if any source is newer than the stamp, codegen runs.
    output.push_str("# Stamp file tracks codegen freshness - rebuilds when sources change\n");
    output.push_str("buck-out/gen/.codegen-stamp: $(CODEGEN_SOURCES)\n");
    output.push_str(&format!(
        "{}@mkdir -p buck-out/gen && {} && touch buck-out/gen/.codegen-stamp\n\n",
        INDENT, config.codegen.to_shell()
    ));

    // Ensure codegen is up-to-date (convenience alias for stamp dependency).
    // Phony so Make always checks, but the real work is in the stamp target.
    output.push_str("# Ensure codegen is up-to-date (upsert: create if missing, update if stale)\n");
    output.push_str("ensure-codegen: buck-out/gen/.codegen-stamp\n\n");

    // Force regenerate CLIs from DAG entrypoints (also updates stamp)
    output.push_str("# Force regenerate CLIs from DAG entrypoints\n");
    output.push_str("codegen:\n");
    output.push_str(&format!("{}{}\n", INDENT, config.codegen_shell()));
    output.push_str(&format!("{}@mkdir -p buck-out/gen && touch buck-out/gen/.codegen-stamp\n\n", INDENT));

    // Full build transaction: codegen → testgen → cargo build → symlink
    output.push_str("# Full build transaction: codegen → testgen → cargo build\n");
    output.push_str("build: ensure-codegen testgen\n");
    output.push_str(&format!("{}{}\n\n", INDENT, config.build_shell()));

    // Rollback transaction: remove all generated artifacts
    output.push_str("# Rollback transaction: remove all generated artifacts\n");
    output.push_str("clean:\n");
    output.push_str(&format!(
        "{}@{} --release -- rollback\n",
        INDENT,
        CargoInvocation::standalone("codegen").command(),
    ));
    output.push_str(&format!("{}@rm -f buck-out/gen/.codegen-stamp\n\n", INDENT));

    // Testgen: regenerate tests from DAGs
    output.push_str("# Regenerate tests from DAG structures and MockSpecs\n");
    output.push_str("testgen:\n");
    output.push_str(&format!("{}{}\n\n", INDENT, config.testgen_shell()));

    // Testgen check: verify generated tests are not stale
    output.push_str("# Check if generated tests are stale (fails if regeneration needed)\n");
    output.push_str("testgen-check:\n");
    output.push_str(&format!("{}{}\n\n", INDENT, config.testgen_check_shell()));

    output
}

/// Render the help target.
fn render_help_target(registry: &ToolRegistry) -> String {
    let mut output = String::new();

    output.push_str("help:\n");
    output.push_str("\t@echo \"gunbc tools - generated Makefile\"\n");
    output.push_str("\t@echo \"\"\n");
    output.push_str("\t@echo \"Naming convention:\"\n");
    output.push_str("\t@echo \"  make <target>      - verify only (CI-safe)\"\n");
    output.push_str("\t@echo \"  make <target>-fix  - auto-fix then verify (for dev)\"\n");
    output.push_str("\t@echo \"\"\n");
    
    // Build transactions section
    output.push_str("\t@echo \"Build transactions:\"\n");
    output.push_str("\t@echo \"  build    - Commit: codegen → cargo build\"\n");
    output.push_str("\t@echo \"  clean    - Rollback: remove all generated artifacts\"\n");
    output.push_str("\t@echo \"  codegen  - Partial commit: just generate CLIs\"\n");
    output.push_str("\t@echo \"  testgen  - Regenerate tests from DAG structures\"\n");
    output.push_str("\t@echo \"  testgen-check  - Check if generated tests are stale\"\n");
    output.push_str("\t@echo \"\"\n");
    
    // Meta targets section
    output.push_str("\t@echo \"Development:\"\n");
    for meta in &registry.meta_targets {
        output.push_str(&format!(
            "\t@echo \"  {}  - {}\"\n",
            meta.name, meta.description
        ));
        if meta.has_fix_variant {
            let deps = if meta.fix_deps.is_empty() {
                "auto-fix".to_string()
            } else {
                format!("{} first", meta.fix_deps.join(" + "))
            };
            output.push_str(&format!(
                "\t@echo \"  {}-fix  - {} ({})\"\n",
                meta.name, meta.description, deps
            ));
        }
        if meta.has_check_variant {
            output.push_str(&format!(
                "\t@echo \"  {}-check  - {} (check only)\"\n",
                meta.name, meta.description
            ));
        }
    }
    output.push_str("\t@echo \"\"\n");
    
    // Tools section
    output.push_str("\t@echo \"Tools:\"\n");
    for tool in &registry.tools {
        let params = render_help_params(&tool.entrypoints);
        output.push_str(&format!(
            "\t@echo \"  {} {}  - {}\"\n",
            tool.short_name, params, tool.description
        ));
        for extra in &tool.extra_targets {
            output.push_str(&format!(
                "\t@echo \"  {}-{}  - {}\"\n",
                tool.short_name, extra.suffix, extra.description
            ));
        }
    }
    output.push_str("\t@echo \"\"\n");
    output.push_str("\t@echo \"Add -dry suffix for dry-run (e.g., make gist-dry)\"\n\n");

    output
}

/// Render meta targets using BuildConfig for commands.
fn render_meta_targets(registry: &ToolRegistry, config: &BuildConfig) -> String {
    let mut output = String::new();

    output.push_str("# ============================================================================\n");
    output.push_str("# Meta Targets - Development workflow commands\n");
    output.push_str("# ============================================================================\n\n");

    // Render alias targets for common fix dependencies
    // These are used as dependencies by -fix targets (e.g., test-fix: fmt-fix lint-fix)
    output.push_str(&render_fix_alias_targets(config));

    for meta in &registry.meta_targets {
        output.push_str(&render_meta_target(meta, config));
        if meta.has_fix_variant {
            output.push_str(&render_meta_fix_variant(meta, config));
        }
        if meta.has_check_variant {
            output.push_str(&render_meta_check_variant(meta, config));
        }
    }

    output
}

/// Render alias targets for common fix dependencies.
///
/// These provide consistent -fix naming so targets like test-fix can depend on fmt-fix.
fn render_fix_alias_targets(config: &BuildConfig) -> String {
    let mut output = String::new();

    // fmt-fix: alias for fmt (fmt IS the fix)
    output.push_str("# fmt-fix: apply formatting (alias for fmt)\n");
    output.push_str("fmt-fix:\n");
    output.push_str(&format!("{}{}\n\n", INDENT, config.fmt_shell()));

    // lint-fix: run clippy with --fix
    output.push_str("# lint-fix: auto-fix lint issues where possible\n");
    output.push_str("lint-fix: ensure-codegen\n");
    output.push_str(&format!("{}{}\n\n", INDENT, config.lint_fix_shell()));

    output
}

/// Render a single meta target using MetaTarget's get_command method.
fn render_meta_target(meta: &MetaTarget, config: &BuildConfig) -> String {
    let mut output = String::new();

    // Determine dependency based on prep level
    let mut deps = match meta.prep_level {
        PrepLevel::None => String::new(),
        PrepLevel::Codegen => " ensure-codegen".to_string(),
        PrepLevel::Full => " build".to_string(),
    };

    // Append extra dependencies (e.g., testgen-check for test target)
    for dep in &meta.extra_deps {
        deps.push(' ');
        deps.push_str(dep);
    }

    // Use MetaTarget's get_command which references BuildConfig via ConfigField
    let command = meta.get_command(config);
    output.push_str(&format!("# {}: {}\n", meta.name, meta.description));
    output.push_str(&format!("{}:{}\n", meta.name, deps));
    output.push_str(&format!("{}{}\n\n", INDENT, command));

    output
}

/// Render a check variant for a meta target.
fn render_meta_check_variant(meta: &MetaTarget, config: &BuildConfig) -> String {
    let mut output = String::new();

    // Use MetaTarget's get_check_command which references BuildConfig via ConfigField
    if let Some(check_cmd) = meta.get_check_command(config) {
        let dependency = match meta.prep_level {
            PrepLevel::None => "",
            PrepLevel::Codegen => " ensure-codegen",
            PrepLevel::Full => " build",
        };

        output.push_str(&format!("{}-check:{}\n", meta.name, dependency));
        output.push_str(&format!("{}{}\n\n", INDENT, check_cmd));
    }

    output
}

/// Render a fix variant for a meta target.
///
/// Following the-gunbai convention:
/// - `make test-fix` runs fmt-fix + lint-fix, then test
/// - `make clippy-fix` runs cargo clippy --fix
fn render_meta_fix_variant(meta: &MetaTarget, config: &BuildConfig) -> String {
    let mut output = String::new();

    if !meta.has_fix_variant {
        return output;
    }

    // Build dependencies list
    let mut deps = Vec::new();
    
    // Add fix_deps from meta target (e.g., ["fmt-fix", "lint-fix"])
    for dep in meta.get_fix_deps() {
        deps.push(dep.to_string());
    }

    // Add prep dependency based on prep level
    match meta.prep_level {
        PrepLevel::None => {}
        PrepLevel::Codegen => deps.push("ensure-codegen".to_string()),
        PrepLevel::Full => deps.push("build".to_string()),
    }

    let deps_str = if deps.is_empty() {
        String::new()
    } else {
        format!(" {}", deps.join(" "))
    };

    // Get the fix command (dedicated fix command or regular command)
    let fix_cmd = meta.get_fix_command(config).unwrap_or_else(|| meta.get_command(config));

    output.push_str(&format!("# {}-fix: auto-fix then verify\n", meta.name));
    output.push_str(&format!("{}-fix:{}\n", meta.name, deps_str));
    output.push_str(&format!("{}{}\n\n", INDENT, fix_cmd));

    output
}

/// Render help text for parameters.
fn render_help_params(params: &[EntrypointParam]) -> String {
    params
        .iter()
        .map(|p| {
            if let Some(ref default) = p.default {
                format!("[{}={}]", p.make_var, default)
            } else {
                format!("[{}=...]", p.make_var)
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// Render a tool target.
fn render_tool_target(tool: &ToolInfo) -> String {
    let mut output = String::new();

    // Comment with entrypoint info
    let port_list = tool
        .entrypoints
        .iter()
        .map(|p| format!("{} ({})", p.port_name, p.type_hint))
        .collect::<Vec<_>>()
        .join(", ");
    output.push_str(&format!("# {} entrypoints: {}\n", tool.binary_name(), port_list));

    // Target with ensure-codegen dependency
    output.push_str(&format!("{}: ensure-codegen\n", tool.short_name));
    output.push_str(&format!(
        "\t@{} --{}",
        tool.invocation.command(),
        render_cli_args(&tool.entrypoints)
    ));
    output.push_str("\n\n");

    output
}

/// Render a dry-run target.
fn render_dry_run_target(tool: &ToolInfo) -> String {
    let mut output = String::new();

    output.push_str(&format!("{}-dry: ensure-codegen\n", tool.short_name));
    output.push_str(&format!(
        "\t@{} -- --dry-run{}",
        tool.invocation.command(),
        render_cli_args(&tool.entrypoints)
    ));
    output.push_str("\n\n");

    output
}

/// Render an extra composite target.
fn render_extra_target(tool: &ToolInfo, extra: &ExtraTarget) -> String {
    let mut output = String::new();

    output.push_str(&format!(
        "# {}-{}: {}\n",
        tool.short_name, extra.suffix, extra.description
    ));
    output.push_str(&format!("{}-{}: {}\n", tool.short_name, extra.suffix, tool.short_name));

    // Add post commands
    for cmd in &extra.post_commands {
        output.push_str(&format!("\t{}\n", cmd));
    }
    output.push('\n');

    output
}

/// Render CLI arguments from entrypoint parameters.
fn render_cli_args(params: &[EntrypointParam]) -> String {
    if params.is_empty() {
        return String::new();
    }

    let args: Vec<String> = params
        .iter()
        .map(|p| {
            // $(if $(VAR),--flag $(VAR))
            format!(" $(if $({}),{} $({}))", p.make_var, p.cli_flag, p.make_var)
        })
        .collect();

    args.join("")
}

