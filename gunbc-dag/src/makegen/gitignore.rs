//! Gitignore generation from repo layout.
//!
//! This module derives .gitignore patterns from the repo's `BuildConfig`,
//! following the pattern from the-gunbai:
//! - `crates/gunbai-integrations-contracts/src/understanding/gitignore.rs`
//! - `.gitignore` (section comments with provenance)
//!
//! Each `IgnoreCategory` has:
//! - `name`: Human-readable category name
//! - `source`: Which tool/concept generates these patterns
//! - `patterns`: The actual .gitignore patterns
//! - `rationale`: Why these files are ignored

use crate::makegen::registry::{BuildConfig, BuildSystem};
use crate::makegen::render::MAKEGEN_NAME;
use gunbc_ir::Renderable;

// ============================================================================
// IgnoreCategory - Pattern with provenance (from the-gunbai)
// ============================================================================

/// Category of ignore patterns with provenance.
///
/// Each category documents where the patterns come from and why they're ignored.
/// This makes the generated .gitignore self-documenting.
#[derive(Debug, Clone)]
pub struct IgnoreCategory {
    /// Human-readable category name (e.g., "Cargo build artifacts")
    pub name: &'static str,
    /// Which tool/concept generates these patterns (e.g., "cargo")
    pub source: &'static str,
    /// The actual .gitignore patterns
    pub patterns: &'static [&'static str],
    /// Why these files are ignored
    pub rationale: &'static str,
}

// ============================================================================
// Category Constants - Derived from repo layout concepts
// ============================================================================

/// Cargo build artifacts - from Language::Rust + BuildSystem::Cargo
const CARGO_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Cargo build artifacts",
    source: "cargo",
    patterns: &["/target/", "/target-codex/"],
    rationale: "Reproducible from source via cargo build",
};

/// Cargo cache - local CARGO_HOME
const CARGO_CACHE_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Cargo cache (local CARGO_HOME)",
    source: "tool/rust",
    patterns: &["/.cargo-home/"],
    rationale: "Local Cargo cache may include git checkouts; not project state",
};

/// Buck2 build artifacts - from BuildSystem::Buck2
const BUCK2_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Buck2 build artifacts",
    source: "buck2",
    patterns: &["/buck-out/"],
    rationale: "Reproducible from source via buck2 build",
};

/// Vendored dependencies - from Buck2
const BUCK2_VENDOR_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Vendored dependencies",
    source: "buck2",
    patterns: &["/third-party/rust/vendor/", "/third-party/rust/.cargo/"],
    rationale: "Reproducible from lockfile via reindeer vendor",
};

/// Coverage reports - from cargo-tarpaulin
const COVERAGE_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Coverage reports",
    source: "cargo-tarpaulin",
    patterns: &[
        "tarpaulin-report.html",
        "tarpaulin-report.json",
        "cobertura.xml",
        "lcov.info",
        "coverage/",
    ],
    rationale: "Generated, often large, reproducible",
};

/// Editor/IDE state - universal
const EDITOR_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Editor/IDE state",
    source: "editor",
    patterns: &[".idea/", ".vscode/", "*.swp", "*.swo", "*~"],
    rationale: "Per-developer configuration, not project state",
};

/// OS metadata - universal
const OS_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "OS metadata",
    source: "os",
    patterns: &[".DS_Store", "Thumbs.db"],
    rationale: "OS-generated, not project state",
};

/// Secrets and local config - universal
const SECRETS_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Secrets and local config",
    source: "secrets",
    patterns: &[".env", ".env.local", ".env.*.local"],
    rationale: "Environment-specific, may contain secrets",
};

/// Generator stamp files - from codegen system
const GENERATORS_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Generator stamp files",
    source: "generators",
    patterns: &[".*-stamp"],
    rationale: "Producer-centric model stamps; regenerated by make targets",
};

/// Generated test files - from testgen system
const TESTGEN_CATEGORY: IgnoreCategory = IgnoreCategory {
    name: "Generated test files",
    source: "testgen",
    patterns: &["**/generated_tests*.rs"],
    rationale: "Regenerated by make testgen; staleness checked by make test",
};

// ============================================================================
// Derive Categories from BuildConfig
// ============================================================================

/// Derive ignore categories from BuildConfig.
///
/// Categories are derived from `build_system` to ensure the gitignore
/// matches what's actually in the repo.
pub fn derive_categories(config: &BuildConfig) -> Vec<IgnoreCategory> {
    let mut categories = Vec::new();

    // From build_system - determines which build artifacts to ignore
    match config.build_system {
        BuildSystem::Cargo => {
            categories.push(CARGO_CATEGORY);
            categories.push(CARGO_CACHE_CATEGORY);
        }
        BuildSystem::Buck2 => {
            // Buck2 uses both cargo (for codegen) and buck2 (for build)
            categories.push(CARGO_CATEGORY);
            categories.push(CARGO_CACHE_CATEGORY);
            categories.push(BUCK2_CATEGORY);
            categories.push(BUCK2_VENDOR_CATEGORY);
        }
    }

    // Coverage is always included (cargo-tarpaulin)
    categories.push(COVERAGE_CATEGORY);

    // Universal categories (always included)
    categories.push(EDITOR_CATEGORY);
    categories.push(OS_CATEGORY);
    categories.push(SECRETS_CATEGORY);
    categories.push(GENERATORS_CATEGORY);
    categories.push(TESTGEN_CATEGORY);

    categories
}

// ============================================================================
// GitignoreRenderer - Implements Renderable trait
// ============================================================================

/// Renderer for .gitignore files.
///
/// Produces a .gitignore with section comments showing provenance,
/// following the pattern from the-gunbai.
pub struct GitignoreRenderer<'a> {
    /// Categories to render
    pub categories: Vec<IgnoreCategory>,
    /// BuildConfig reference (for metadata)
    pub config: &'a BuildConfig,
}

impl<'a> GitignoreRenderer<'a> {
    /// Create a renderer from BuildConfig.
    pub fn from_config(config: &'a BuildConfig) -> Self {
        Self {
            categories: derive_categories(config),
            config,
        }
    }

    /// Create with custom categories.
    pub fn with_categories(config: &'a BuildConfig, categories: Vec<IgnoreCategory>) -> Self {
        Self { categories, config }
    }
}

impl Renderable for GitignoreRenderer<'_> {
    fn generator_name(&self) -> &str {
        MAKEGEN_NAME
    }

    fn regenerate_command(&self) -> &str {
        "make makegen"
    }

    fn format_id(&self) -> &str {
        "gitignore"
    }

    fn render_content(&self) -> String {
        let mut output = String::new();

        // Rule comment at top
        output.push_str(
            "# Rule: Ignore anything that is (a) reproducible from committed source-of-truth\n",
        );
        output
            .push_str("# files, or (b) environment-specific and not shared across developers.\n\n");

        // Render each category with provenance
        for category in &self.categories {
            // Section header with source
            output.push_str(&format!(
                "# --- {} (from {}) ---\n",
                category.name, category.source
            ));
            // Rationale
            output.push_str(&format!("# {}\n", category.rationale));
            // Patterns
            for pattern in category.patterns {
                output.push_str(pattern);
                output.push('\n');
            }
            output.push('\n');
        }

        output
    }
}

// ============================================================================
// Public API
// ============================================================================

/// Render a .gitignore from BuildConfig.
pub fn render_gitignore(config: &BuildConfig) -> String {
    GitignoreRenderer::from_config(config).render()
}

/// Render .gitignore content only (without header).
pub fn render_gitignore_content(config: &BuildConfig) -> String {
    GitignoreRenderer::from_config(config).render_content()
}

