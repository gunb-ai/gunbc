//! DAG Visualization Tool
//!
//! Generates an interactive HTML page with Mermaid diagrams showing
//! all DAGs in the gunbc workspace.
//!
//! This is a development tool that directly writes files and opens browsers.
//! It's exempt from the transport layer requirement because it's purely for
//! developer introspection, not part of the DAG workflow.
//!
//! Uses the HTML language module from gunbc-ir for document generation.

#![allow(clippy::disallowed_methods)] // Dev tool - direct I/O is acceptable

use gunbc_dag::{
    build_bootstrap_graph, build_ci_graph, build_makegen_graph, build_workspace_dag,
};
use gunbc_ir::render_html_document;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    
    if args.iter().any(|a| a == "-h" || a == "--help") {
        println!("dag-viz - Visualize gunbc DAG structure");
        println!();
        println!("USAGE:");
        println!("    dag-viz [OPTIONS] [OUTPUT_PATH]");
        println!();
        println!("OPTIONS:");
        println!("    --no-open    Don't open browser automatically");
        println!("    -h, --help   Print this help");
        println!();
        println!("Default OUTPUT_PATH: dag-viz.html");
        return;
    }
    
    let open_browser = !args.iter().any(|a| a == "--no-open");
    let output_path = args.iter()
        .skip(1)
        .find(|a| !a.starts_with('-'))
        .map(|s| s.as_str())
        .unwrap_or("dag-viz.html");
    
    // Collect all DAGs
    let mut diagrams = Vec::new();
    
    // 1. Workspace DAG (top-level composition)
    let workspace_dag = build_workspace_dag();
    diagrams.push(("Workspace DAG", workspace_dag.to_mermaid("workspace")));
    
    // 2. Individual tool graphs (for detailed view)
    if let Ok(ci_dag) = build_ci_graph() {
        diagrams.push(("CI Pipeline", ci_dag.to_mermaid("ci")));
    }
    
    if let Ok(makegen_dag) = build_makegen_graph() {
        diagrams.push(("Makegen", makegen_dag.to_mermaid("makegen")));
    }
    
    if let Ok(bootstrap_dag) = build_bootstrap_graph() {
        diagrams.push(("Bootstrap", bootstrap_dag.to_mermaid("bootstrap")));
    }
    
    // 3. Language DAGs
    let languages_dag = gunbc_ir::build_languages_dag();
    diagrams.push(("Languages", languages_dag.to_mermaid("languages")));
    
    // Generate HTML
    let html = generate_html(&diagrams);
    
    // Write to file
    std::fs::write(output_path, &html).expect("Failed to write HTML file");
    println!("Generated: {}", output_path);
    
    // Open in browser
    if open_browser {
        #[cfg(target_os = "linux")]
        {
            let _ = std::process::Command::new("xdg-open")
                .arg(output_path)
                .spawn();
        }
        #[cfg(target_os = "macos")]
        {
            let _ = std::process::Command::new("open")
                .arg(output_path)
                .spawn();
        }
        #[cfg(target_os = "windows")]
        {
            let _ = std::process::Command::new("cmd")
                .args(["/C", "start", output_path])
                .spawn();
        }
    }
}

fn generate_html(diagrams: &[(&str, String)]) -> String {
    let mut nav_items = String::new();
    let mut diagram_sections = String::new();

    for (name, mermaid) in diagrams.iter() {
        let id = name.to_lowercase().replace(' ', "-");

        // Navigation item
        nav_items.push_str(&format!(
            "        <a href=\"#{}\" class=\"nav-item\">{}</a>\n",
            id, name
        ));

        // Diagram section
        diagram_sections.push_str(&format!(
            r#"    <section id="{id}">
        <h2>{name}</h2>
        <div class="mermaid-container">
            <pre class="mermaid">
{mermaid}
            </pre>
        </div>
    </section>
"#,
            id = id,
            name = name,
            mermaid = mermaid
        ));
    }

    let head = format!(
        r#"    <script src="https://cdn.jsdelivr.net/npm/mermaid/dist/mermaid.min.js"></script>
{}"#,
        DAG_VIZ_STYLES
    );

    let body = format!(
        r#"    <header>
        <h1>gunbc DAG Visualization</h1>
        <nav>
{nav_items}        </nav>
    </header>

    <main>
{diagram_sections}    </main>

    <footer>
        Generated by gunbc-dag-viz | <a href="https://mermaid.js.org/" style="color: #888;">Powered by Mermaid</a>
    </footer>

    <script>
        mermaid.initialize({{
            startOnLoad: true,
            theme: 'default',
            flowchart: {{
                useMaxWidth: true,
                htmlLabels: true,
                curve: 'basis'
            }}
        }});
    </script>"#,
        nav_items = nav_items,
        diagram_sections = diagram_sections
    );

    render_html_document("gunbc DAG Visualization", &head, &body)
}

