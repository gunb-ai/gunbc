#!/usr/bin/env bash
# One-shot, offline-build verification for PR #15670 (heal publisher credential-free admit).
# Runs entirely in ~/runs. Emits named markers; nothing is committed by this job.
set -uo pipefail
ROW=witty-owl-255-admit-v2
RUNS="$HOME/runs/$ROW"; SRC="$RUNS/src"; BASE="$RUNS/base"; GB="$RUNS/gunbc"
ORIGIN=https://github.com/gunb-ai/gunbc.git
HEAD_SHA="${HEAD_SHA:?HEAD_SHA must be supplied by the launcher (the PR head commit that contains this build.sh)}"
BASE_SHA=aaadb719dab68ddd9efcdb370fd3234fd13a9844
DRIVER=dag/test/claim/heal_publication_admit_wet_red.dag
WF=.github/workflows/heal-publish.yml
mkdir -p "$RUNS"; rm -rf "$SRC" "$BASE"
git init -q "$SRC" && git -C "$SRC" remote add origin "$ORIGIN"
git -C "$SRC" fetch -q --depth=1 origin "$HEAD_SHA" && git -C "$SRC" checkout -q FETCH_HEAD || { echo "CLONE_HEAD_FAILED"; exit 1; }
git init -q "$BASE" && git -C "$BASE" remote add origin "$ORIGIN"
git -C "$BASE" fetch -q --depth=1 origin "$BASE_SHA" && git -C "$BASE" checkout -q FETCH_HEAD || { echo "CLONE_BASE_FAILED"; exit 1; }
cp "$SRC/$DRIVER" "$BASE/$DRIVER" 2>/dev/null || { echo "DRIVER_COPY_FAILED"; exit 1; }
cd "$SRC"
echo "=== build gunbc @ $HEAD_SHA ==="
cargo build --release --bin gunbc 2>&1 | tail -3 || { echo "BUILD_FAILED"; exit 1; }
cp target/release/gunbc "$GB" || { echo "BUILD_COPY_FAILED"; exit 1; }
echo "GUNBC_SHA256=$(sha256sum "$GB" | awk '{print $1}')"

echo "=== [a] BASE RED: the real function aborts AuthDeclaredButUnwired (the defect) ==="
"$GB" run --function admit_did_not_reach_auth_guard --entry "$BASE" --source-root "$BASE/dag" --source-root "$BASE/src/v2" >/tmp/a.out 2>&1; echo "BASE_RED_exit=$?"
echo "BASE_RED_AuthDeclaredButUnwired=$(grep -c 'AuthDeclaredButUnwired' /tmp/a.out)"          # expect >=1: the pre-send guard fired inside observe_candidate_world_wet
echo "BASE_RED_resolve_errors=$(grep -cE 'resolve failed for' /tmp/a.out)"                     # expect 0 (a resolve error is NOT the intended RED; 'unresolved' in the auth reason is excluded)
echo "BASE_RED_HostEffectRefused=$(grep -c 'HostEffectRefused' /tmp/a.out)"                    # expect 0 (route is not refused for effects)
echo "--- base output tail ---"; tail -8 /tmp/a.out

echo "=== [b] HEAD GREEN: same controls with the same head-built binary ==="
"$GB" run --function admit_did_not_reach_auth_guard --entry "$SRC" --source-root "$SRC/dag" --source-root "$SRC/src/v2" >/tmp/b1.out 2>&1; echo "HEAD_GREEN_admit_driver_exit=$?"
echo "HEAD_GREEN_token_BaseBlobDisagreed=$(grep -c 'BaseBlobDisagreed' /tmp/b1.out)"           # expect 1: credential-free live tree reached admit's comparison
echo "HEAD_GREEN_AuthDeclaredButUnwired=$(grep -c 'AuthDeclaredButUnwired' /tmp/b1.out)"       # expect 0
echo "--- head driver output tail ---"; tail -5 /tmp/b1.out
"$GB" run --claim-run --entry dag/test/claim/heal_publication_boundary_witness.dag --source-root "$SRC/dag" --source-root "$SRC/src/v2" >/tmp/b2.out 2>&1; echo "HEAD_GREEN_boundary_witness_exit=$?"
echo "HEAD_GREEN_boundary_PASS=$(grep -c '"pass":true' /tmp/b2.out)"; echo "HEAD_GREEN_boundary_FAIL=$(grep -c '"pass":false' /tmp/b2.out)"
if [ -n "${GITHUB_TOKEN:-}" ]; then
  "$GB" run --function closed_pr_publish_control --entry "$SRC" --source-root "$SRC/dag" --source-root "$SRC/src/v2" >/tmp/b3.out 2>&1; echo "HEAD_GREEN_publish_closed_exit=$?"; tail -4 /tmp/b3.out
else
  echo "HEAD_GREEN_publish_closed_exit=SKIPPED (no job token on srv2; publish open-check stays proven by the CI-gated classifier arms)"
fi

echo "=== [c] regenerate heal-publish.yml via the instrument (NEVER hand-edit) ==="
BEFORE=$(sha256sum "$SRC/$WF" | awk '{print $1}')
"$GB" run --function main_wet_one --entry dag/gunbc/instruments/generated_artifact_gate.dag --arg "path=$WF" --source-root "$SRC/dag" --source-root "$SRC/src/v2" >/tmp/c.out 2>&1; echo "REGEN_exit=$?"
tail -8 /tmp/c.out
AFTER=$(sha256sum "$SRC/$WF" | awk '{print $1}')
echo "BEFORE_SHA256=$BEFORE"; echo "AFTER_SHA256=$AFTER"
echo "REGEN_WITNESSES_UNTOUCHED=$( [ "$BEFORE" != "$AFTER" ] && git -C "$SRC" status --porcelain witnesses.yml | grep -q . && echo NO || echo YES )"
echo "--- REGEN_DIFF (expected: ONLY the admit 'GITHUB_TOKEN: \${{ github.token }}' line) ---"
git -C "$SRC" --no-pager diff -- "$WF"
echo "REGEN_CHANGED_FILES=$(git -C "$SRC" status --porcelain | awk '{print $2}' | tr '\n' ',')"
# Emit the regenerated bytes so the maintainer commits the generator's output, never a hand-edit.
echo "HEAL_PUBLISH_B64_BEGIN=$(base64 -w0 "$SRC/$WF")_END"
echo "REGEN_DONE"
